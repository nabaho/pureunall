var 번호꼴 = /^\s*(?:\d{1,2}\s*[.)]|[ⅠⅡⅢⅣⅤⅥⅦⅧⅨⅩ]+\s*[.)]?|[①-⑩]|[가-하]\s*[.)]|[-·•▪◈]\s*)\s*(.+)$/;
