function _두자(n) { return (n < 10 ? "0" : "") + n; }

/* 「2026.09.17」·「2026. 9. 11.」·「9.29」·「5/18」을 다 읽는다.
   ⚠ 해가 없으면 «그 덩이에 적힌 해»를, 그것도 없으면 오늘 해를 쓴다. */
function _날들(글, 바탕해) {
  var out = [];
  /* ⚠ 「8. 21.(금)」처럼 날 뒤에 «점이 하나 더» 붙는 곳이 많다(지자체 꼴).
       뒤를 [.\-/] 로 막아 두었더니 그런 날을 통째로 못 읽어,
       「8.12 ~ 8.21」에서 앞것만 집고 마감을 이틀 이르게 봤다(실측 2026-09-13).
     ★ 막을 것은 «점»이 아니라 «또 다른 숫자»다. */
  var re = /(20\d{2})\s*[.\-/]\s*(\d{1,2})\s*[.\-/]\s*(\d{1,2})(?!\s*\d)|(?:^|[^\d])(\d{1,2})\s*[.\-/]\s*(\d{1,2})(?!\s*\d)/g;
  var m;
  while ((m = re.exec(글))) {
    var y, mo, d;
    if (m[1]) { y = +m[1]; mo = +m[2]; d = +m[3]; }
    else { y = 바탕해; mo = +m[4]; d = +m[5]; }
    if (!(mo >= 1 && mo <= 12 && d >= 1 && d <= 31)) continue;
    out.push(y + "-" + _두자(mo) + "-" + _두자(d));
  }
  return out;
}

/* 마감일 하나를 돌려준다. 못 읽으면 «빈 글자» — 지어내지 않는다. */
