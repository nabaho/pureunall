'use strict';

/* ══════════════════════════════════════════════════════════════════════════
   회차 발송 잠금 — «같은 회차가 두 번 나가는 것»만 막는다
   ══════════════════════════════════════════════════════════════════════════
   화면의 App.보내는중 은 «그 PC 안»에서만 산다. 관리자가 둘이면 각자의 화면이
   각자 「보내는 중」을 들고 있어 서로를 못 본다 — 두 관리자가 같은 순간에 누르면
   119곳이 편지를 두 통 받는다.

   ★ 그래서 잠금은 «두 사람이 반드시 만나는 곳»인 서버에 하나만 둔다.
     화면에 잠금을 하나 더 두면 두 벌이 되고, 두 벌은 서로 어긋난다.

   ★★ 왜 판단을 이 파일로 뺐나 — 거래(transaction) 안에 묻어 두면 «글자가 있나»
     말고는 검사할 길이 없다. 여기로 빼면 두 사람이 같은 순간에 누른 상황을
     검사가 실제로 만들어 볼 수 있다.

   ⚠⚠ «찬 자리»에서 접히지 않아야 한다 — 파이어베이스 거래는 지금 손안에 있는
     값으로 «먼저 한 번» 부른다. 그 자리를 듣고 있지 않으면 그 값이 null 이다.
     거기서 아무것도 안 돌려주면(undefined) 서버에 물어보지도 않고 끝난다.
     그래서 잠글까(null,…) 는 «잠근다»고 답한다 — 진짜 서버 값이 다르면
     파이어베이스가 그 값으로 한 번 더 부르고, 그때 제대로 접는다.
     (같은 덫을 저장소가 이미 한 번 밟았다: 지역뉴스 등록은 그래서 거래 앞에
      once('value') 를 붙여 두었다.)                                          */

/* 서버가 죽어 «거는중»인 채 남았을 때 풀리는 한도.
   서버 한 번 실행이 2분이라 15분이면 넉넉하고, 사람이 다시 누를 만한 길이다. */
const 살아있는한도 = 15 * 60 * 1000;

/* 잠글 수 있으면 «새 잠금»을, 못 잠그면 null 을 준다.
   ⚠ 거래에서 null 을 돌려주면 «그 자리를 지워라»는 뜻이 된다 — 부르는 쪽이
     반드시 undefined 로 바꿔서 접어야 한다. */
function 잠글까(지금잠금, 요청열쇠, 지금, 요청한이) {
  const 열쇠 = String(요청열쇠 == null ? '' : 요청열쇠).trim();
  if (!열쇠) return null;
  const 옛 = (지금잠금 && typeof 지금잠금 === 'object') ? 지금잠금 : null;
  if (옛) {
    /* 이미 보낸 회차는 누가 눌러도 다시 안 나간다 */
    if (옛.상태 === '완료') return null;
    const 잡은때 = Number(옛.서버시작때 || 옛.요청한때 || 0);
    const 살아있음 = 옛.상태 === '거는중' && (지금 - 잡은때) < 살아있는한도;
    /* 같은 요청번호면 «내가 다시 물은 것»이라 통과시킨다(그물이 끊겨 다시 부른 경우) */
    if (살아있음 && String(옛.요청열쇠 || '') !== 열쇠) return null;
  }
  return {
    상태: '거는중',
    요청열쇠: 열쇠,
    요청한이: String(요청한이 == null ? '' : 요청한이),
    요청한때: (옛 && String(옛.요청열쇠 || '') === 열쇠 && Number(옛.요청한때)) || 지금,
    서버시작때: 지금,
  };
}

/* 대기열까지 다 만든 뒤 — 이 회차는 끝났다 */
function 마쳤다(잠금, 지금, batchId) {
  return Object.assign({}, 잠금 || {}, {
    상태: '완료', 완료때: 지금, batchId: String(batchId == null ? '' : batchId),
  });
}

/* 걸다가 터졌다 — 「거는중」인 채 두면 15분을 기다려야 다시 누를 수 있다 */
function 틀어졌다(잠금, 지금, 까닭) {
  return Object.assign({}, 잠금 || {}, {
    상태: '오류', 오류때: 지금, 오류: String(까닭 == null ? '' : 까닭).slice(0, 300),
  });
}

/* 「내가 아까 건 그 요청이 이미 끝났나」 — 그물이 끊겨 화면이 다시 물을 때,
   두 번 보내는 대신 «그때 그 결과»를 그대로 돌려주기 위한 잣대다. */
function 이미마친내요청인가(잠금, 요청열쇠) {
  const 열쇠 = String(요청열쇠 == null ? '' : 요청열쇠).trim();
  if (!열쇠 || !잠금 || typeof 잠금 !== 'object') return false;
  return 잠금.상태 === '완료' && String(잠금.요청열쇠 || '') === 열쇠;
}

module.exports = { 잠글까, 마쳤다, 틀어졌다, 이미마친내요청인가, 살아있는한도 };
