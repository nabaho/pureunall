/* 뉴스레터 «⭐ 핵심» 편집 화면 — pu-news.html (대표 지시 2026-10-13)
   ═══════════════════════════════════════════════════════════════════════
   진짜 Edge 로 «후보 뽑기 → 쓰기 → 고치기 → 미리보기·요약 반영 → 3장 한도 → 폰 폭»을 한 번 돌려 보았다(2026-10-13).
   이 검사는 그때 확인한 것 가운데 «어긋나면 조용히 사고가 나는 규칙»을 못 박는다 — 브라우저 없이 돈다.

   ■ 지키는 것
     ㉠ ★ 저장이 «칸을 하나씩 적는 목록»이다 — 핵심·핵심후보가 거기 없으면 카드가 저장되지 않는다(새로 고치면 사라진다)
     ㉡ ★ 서버(금요일 자동 준비)가 회차를 쓸 때 «핵심 칸을 지우지 않는다» — set 이 아니라 update 다
     ㉢ ★★ AI 는 «후보»(핵심후보)에만 쓴다. 나가는 카드(핵심)에 직접 쓰지 못한다 — 사람이 «쓰기»를 눌러야 편지에 실린다
     ㉣ 보낸 회차는 못 고친다 · 카드는 3장까지 · 칸 글자 한도는 Core 의 것을 쓴다
     ㉤ 쓰는 중에 다시 그려도 커서·굴림이 산다(안 지키면 한 칸 칠 때마다 커서가 사라진다)
     ㉥ 핵심판일 때 «전문판 전용 경고»(한마디 비어 있음 따위)는 걷는다 — 편지에 안 나가는 것을 고치라고 하지 않는다 */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { 주석걷기, 함수몸 } = require('./helpers/strip-comments.js');

const 뿌리 = path.join(__dirname, '..');
const 원문 = fs.readFileSync(path.join(뿌리, 'pu-news.html'), 'utf8');
const 화면 = 주석걷기(원문);
const 서버 = 주석걷기(fs.readFileSync(path.join(뿌리, 'functions', 'news-friday.js'), 'utf8'));

const 몸 = (이름) => {
  const b = 함수몸(화면, 이름);
  assert.ok(b, 이름 + ' 을(를) 못 찾았다');
  return b;
};

test('★★★ 저장 목록에 «핵심»·«핵심후보»가 있다 — 없으면 카드가 저장되지 않는다', () => {
  const b = 몸('회차저장');
  assert.match(b, /핵심\s*:\s*자료\.핵심/, '회차저장이 핵심을 안 적는다 — 카드를 만들어도 새로 고치면 사라진다');
  assert.match(b, /핵심후보\s*:\s*자료\.핵심후보/, '회차저장이 핵심후보를 안 적는다 — AI 후보가 새로 고치면 사라진다');
});

test('★★★ 서버가 회차를 쓸 때 «핵심 칸»을 지우지 않는다 — 칸을 골라 update 한다(set 이 아니다)', () => {
  const b = 함수몸(서버, '회차쓰기');
  assert.ok(b, 'news-friday.js 의 회차쓰기 를 못 찾았다');
  assert.match(b, /\.update\(\{/, '서버 회차 쓰기가 update 가 아니다');
  assert.ok(!/\.set\(/.test(b), '★★ 서버 회차 쓰기가 set 을 쓴다 — 금요일 자동 준비가 대표님이 만든 핵심 카드를 통째로 지운다');
  assert.ok(!/핵심/.test(b), '서버가 핵심 칸을 건드린다 — 화면만 쓰는 칸이다(서버는 읽기만)');
});

test('★★★ AI 는 «후보»에만 쓴다 — 나가는 카드(핵심)에 직접 쓰지 못한다', () => {
  const b = 몸('핵심후보뽑기');
  assert.match(b, /\.핵심후보\s*=/, 'AI 결과가 핵심후보에 안 담긴다');
  assert.ok(!/\.핵심\s*=[^=]/.test(b), '★★ AI 결과가 «나가는 카드»에 곧바로 들어간다 — 사람이 안 읽은 법률 문장이 대량 발송된다');
  assert.match(b, /Core\.핵심후보지시\(/, '후보 지시를 Core 한 곳에서 안 가져온다');
  assert.match(b, /Core\.핵심후보받기\(/, '★ AI 답을 «Core.핵심후보받기»로 안 거른다 — 날짜 지어내기·주소 지어내기 막이가 빠진다');
  assert.ok(!/JSON\.parse/.test(b), 'AI 답을 화면에서 날것으로 읽는다 — 거르는 곳은 Core 한 곳이어야 한다');
});

test('★★ 후보를 카드로 올리는 길은 «사람이 누르는 단추» 하나다', () => {
  const 쓰기 = 몸('핵심후보쓰기');
  assert.match(쓰기, /\.핵심\s*=/, '쓰기가 카드에 안 넣는다');
  /* 후보쓰기 를 부르는 곳이 단추 onclick 뿐이어야 한다 — 다른 함수가 자동으로 부르면 «사람이 확인»이 사라진다 */
  const 부름 = 화면.match(/핵심후보쓰기\(/g) || [];
  const 정의 = 1;
  const 단추 = (화면.match(/onclick="핵심후보쓰기\(/g) || []).length;
  assert.strictEqual(부름.length, 정의 + 단추, '핵심후보쓰기 를 단추 말고 다른 코드가 부른다 — AI 후보가 사람 확인 없이 카드가 된다');
});

test('보낸 회차는 못 고친다 — 고치는 길 전부가 «발송»을 본다 · 칸도 잠근다', () => {
  ['핵심바뀜', '핵심곧저장', '핵심후보뽑기'].forEach((이름) => {
    assert.match(몸(이름), /'발송'/, 이름 + ' 이 보낸 회차를 안 막는다 — 이미 나간 편지의 카드가 바뀐다');
  });
  const 화면몸 = 몸('핵심판화면');
  assert.match(화면몸, /잠김\s*=\s*d\.상태\s*===\s*'발송'/, '화면이 보낸 회차를 잠그지 않는다');
  assert.ok((화면몸.match(/\$\{막\}/g) || []).length >= 4, '입력칸들이 잠기지 않는다');
});

test('카드는 «3장까지» — 더하기·후보 쓰기 둘 다 Core 의 한도를 본다 · 칸 글자 한도도 Core 것', () => {
  assert.match(몸('핵심더하기'), /Core\.핵심한도/, '카드 더하기가 한도를 안 본다');
  assert.match(몸('핵심후보쓰기'), /Core\.핵심한도/, '후보 쓰기가 한도를 안 본다 — 4장째가 들어간다');
  const 화면몸 = 몸('핵심판화면');
  assert.match(화면몸, /Core\.핵심칸한도/, '칸 글자 한도를 Core 에서 안 가져온다(숫자를 화면에 따로 적었다)');
  /* 글자칸은 도우미(글자) 하나가 maxlength 를 달고, 설명(textarea)이 따로 단다 — 둘 다 있어야 한다 */
  assert.ok((화면몸.match(/maxlength="\$\{/g) || []).length >= 2, '입력칸에 maxlength 가 없다 — 편지 쪽이 잘라 버려 「쓴 것과 나간 것이 다르다」');
});

test('★ 핵심판켜짐 은 편지 짓는 층과 «같은 잣대»다 — 카드가 있고 · 갈 곳(추적 밑주소)이 있다', () => {
  const b = 몸('핵심판켜짐');
  assert.match(b, /Core\.핵심있나\(/);
  assert.match(b, /추적밑주소/, '갈 곳(추적 밑주소) 조건이 빠졌다 — 화면은 「핵심판」이라는데 편지는 전문판이 나간다');
});

test('★★ 쓰는 중에 다시 그려도 «커서와 굴림»이 산다', () => {
  const b = 몸('핵심그리기');
  assert.match(b, /activeElement/, '치던 칸을 기억하지 않는다 — 700ms 저장 뒤마다 커서가 사라진다');
  assert.match(b, /\ba\.id\b/, '치던 칸의 «번호(id)»를 읽지 않는다 — 기억해도 되찾을 열쇠가 없다');
  assert.match(b, /getElementById\(id\)[\s\S]*\.focus\(\)/, '다시 그린 뒤 치던 칸을 되찾아 focus 하지 않는다');
  assert.match(b, /setSelectionRange/, '커서 위치를 되돌리지 않는다');
  assert.match(b, /scrollTop/, '굴림 위치를 지키지 않는다 — 저장될 때마다 왼쪽 칸이 맨 위로 튄다');
  assert.match(몸('핵심바뀜'), /핵심그리기/, '글을 치고 저장된 뒤 핵심그리기 로 안 그린다(그냥 render 면 커서가 사라진다)');
});

test('새 저장은 모두 «회차저장»을 지난다 — 판(버전) 올리기를 건너뛰는 직접 쓰기가 없다', () => {
  ['핵심바뀜', '핵심곧저장', '핵심후보뽑기', '핵심후보쓰기', '핵심후보지우기', '핵심더하기', '핵심빼기', '핵심옮기기', '핵심건고르기'].forEach((이름) => {
    assert.ok(!/db\.ref\(/.test(몸(이름)), 이름 + ' 이 db.ref 로 직접 쓴다 — 동시에 고친 것을 덮는다(판 올리기를 건너뛴다)');
  });
  assert.match(몸('핵심곧저장'), /회차저장\(/);
  assert.match(몸('핵심바뀜'), /회차저장\(/);
});

test('핵심판일 때 «전문판 전용 경고»는 걷힌다 — 편지에 안 나가는 한마디·해석·기사 우리 말을 고치라고 하지 않는다', () => {
  const b = 몸('편지요약');
  assert.match(b, /const 핵심켬\s*=\s*핵심판켜짐\(d\)/, '핵심판 여부를 못 읽는다');
  assert.ok((b.match(/!핵심켬\s*&&/g) || []).length >= 3, '전문판 전용 경고(우리 글 비어 있음·해석 밀림·기사 우리 말)가 핵심판에서도 뜬다');
  assert.match(b, /나가는 판/, '요약에 «나가는 판» 줄이 없다 — 지금 무엇이 나가는지 한눈에 모른다');
});

test('탭과 칸이 이어져 있다 — 「⭐ 핵심」 탭이 핵심 칸을 연다', () => {
  assert.match(화면, /onclick="길바꾸기\('core'\)"/, '핵심 탭 단추가 없다');
  assert.match(화면, /App\.길==='core'\s*\?\s*핵심판화면\(d\)/, '핵심 탭이 칸을 안 그린다');
});
