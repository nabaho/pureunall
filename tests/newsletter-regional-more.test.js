"use strict";
/* 지역 출처를 «값이 있는 쪽»으로 넓힌다 — 경기 관서 · 괄호 낀 관서 살림 거르기
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-13: 「추천대로 해라」

   ⚠ 앞서 「지자체 셋(충청남도·서산시·천안시)도 읽게 하려면 공식링크 잣대를 넓혀야
     한다」고 말씀드렸다. 그런데 셋을 실제로 열어 보고 추천을 «바꿨다»(실측 2026-09-13):
       · 충청남도 보도자료 — 목록이 「조회 데이터가 없습니다」로 «비어서» 온다
       · 천안시           — 404
       · 서산시 기업지원   — 살아 있으나 글이 «2건»뿐
     잣대를 넓히는 값은 치르는데 들어올 것이 거의 없다. 넓히지 «않는다».

   ★ 대신 이미 통하는 길(지방고용노동관서 게시판)을 넓힌다 — 받는 곳이 정한 대로:
     경기 10곳(평택 5 · 용인 2 · 오산 1 · 안성 1 · 안양 1) → 평택지청.
     실측 평택지청: 글 10건 가운데 쓸 것 4건 —
       외국인근로자 신규 고용허가 신청 · 대량 고용변동 신고제도 ·
       폭염중대경보 작업중지 이행계획서 · 건설업 자율안전관리컨설팅.

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ① 관서 살림 공고는 «괄호 안 직명»이 끼어도 걸러진다
     ② 경기 받는 곳에 닿는 출처가 있다
     ③ 넓힌 잣대가 «남의 집»까지 열어 주지 않는다

   ⚠ 인터넷을 두드리지 않는다. */

const test = require("node:test");
const assert = require("node:assert");
const R = require("../functions/news-region.js");
const C = require("../js/pu-news-core.js");
const Sources = require("../js/pu-news-regional-sources.js");

/* ══════════════════════════════════════════════════════════════════════════
   ① 괄호 낀 관서 살림 — 「기간제근로자(통계조사관) 채용 공고」
   ══════════════════════════════════════════════════════════════════════════ */

test("★★ 괄호 안에 직명이 끼어도 관서 채용 공고는 걸러진다", () => {
  /* ⚠ 제외말에 「기간제근로자 채용」이 있는데도 새어 들어오고 있었다(실측 2026-09-13).
       사이에 (통계조사관)·(직업상담원 대체인력)이 끼어 글자가 안 맞았다.
     ★ 값(어느 직명인가)이 아니라 «괄호를 걷어 내고 본다»는 규칙을 못 박는다. */
  assert.equal(R.쓸모있는가("[공고] [제2026-183호]대전지방고용노동청 기간제근로자(통계조사관) 채용 공고"),
    false, "★★ 관서 채용 공고가 뉴스레터 후보로 올라온다");
  assert.equal(R.쓸모있는가("[공고] 경기지방고용노동청안양지청 기간제근로자(직업상담원 대체인력) 채용 공고"),
    false, "★★ 괄호 안이 길어지면 또 새어 든다");
});

test("괄호를 걷어 내도 «쓸 것»은 그대로 남는다 — 넓혀 놓고 다 잡으면 안 된다", () => {
  [
    "[공고] 2026년 4회차 외국인근로자 신규 고용허가 신청 안내",
    "[안내] 대량 고용변동 신고제도 안내",
    "[안내] (50억 이상 건설현장) 폭염중대경보 발령 시 작업중지 이행계획서 제출 요청",
    "[안내] '26년 하반기 건설업 자율안전관리컨설팅 신청 안내",
  ].forEach((t) => assert.equal(R.쓸모있는가(t), true, "쓸 것을 걸렀다: " + t));
});

/* ══════════════════════════════════════════════════════════════════════════
   ② 경기 받는 곳에 닿는 출처
   ══════════════════════════════════════════════════════════════════════════ */

test("★ 경기 사업장에 닿는 «지역» 출처가 있다", () => {
  /* ⚠ 실측 2026-09-13 받는 곳: 경기 10곳(평택 5·용인 2·오산 1·안성 1·안양 1).
       그 전에는 경기 사업장이 받을 지역 소식이 «하나도» 없었다. */
  const 경기것 = R.출처들.filter((x) => String(x.지역 || "") !== "전국"
    && C.지역뉴스고르기([{ 지역: x.지역, 상태: "승인" }],
      C.지역코드("경기도 평택시 어딘가")).length > 0);
  assert.ok(경기것.length >= 1, "★ 경기에 닿는 지역 출처가 없다");
});

test("경기 출처가 «충남»까지 넘어오지 않는다 — 지역을 가르는 뜻이 없어진다", () => {
  const 평택 = R.출처들.find((x) => x.id === "moel-pyeongtaek");
  assert.ok(평택, "평택지청 출처가 없다");
  assert.equal(C.지역뉴스고르기([{ 지역: 평택.지역, 상태: "승인" }],
    C.지역코드("충남 천안시 어딘가")).length, 0, "경기 소식이 천안까지 간다");
});

/* ══════════════════════════════════════════════════════════════════════════
   ③ 잣대를 «넓히지 않았다» — 남의 집을 열어 주면 안 된다
   ══════════════════════════════════════════════════════════════════════════ */

test("★★★ 공식링크 잣대는 여전히 «고용노동부»만 연다", () => {
  /* ⚠⚠ 지자체를 읽으려고 go.kr 을 통째로 열면, 링크 하나 잘못 긁어도
       엉뚱한 기관 글이 우리 법인 이름으로 114곳에 나간다.
     ★ 지자체 셋이 사실상 비어 있어(충남 0건 · 천안시 404 · 서산시 2건)
       그 값을 치를 까닭이 없다 — 실측 2026-09-13. */
  assert.equal(R.공식링크인가("https://www.moel.go.kr/local/pyeongtaek/news/notice/noticeView.do?bbs_seq=1"),
    true, "고용노동부 링크를 막는다");
  assert.equal(R.공식링크인가("https://www.chungnam.go.kr/cnportal/bbs/B0000417/view.do?nttId=1"),
    false, "★★★ 잣대가 지자체까지 열렸다 — 검증하지 않은 집이다");
  assert.equal(R.공식링크인가("https://moel.go.kr.example.com/x"),
    false, "★★★ 이름만 흉내 낸 집이 지나간다");
});

test("서버가 읽는 출처는 모두 화면 등록부에도 있다", () => {
  const 화면것 = new Map(Sources.목록.map((x) => [x.id, x.목록주소]));
  R.출처들.forEach((s) => {
    assert.equal(화면것.get(s.id), s.목록주소,
      "화면 등록부에 없거나 주소가 다르다: " + s.id);
  });
});
