"use strict";
/* 등록부의 주소는 «살아 있어야» 하고, 살핌은 «재어 본 것»이어야 한다
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-13: 「주소 찾아라」

   ⚠ 천안시 주소가 404 인 채로 등록부에 앉아 있었다. 죽은 주소를 적어 두면
     다음에 여는 사람이 「아직 안 만들었나 보다」로 읽고 같은 길을 다시 걷는다.
   ★ 새 주소를 찾아 갈아 끼웠다(200). 그런데 «담을 것이 없다» —
     천안시 판은 자금·판로 지원과 지자체 행정뿐이고 노무 관련이 0건이다.
     노무는 천안지청 몫이고 우리는 이미 읽고 있다(moel-cheonan).

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ① 서버가 «안 읽는» 출처에는 왜 안 읽는지가 «살핌»으로 적혀 있다
     ② 옛 죽은 주소가 되살아나지 않는다
     ③ 지자체 판을 읽었다면 관련말이 엉뚱한 것을 잡았을 것이다 — 그 증거를 남긴다

   ⚠ 인터넷을 두드리지 않는다. */

const test = require("node:test");
const assert = require("node:assert");
const R = require("../functions/news-region.js");
const Sources = require("../js/pu-news-regional-sources.js");

const 읽는것 = () => new Set(R.출처들.map((x) => x.id));

test("★ 서버가 «안 읽는» 출처마다 그 까닭이 적혀 있다", () => {
  /* ⚠ 적어 두지 않으면 다음에 여는 사람이 「읽개만 만들면 되겠네」로 시작한다.
       실제로는 열어 보고 «담을 것이 없어서» 안 만든 것이다. */
  const 서버 = 읽는것();
  const 안읽는것 = Sources.목록.filter((x) => !서버.has(x.id));
  assert.ok(안읽는것.length >= 1, "안 읽는 출처가 하나도 없다 — 검사가 헛돈다");
  안읽는것.forEach((x) => {
    assert.ok(String(x.살핌 || "").trim(),
      "★ 왜 안 읽는지 적혀 있지 않다: " + x.id);
    assert.ok(/\d{4}-\d{2}-\d{2}/.test(String(x.살핌)),
      "언제 재어 본 것인지 없다: " + x.id);
  });
});

test("★★ 죽은 주소가 등록부에 남아 있지 않다", () => {
  /* ⚠⚠ 실측 2026-09-13 에 404 였던 천안시 주소. 되살아나면 여기서 걸린다. */
  const 죽은것 = "/prog/ioCateData/kor/sub03_01_02/list.do";
  Sources.목록.forEach((x) => {
    assert.ok(String(x.목록주소 || "").indexOf(죽은것) < 0,
      "★★ 404 로 확인된 옛 주소가 되돌아왔다: " + x.id);
  });
  const 천안시 = Sources.목록.find((x) => x.id === "cheonan-company");
  assert.ok(천안시, "천안시 자리가 없어졌다");
  assert.ok(/^https:\/\/www\.cheonan\.go\.kr\/bbs\/BBSMSTR_/.test(천안시.목록주소),
    "새로 찾은 주소가 아니다: " + 천안시.목록주소);
});

test("★★★ 지자체 «행정»은 안 담는다 — 넓힌 것은 집이지 잣대가 아니다", () => {
  /* ⚠⚠ 이 검사는 오늘 «두 번» 뜻이 바뀐 자리다. 그 내력을 적어 둔다.
       ① 처음: 「지자체는 아예 안 읽는다」. 셋을 열어 보니 비어 있거나 404 였고,
          읽으려면 공식링크 잣대를 go.kr 로 넓혀야 해서 값이 안 맞았다.
       ② 그 뒤 대표 지시 「꼭지를 넓히는 일(노무 → 노무+기업지원) 이것도 같이해라」로
          천안시 기업지원을 읽게 되었다.
     ★ 그래도 잣대를 go.kr 로 넓히지는 «않았다». 넓힌 것은 «등록한 집»뿐이다 —
       새 집을 들이려면 등록부에 적어야 하니 저절로 검토를 거친다.
     ★ 그리고 지자체 판에서 새어 들던 것(과태료 체납 공시송달·의료법 행정처분)은
       지자체행정말로 «잘라 냈다». 그것이 이 검사가 지금 지키는 것이다. */
  assert.equal(R.쓸모있는가("「식품위생법」위반 과태료 체납에 따른 납부 독촉 공시송달 공고"),
    false, "★★★ 지자체 행정이 검토함으로 들어온다");
  assert.equal(R.쓸모있는가("의료법 위반에 따른 행정처분(의료기관 폐쇄) 공시송달 공고"),
    false, "★★★ 지자체 행정이 검토함으로 들어온다");
  /* ★ 서버가 읽는 집은 «등록부에 적힌 것»뿐이다 — 아무 go.kr 이나가 아니다 */
  const 아는집 = new Set(Sources.목록.map((x) => {
    try { return new URL(x.목록주소).hostname.toLowerCase(); } catch (_) { return ""; }
  }));
  R.출처들.forEach((s) => {
    assert.ok(아는집.has(new URL(s.목록주소).hostname.toLowerCase()),
      "★★★ 등록부에 없는 집을 서버가 읽는다: " + s.목록주소);
  });
  assert.equal(R.공식링크인가("https://www.korea.kr/news/x.do"), false,
    "★★★ 잣대가 go.kr 로 통째로 넓어졌다");
});

test("천안시 노무 소식은 «천안지청»이 맡는다 — 빈 채로 두지 않았다", () => {
  const 지청 = R.출처들.find((x) => x.id === "moel-cheonan");
  assert.ok(지청, "천안지청 출처가 없다");
  assert.equal(지청.지역, "충남", "천안 사업장에 닿지 않는 지역 딱지다");
});
