/* 월요일 뉴스레터 «몇 시에 나가나» — 서버·검토 메일·화면·사용액 창이 같은 시각을 말한다
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-27 「월요일 6시 자동발송으로 바꿔달라」 (전에는 8시)

   ■ 왜 이 검사가 있나
     「오전 8시」가 «다섯 군데»에 따로 적혀 있었다 — 서버 예약 한 곳, 검토 메일 네 곳,
     관리 화면 세 곳, 사용액 창 한 곳. 서버만 6시로 바꾸면, 금요일 검토 메일은 여전히
     「오전 8시에 나갑니다」라고 하고 실제로는 6시에 나간다. 대표님은 그 메일을 보고
     「8시 전에 고치면 된다」고 두셨다가 이미 나간 뒤에 고치시게 된다.
   ★ 값(6시)을 못 박지 않는다 — 서버 예약에서 «읽어서» 나머지와 견준다.
     다음에 또 바꾸면 서버만 고치고 이 검사가 나머지를 짚어 준다.

   ■ 법 (2026-09-27 법제처 원문 확인)
     정보통신망법 제50조제3항: 오후 9시~오전 8시 광고성 정보 전송은 별도 사전 동의.
     시행령 제61조제2항: 그 단서의 «대통령령으로 정하는 매체»는 «전자우편».
     → 메일은 새벽 발송 제한에서 빠진다. 문자·카톡으로 바꾸면 이 시각은 안 된다. */

'use strict';

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const 읽기 = (p) => fs.readFileSync(path.join(ROOT, p), 'utf8');
const 서버 = 읽기('functions/index.js');
const 화면 = 읽기('pu-news.html');
const 문 = 읽기('enter.html');
const NF = require('../functions/news-friday.js');

/* 서버 예약에서 «몇 시»를 읽는다 — 이것이 기준이다 */
function 보내는시() {
  const i = 서버.indexOf('exports.weeklyNewsletterSend');
  assert.ok(i >= 0, 'weeklyNewsletterSend 를 못 찾았다');
  const j = 서버.indexOf('\nexports.', i + 10);
  const 몸 = 서버.slice(i, j > i ? j : 서버.length);
  const m = /\.pubsub\.schedule\(["']every monday (\d{1,2}):(\d{2})["']\)/.exec(몸);
  assert.ok(m, '월요일 예약을 못 읽었다 — 꼴이 바뀌었으면 이 검사를 고쳐야 한다');
  assert.match(몸, /\.timeZone\(["']Asia\/Seoul["']\)/, '★★ 서울 시각이 아니다 — 아홉 시간 어긋난다');
  return { 시: Number(m[1]), 분: Number(m[2]) };
}
const 말로 = (시) => (시 < 12 ? '오전 ' + 시 + '시' : '오후 ' + (시 === 12 ? 12 : 시 - 12) + '시');

test('★★★ 검토 메일이 «서버가 실제로 보내는 시각»을 말한다', () => {
  const { 시 } = 보내는시();
  assert.strictEqual(NF.보내는시각말, 말로(시),
    '★★★ 서버는 ' + 말로(시) + '에 보내는데 금요일 검토 메일은 「' + NF.보내는시각말
      + '」라고 한다 — 대표님이 그 시각 전에 고치면 된다고 두셨다가 이미 나간 뒤가 된다');
  /* 실제로 지어 본 메일에도 그 시각이 찍혀 있어야 한다(상수만 맞고 안 쓰면 헛일) */
  const 메일 = NF.검토메일짓기({ 회차: { 이름: '2026년 10월 1주' }, 열쇠: '2026-10-w1',
    보낼날: '2026-10-05', 확정본됨: true, 자동발송켜짐: true, 받는수: 143,
    실림: { 표: {} }, 알림들: [], 편지서식: '' });
  assert.ok(메일.subject.indexOf(말로(시)) >= 0, '★★★ 검토 메일 제목의 시각이 서버와 다르다: ' + 메일.subject);
  assert.ok(메일.html.indexOf(말로(시)) >= 0, '★★ 검토 메일 본문의 시각이 서버와 다르다');
});

test('★★★ 관리 화면이 «서버가 실제로 보내는 시각»을 말한다', () => {
  const { 시 } = 보내는시();
  const 맞는말 = '월요일 ' + 말로(시) + ' 자동발송';
  assert.ok(화면.indexOf(맞는말) >= 0, '★★★ 설정 화면에 「' + 맞는말 + '」이 없다');
  /* 옛 시각이 한 군데라도 남아 있으면 안 된다 — 설정·확인창·경고가 서로 다른 시각을 말한다 */
  const 다른시각 = [...화면.matchAll(/월요일 오전 (\d{1,2})시 자동발송/g)].map((x) => Number(x[1]))
    .filter((h) => h !== 시);
  assert.deepStrictEqual(다른시각, [],
    '★★★ 화면에 옛 시각(' + 다른시각.join(', ') + '시)이 남아 있다 — 서버는 ' + 시 + '시에 보낸다');
});

test('★★ 사용액 창이 «서버가 실제로 도는 시각»을 말한다', () => {
  /* 대표께서 「새벽마다 금액이 올라가는데 무엇이 도는지」를 보시는 곳이다 —
     시각이 틀리면 그 시각에 오른 돈을 엉뚱한 것 탓으로 돌리신다. */
  const { 시, 분 } = 보내는시();
  const 시각 = 시 + ':' + String(분).padStart(2, '0');
  assert.ok(new RegExp('거래처 뉴스레터 월요일 한 번\\((새벽|아침|오전) ' + 시각 + '\\)').test(문),
    '★★ 사용액 창의 뉴스레터 시각이 서버(' + 시각 + ')와 다르다');
});

test('★ 메일로만 새벽에 보낸다 — 법(정보통신망법 제50조제3항 · 시행령 제61조제2항)', () => {
  /* 새벽(오후 9시~오전 8시) 광고성 정보는 «전자우편»만 별도 동의 없이 된다.
     이 함수가 메일 대기열(sendBulkMail 과 같은 길)에 거는지 — 문자로 바뀌면 이 검사를 다시 보라. */
  const { 시 } = 보내는시();
  if (시 >= 8 && 시 < 21) return;              /* 낮이면 따질 것이 없다 */
  const i = 서버.indexOf('exports.weeklyNewsletterSend');
  const j = 서버.indexOf('\nexports.', i + 10);
  const 몸 = 서버.slice(i, j > i ? j : 서버.length);
  assert.ok(!/sms|문자|kakao|알림톡/i.test(몸.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\/\/.*$/gm, '')),
    '★ 새벽 발송인데 문자·카톡 길이 섞였다 — 전자우편만 새벽 제한에서 빠진다');
});
