/* 주간 뉴스레터 — 사람이 쓴 { } 가 발송기를 지나도 «살아 있다»
   ═══════════════════════════════════════════════════════════════════════════
   ⚠⚠ 대량 발송기(functions/mail-bulk.js fill)는 {무엇} 꼴을 «모두» 자리로 읽고,
     모르는 이름은 «빈 글자»로 바꾼다. 그래서 대표님이 우리글·인사말·판례 제목에
     「{주의}」라고 쓰시면 그 글자가 받는 분 편지에서 «조용히» 사라진다.
   ⚠⚠ 시험 발송은 즉시 길이라 fill 을 안 지난다 — 시험에서는 멀쩡해 보인다.
     그래서 아무도 모른다. 이 검사는 «발송기를 실제로 지나게» 해서 본다.

   ■ 무엇을 지키는가
     ㉠ 사람이 쓴 중괄호는 제목·서식·평문 어디서도 안 사라진다
     ㉡ 편지 안에서 발송기가 읽을 자리는 «정해진 셋»뿐이다
        — {추적열쇠}(통마다 받는 이) · {지역뉴스}(서식) · {지역뉴스평문}(평문)
     ㉢ 그 셋은 그대로 살아 일한다 — 막느라 자리까지 막으면 추적·지역판이 죽는다

   ⚠ 안내문(tests/newsletter-notice.test.js 「사람이 쓴 { } …」)과 «같은 잣대»다.
     서식은 &#123;/&#125;, 평문·제목은 전각 ｛｝ — 두 층이 다르면 한쪽만 새 나간다. */

const test = require('node:test');
const assert = require('node:assert');
const C = require('../js/pu-news-core.js');
const T = require('../js/pu-news-tpl.js');
const MB = require('../functions/mail-bulk.js');
const MS = require('../functions/mail-send.js');

const 설정 = {
  회사이름: '푸른노무법인', 회신주소: '370-6@daum.net',
  추적밑주소: 'https://asia-northeast3-pureun-erp.cloudfunctions.net'
};

/* 사람이 쓴 자리마다 중괄호를 하나씩 심어 둔다 — 어느 칸이 새는지 바로 보이게 */
function 회차자료(더할것) {
  return Object.assign({
    회차: C.회차('2026-08-31'),
    안: {
      news: [{ 갈래: '기사', 제목: '기사 제목',
        우리말: '우리 정리 — 가나상사처럼 {주의} 살펴보실 곳이 있습니다',
        링크: 'https://n.kr/a', 언론사: '매일노동뉴스' },
        /* 우리 말이 없는 줄은 «제목»이 그 자리에 선다 — 거기도 새면 안 된다 */
        { 갈래: '기사', 제목: '{육아}휴직 급여 바뀐다', 링크: 'https://n.kr/b',
          언론사: '매일노동뉴스' }],
      policy: [{ 갈래: '자료', 제목: '{지침} 안내서', 발행처: '고용노동부',
        링크: 'https://www.moel.go.kr/d1', 파일: 'https://www.moel.go.kr/1.pdf' }],
      case: [{ 갈래: '판례', 딱지: '[판례]', 제목: '{대법} 퇴직금 분할 약정',
        인용: '대법원 2026다1', 요지: '요지 {주의} 끝', 링크: 'https://law.go.kr/1' }],
      hr: []
    },
    우리글: '이번 주 한마디 — {주의} 꼭 보십시오',
    인사: { 제목: '{추석} 인사드립니다', 글: '홍길동 올림 {주의}', 서명: '푸른노무법인' },
    지역뉴스: [{ 지역: '충남', 우리말: '천안 {지원금} 접수 시작', 기관: '천안시',
      링크: 'https://cheonan.go.kr/1' }],
    범위: '자문중'
  }, 더할것 || {});
}

const 짓기 = (옵션, 더할것) => T.편지짓기(회차자료(더할것), 설정, 옵션 || {});
/* 발송기를 «실제로» 지나게 한다 — 아는 자리가 하나도 없는 통(모르는 자리는 비워진다) */
const 발송기통과 = (s) => MB.fill(s, {});
const 자리들 = (s) => Array.from(new Set(String(s).match(/\{[^{}]{1,20}\}/g) || [])).sort();

/* ═══ ㉠ 사람이 쓴 { } 는 안 사라진다 ═══════════════════════════════════ */
test('★★★ 사람이 쓴 { } 가 발송기를 지나도 «살아 있다» — 서식', () => {
  const h = 발송기통과(짓기().서식);
  ['육아', '주의', '대법', '추석', '지침'].forEach((말) => {
    assert.ok(h.includes(말), '서식에서 «' + 말 + '» 이 사라졌다');
    assert.ok(h.includes('&#123;' + 말 + '&#125;'),
      '서식의 «{' + 말 + '}» 가 중괄호째 살아 있지 않다');
  });
});

test('★★★ 사람이 쓴 { } 가 발송기를 지나도 «살아 있다» — 평문', () => {
  const t = 발송기통과(짓기().본문);
  ['주의', '대법', '추석', '육아'].forEach((말) => {
    assert.ok(t.includes('｛' + 말 + '｝'),
      '평문의 «{' + 말 + '}» 가 중괄호째 살아 있지 않다');
  });
});

test('★★ 제목의 { } 도 안 사라진다 — 받은편지함에서 먼저 보이는 줄이다', () => {
  const 회 = Object.assign({}, C.회차('2026-08-31'),
    { 제목: '푸른노무법인 주간뉴스레터 {9월호} 입니다.' });
  const 제 = 발송기통과(짓기({}, { 회차: 회 }).제목);
  assert.ok(제.includes('｛9월호｝'), '제목의 중괄호 글자가 사라졌다: ' + 제);
});

test('★★ 씻는 손(mail-send)을 지나도 중괄호 글자가 남는다', () => {
  const h = MS.sanitizeHtml(발송기통과(짓기().서식));
  assert.ok(h.includes('&#123;주의&#125;') || h.includes('{주의}'),
    '발송기가 씻는 사이에 중괄호 글자가 사라졌다');
});

/* ═══ ㉡ 발송기가 읽을 자리는 «정해진 셋»뿐 ═══════════════════════════ */
test('★★★ 편지 안에서 발송기가 읽을 자리는 정해진 셋뿐이다', () => {
  const 편 = 짓기();
  assert.deepStrictEqual(자리들(편.서식), ['{지역뉴스}', '{추적열쇠}'],
    '서식에 우리가 안 둔 자리가 있다: ' + 자리들(편.서식));
  assert.deepStrictEqual(자리들(편.본문), ['{지역뉴스평문}'],
    '평문에 우리가 안 둔 자리가 있다: ' + 자리들(편.본문));
  assert.deepStrictEqual(자리들(편.제목), [], '제목에 자리가 생겼다');
});

test('★★ 지역판으로 지으면 지역 자리가 «채워져» 사라진다 — 남은 자리는 추적뿐', () => {
  const 편 = T.편지짓기(회차자료(), 설정, { 지역: '충남' });
  assert.deepStrictEqual(자리들(편.서식), ['{추적열쇠}'], '지역 자리가 안 채워졌다');
  assert.deepStrictEqual(자리들(편.본문), [], '평문 지역 자리가 안 채워졌다');
  /* 지역 소식에 사람이 쓴 중괄호도 살아 있어야 한다 */
  assert.ok(발송기통과(편.서식).includes('&#123;지원금&#125;'), '지역 소식의 { } 가 사라졌다');
  assert.ok(발송기통과(편.본문).includes('｛지원금｝'), '지역 평문의 { } 가 사라졌다');
});

/* ═══ ㉢ 그 셋은 «그대로 일한다» ═══════════════════════════════════════ */
test('★★★ 막느라 «우리 자리»까지 막으면 안 된다 — 셋 다 그대로 바뀐다', () => {
  const 편 = 짓기();
  const 통 = MB.fill(편.서식, { 추적열쇠: 'abc123', 지역뉴스: '<b>충남 소식</b>' });
  assert.ok(통.includes('e=abc123'), '{추적열쇠} 가 안 바뀌었다 — 열람·클릭 추적이 죽는다');
  assert.ok(!통.includes('{추적열쇠}'), '{추적열쇠} 가 글자 그대로 남았다');
  assert.ok(통.includes('<b>충남 소식</b>'), '{지역뉴스} 가 안 바뀌었다');
  const 평 = MB.fill(편.본문, { 지역뉴스평문: '[우리 지역 노동소식]' });
  assert.ok(평.includes('[우리 지역 노동소식]'), '{지역뉴스평문} 이 안 바뀌었다');
});

test('★★ 발송기 길 전체를 지나도 자리가 글자로 남지 않는다', () => {
  const 편 = 짓기();
  const v = MB.validateBulk({ subject: 편.제목, body: 편.본문, html: 편.서식,
    to: [{ email: 'a@x.test', name: '홍길동', company: '가나상사', track: 'tk1',
      regionHtml: '<i>충남</i>', regionText: '충남 소식' }] });
  assert.ok(v.ok, v.error);
  const 줄 = MB.buildQueue(v, 1000, 'me', 'b1');
  const p = 줄[0].payload;
  assert.ok(!/\{[^{}]{1,20}\}/.test(p.html), '서식에 자리가 글자로 남았다');
  assert.ok(!/\{[^{}]{1,20}\}/.test(p.body), '평문에 자리가 글자로 남았다');
  assert.ok(p.html.includes('e=tk1'), '추적 번호가 안 실렸다');
  assert.ok(p.html.includes('&#123;주의&#125;'), '사람이 쓴 { } 가 끝내 사라졌다');
  assert.ok(p.body.includes('｛주의｝'), '평문에서 사람이 쓴 { } 가 끝내 사라졌다');
});
test('★★ 지역 조각은 «따로 불려도» 막혀 있다 — 화면이 통마다 끼우는 값이다', () => {
  /* pu-news.html 지역뉴스붙인명단·지역판씌우기 가 이 둘을 «따로» 불러 끼운다.
     편지 몸통과 다른 길이라, 여기서 안 막으면 지역 소식의 { } 만 그대로 나간다. */
  const 뉴 = [{ 지역: '충남', 우리말: '천안 {지원금} 접수 시작', 기관: '천안시',
    링크: 'https://cheonan.go.kr/1' }];
  assert.ok(T.지역뉴스조각(뉴, '충남').includes('&#123;지원금&#125;'),
    '지역 서식 조각의 { } 가 안 막혀 있다');
  assert.ok(T.지역뉴스평문(뉴, '충남').includes('｛지원금｝'),
    '지역 평문 조각의 { } 가 안 막혀 있다');
});
