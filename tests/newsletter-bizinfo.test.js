/* ══════════════════════════════════════════════════════════════════════════
   ① 샘이 있고, 정책 꼭지로 간다
   ══════════════════════════════════════════════════════════════════════════ */

test("★★ 기업지원 샘이 있고 «정책» 꼭지로 간다", () => {
  const s = 기업샘();
  assert.ok(s, "★★ 기업마당 샘이 없다 — 대표 지시 2026-09-13");
  assert.equal(s.꼭지, "policy", "정책 꼭지로 안 간다");
  assert.equal(s.발행처, "중소벤처기업부", "발행처를 밝히지 않는다");
});

test("★ 정책 꼭지 이름이 «기업지원»까지 말한다 — 이름이 거짓이면 안 된다", () => {
  const g = C.꼭지들.find((x) => x.키 === "policy");
  assert.ok(g.이름.indexOf("기업지원") >= 0,
    "★ 꼭지에 기업지원을 담으면서 이름은 「고용·노동정책」 그대로다");
  assert.ok((g.옛이름 || []).indexOf("고용·노동정책") >= 0,
    "★★ 옛 이름을 안 남겼다 — 지난 회차·붙여넣기가 이 꼭지를 못 찾는다");
});

test("★ 기업지원이 들어오는 만큼 정책 칸을 «넓힌다»", () => {
  /* ⚠ 칸 수를 그대로 두면 노무 자료가 기업지원에 밀려난다. 늘리는 까닭이 그것이다.
       ★ 자료 카드는 두 칸 나란히라 «짝수»여야 오른쪽이 안 빈다. */
  const g = C.꼭지들.find((x) => x.키 === "policy");
  assert.ok(g.몇개 >= 6, "정책 칸이 6보다 적다 — 기업지원이 노무를 밀어낸다");
  assert.equal(g.몇개 % 2, 0, "홀수면 자료 카드 오른쪽이 빈 칸으로 나간다");
});

/* ══════════════════════════════════════════════════════════════════════════
   ② 「공고」로 거르면 안 된다 · 지역 것은 안 담는다
   ══════════════════════════════════════════════════════════════════════════ */

test("★★★ 지원사업은 «공고가 곧 자료»다 — 「공고」로 거르면 한 건도 안 남는다", () => {
  /* ⚠⚠ 뺄말에 「공고」가 있다. 고용노동부 자료실에서는 맞는 규칙이지만
       기업마당 제목은 거의 다 「…지원사업 공고」로 끝난다. 그대로 두면 전멸한다. */
  assert.equal(D.뺄자료인가("2026년 중소기업 해외시장개척단 참가기업 모집 공고", "bizinfo"),
    false, "★★★ 기업지원 공고를 통째로 거른다");
  assert.equal(D.뺄자료인가("2026년 천안시 중소기업 육성자금 이자 지원계획 공고", "bizinfo"),
    false, "육성자금 공고를 거른다");
  /* 그래도 관서 «채용·입찰»은 여전히 뺀다 — 사업장이 챙길 일이 아니다 */
  assert.equal(D.뺄자료인가("2026년 기간제근로자 채용 공고", "bizinfo"), true,
    "★ 채용 공고까지 들어온다");
  assert.equal(D.뺄자료인가("물품 구매 입찰 공고", "bizinfo"), true, "입찰 공고가 들어온다");
  /* ⚠ 고용노동부 쪽 규칙은 «그대로»여야 한다 — 한쪽을 풀다가 다른 쪽을 풀면 안 된다 */
  assert.equal(D.뺄자료인가("2026년 ○○ 사업 공고", "moel-policy"), true,
    "★★ 고용노동부 자료실의 「공고」 거르기가 함께 풀렸다");
});

test("★★ 지역 꼬리표가 붙은 것은 정책 꼭지에 «안 담는다»", () => {
  /* ⚠⚠ 정책 꼭지에는 지역을 가르는 장치가 없다(지역뉴스에만 있다).
       [인천] 것을 담으면 천안 사업장 60곳에 부평구 공고가 나간다. */
  const 것 = D.목록읽기(목록조각, 기업샘());
  const 제목들 = 것.map((x) => x.제목);
  assert.ok(제목들.some((t) => t.indexOf("해외시장개척단") >= 0),
    "★ 전국짜리를 못 읽었다");
  assert.ok(!제목들.some((t) => t.indexOf("[인천]") >= 0),
    "★★ 인천 공고가 전국으로 나간다");
  assert.ok(!제목들.some((t) => t.indexOf("[충남]") >= 0),
    "★★ 충남 공고까지 담았다 — 지역 것은 지역뉴스가 맡는다");
});

/* ══════════════════════════════════════════════════════════════════════════
   ③ 읽개 — 번호가 숫자가 아니다 · href 뒤에 빈칸이 있다
   ══════════════════════════════════════════════════════════════════════════ */

test("★★ 번호가 «숫자가 아니어도» 읽는다 (pblancId=PBLN_…)", () => {
  const 것 = D.목록읽기(목록조각, 기업샘());
  assert.ok(것.length >= 1, "★★ 한 건도 못 읽었다 — 번호 꼴이 \\d+ 로 굳어 있다");
  assert.equal(것[0].일련번호, "PBLN_000000000126401", "일련번호를 잘못 읽었다");
  assert.ok(/pblancId=PBLN_000000000126401$/.test(것[0].링크), "상세 주소가 틀리다: " + 것[0].링크);
});

test("★★ 제목에 「페이지 이동」 같은 «안내 글자»가 따라붙지 않는다", () => {
  /* ⚠⚠ 눈에는 안 보이는 글자다. 그대로 두면 편지 카드에
       「…모집 공고 페이지 이동」으로 나가 법인이 글자를 흘린 것처럼 보인다. */
  const 것 = D.목록읽기(목록조각, 기업샘());
  assert.equal(것[0].제목, "2026년 중소기업 해외시장개척단 참가기업 모집 공고",
    "★★ 제목에 꼬리가 붙었다: " + 것[0].제목);
});

test("★★★ 설명이 «첫 칸에서 끊기지» 않는다 — 신청기간이 알맹이다", () => {
  /* ⚠⚠ view_cont 안에 <div>가 겹쳐 있다. 첫 </div> 에서 자르면
       「소관부처·지자체 중소벤처기업부」만 남고 «신청기간·사업개요»를 잃는다.
       지원사업은 「언제까지 · 무엇을」이 전부다. */
  const d = D.상세읽기(상세조각, "PBLN_000000000126401", 기업샘());
  assert.ok(d, "★ 상세를 못 읽었다");
  assert.equal(d.제목, "2026년 중소기업 해외시장개척단 참가기업 모집 공고");
  assert.ok(d.설명.indexOf("신청기간") >= 0,
    "★★★ 신청기간을 못 담았다 — 겹친 div 에서 끊겼다: " + d.설명.slice(0, 60));
  assert.ok(d.설명.indexOf("2026.10.10") >= 0, "마감일을 못 담았다");
  assert.ok(d.설명.indexOf("바이어 상담") >= 0, "사업개요를 못 담았다");
});

test("★★ 첨부 이름에 「바로보기 새 창 열기」가 따라붙지 않는다", () => {
  const d = D.상세읽기(상세조각, "PBLN_000000000126401", 기업샘());
  assert.equal(d.파일들.length, 1, "첨부를 못 읽었다 (바로보기 단추를 파일로 셌을 수도)");
  assert.ok(/fileDown\.do\?atchFileId=FILE_000000000773158/.test(d.파일들[0].주소),
    "첨부 주소가 틀리다: " + d.파일들[0].주소);
  assert.equal(d.파일들[0].이름, "2026_해외시장개척단_모집공고.hwp",
    "★★ 첨부 이름에 꼬리가 붙었다: " + d.파일들[0].이름);
});

/* ══════════════════════════════════════════════════════════════════════════
   ④ 노무를 밀어내지 않는다
   ══════════════════════════════════════════════════════════════════════════ */

test("★★★ 기업지원은 노무 «가이드»를 밀어내지 않는다 — 값어치가 그 아래다", () => {
  /* ⚠⚠ 정책 칸은 값어치 순으로 찬다. 기업지원이 가이드보다 높으면
       「난임치료휴가 활용가이드」가 밀려난다 — 우리는 노무법인이다. */
  const 가이드 = D.자료값어치("사업주와 인사담당자를 위한 난임치료휴가 및 급여제도 활용가이드", "moel-policy");
  const 기업 = D.자료값어치("2026년 중소기업 해외시장개척단 참가기업 모집 공고", "bizinfo");
  assert.ok(기업 > 0, "★ 기업지원이 0 이하다 — 옛 자료(0점)에도 밀린다");
  assert.ok(기업 < 가이드,
    "★★★ 기업지원(" + 기업 + ")이 노무 가이드(" + 가이드 + ")를 밀어낸다");
});

test("기업지원끼리는 «신청 기한이 있는 것»이 위로 온다", () => {
  const 자금 = D.자료값어치("2026년 천안시 중소기업 육성자금 이자 지원계획 공고", "bizinfo");
  const 알림 = D.자료값어치("중소벤처24 신규 서비스 안내", "bizinfo");
  assert.ok(자금 >= 알림, "지원사업이 단순 안내보다 아래에 선다");
});
