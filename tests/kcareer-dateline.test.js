'use strict';
/* 📅 「202026년」 — 서식에 미리 찍힌 «세기 두 자리» (대표 캡쳐 2026-09-27)
   ─────────────────────────────────────────────────────────────
   대표가 만든 개인정보 동의서 아래에 이렇게 찍혀 있었다:

       202026년 9월 26일     신청인   권 형 하 (서명)

   ■ 까닭
     기관 서식은 「20    년   월   일」처럼 «세기 두 자리»를 미리 찍어 둔다.
     날짜를 채우는 자가 «네 자리»만 해로 봐서, 그 「20」을 «적힌 해»로도 «빈칸»으로도
     못 보고 그대로 남긴 채 앞에 2026 을 써 넣었다 → 「20」+「2026년」.

   ■ 규칙 — 두 자리를 셋으로 가른다
     · 「19」·「20」 = 미리 찍힌 «세기 자리» → 통째로 갈아 끼운다
     · 그 밖의 두 자리(「26」) = 사람이 적은 «짧은 해» → 그대로 둔다
     · 네 자리 = 적힌 해 → 그대로 둔다
   ⚠ 안 가르면 「26년」이 「262026년」이 된다 — 같은 병이다. */
const test = require('node:test');
const assert = require('node:assert/strict');
const path = require('node:path');

const R = path.join(__dirname, '..');
const X = require(path.join(R, 'js', 'kcareer-hwpxfill.js'));

const 오늘 = new Date(2026, 8, 27);      /* 2026-09-27 */
const run = (t) => '<hp:run charPrIDRef="0"><hp:t>' + t + '</hp:t></hp:run>';
const 문단 = (t) => '<hp:p>' + run(t) + '</hp:p>';
/* fillParagraphs(xml, fields, report, today) → 바뀐 xml */
function 채움(글) {
  const report = { fields: [] };        /* fillParagraphs 는 여기에 적어 넣는다 */
  const out = X.fillParagraphs(문단(글), {}, report, 오늘);
  return X.paraText(out);
}

test('★★★ 「20    년   월   일」 — 미리 찍힌 세기 자리를 «갈아 끼운다»', () => {
  const r = 채움('20    년    월    일');
  assert.equal(r, '2026년 9월 27일',
    '★ 「202026년」이 됩니다 — 대표 서류에 실제로 그렇게 찍혔습니다: ' + r);
  assert.ok(r.indexOf('202026') < 0, '★ 세기 자리가 앞에 남았습니다');
});

test('★★ 「19    년」(옛 서식)도 같다', () => {
  assert.equal(채움('19    년   월   일'), '2026년 9월 27일');
});

test('★ 통째로 빈 「  년   월   일」은 오늘로', () => {
  assert.equal(채움('      년    월    일'), '2026년 9월 27일');
});

test('★★★ 사람이 적은 짧은 해(「26년」)는 «그대로 둔다» — 지우면 안 된다', () => {
  const r = 채움('26년   월   일');
  assert.equal(r, '26년 9월 27일',
    '★ 「262026년」이 됩니다 — 「202026년」과 같은 병입니다: ' + r);
});

test('★★ 이미 다 적힌 날짜는 «손대지 않는다» — 사람이 일부러 적은 날일 수 있다', () => {
  /* ⚠ 「2026년 9월 26일」처럼 띄어쓰기까지 같은 것으로 재면 «덮어써도» 결과가 같아
     고장을 못 잡는다(고장넣기가 그것을 잡았다). 띄어쓰기가 다른 것으로 잰다 —
     덮으면 한 칸으로 다시 쓰여 글자가 달라진다. */
  const 그대로 = '2026년   9월   26일';
  assert.equal(채움(그대로), 그대로,
    '★ 적어 둔 날짜를 오늘로 덮었습니다(띄어쓰기까지 그대로여야 합니다)');
  assert.equal(채움('2026년 9월 26일'), '2026년 9월 26일');
});

test('★ 해만 적혀 있으면 달·날만 채운다', () => {
  assert.equal(채움('2026년   월   일'), '2026년 9월 27일');
});

test('★ 앞에 글자가 있어도 그 글자는 남는다', () => {
  assert.equal(채움('제출일 : 20   년   월   일'), '제출일 : 2026년 9월 27일');
});

test('★ 날짜 틀이 없는 문단은 손대지 않는다', () => {
  const 그냥 = '위와 같이 동의합니다';
  assert.equal(채움(그냥), 그냥, '★ 날짜가 아닌 줄을 건드립니다');
  /* ⚠ `return hit ? out : null` 의 `hit` 를 빼도 같은 답이 난다 — 날짜 틀이 없으면
     replace 가 아무것도 안 바꿔 out === txt 이고, 부르는 쪽이 «달라졌을 때만» 쓴다.
     고장넣기가 «안 걸리는» 까닭이 이것이다(억지 검사를 지어 붙이지 않는다). */
});
