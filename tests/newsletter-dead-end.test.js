/* 편지에 «막다른 길»을 두지 않는다 (대표 검증 지시 2026-09-20)
   ═══════════════════════════════════════════════════════════════════════════
   「메일 보내고 받은사람이 팝업으로 창을 봤을때 어색한지 불필요한 화면 없는지
    그리고 자료 다운받을때 문제가 되는게 아닌지 등 한번 검증해달라」

   ■ 검증에서 실제로 나온 것 (살아 있는 2026-09-w3 편지·웹 쪽)
     ㉠ 붙임이 «없는» 자료 칸 — 카드에도 팝업에도 나갈 문이 하나도 없었다.
        옆 칸 셋에는 「내려받기 ↓」가 있어 «빠뜨린 것»처럼도 보였다.
        제목을 상세 쪽으로 안 거는 규칙(2026-09-20)은 «카드에 이미 내려받기가
        있다»는 것을 전제로 한다 — 붙임이 없으면 그 전제가 깨진다.
     ㉡ 판례 한 건의 「전문 보기」가 https://www.law.go.kr/ — 판례가 아니라
        법제처 «첫 화면»이었다. 눌러 놓고 그 판례를 손으로 찾아야 한다.
     ㉢ 「전문 보기 ↓」 — ↓ 는 «내려받기» 뜻으로 갈라 두었는데 여기만 ↓ 였다.
        파일이 받아지는 줄 알고 누르시게 된다.

   ■ 이 검사가 지키는 것
     ① 붙임 없는 자료에는 «자세히 보기 ↗»가 뜬다 — 붙임이 있으면 안 뜬다(단추는 하나)
     ② 「전문 보기」는 «그 한 건으로 가는 주소»일 때만 붙는다
     ③ 화살표 약속 — 내려받기는 ↓, 쪽이 열리는 것은 ↗ */

const test = require('node:test');
const assert = require('node:assert');

const C = require('../js/pu-news-core.js');
const T = require('../js/pu-news-tpl.js');

const 설 = { 회사이름: '푸른노무법인', 보내는주소: '370-6@hanmail.net',
  추적밑주소: 'https://asia-northeast3-pureun-erp.cloudfunctions.net' };
function 편지(안, 옵) {
  return T.편지짓기({ 회차: C.회차('2026-09-14'), 안: 안, 우리글: '' }, 설,
    Object.assign({ 미리보기: true }, 옵 || {})).서식;
}
const 상세 = 'https://www.moel.go.kr/policy/policydata/view.do?bbs_seq=20260800764';
const 붙임 = 'https://www.moel.go.kr/common/downloadFile.do?file_seq=1&file_ext=pdf';
const 자료 = (덧) => Object.assign({ 갈래: '자료', 제목: '마트배송 직종 표준계약서 및 활용가이드',
  발행처: '고용노동부', 발행일: '2026-08-26', 링크: 상세 }, 덧 || {});
const 판례 = (덧) => Object.assign({ 갈래: '판례', 딱지: '[판례]', 제목: '어느 판례입니다',
  인용: '대법원 2025두32673 (2026. 8. 12.)' }, 덧 || {});

/* ═══ ① 붙임 없는 자료 ════════════════════════════════════════════════ */

test('★★★ 붙임이 «없는» 자료 칸에도 나갈 문이 하나는 있다', () => {
  const h = 편지({ policy: [자료({ 파일: '' })] });
  assert.ok(h.indexOf(자료().제목) >= 0, '제목 자체가 사라졌다');
  assert.ok(/자세히 보기 ↗/.test(h),
    '★★★ 붙임도 없고 나갈 문도 없다 — 받는 분은 그 자료를 «찾을 길»이 없다');
  assert.ok(h.indexOf('href="' + 상세 + '"') >= 0,
    '★★★ 「자세히 보기」가 그 자료의 상세 쪽으로 안 간다');
});

test('★★★ 붙임이 «있으면» 자세히 보기는 «안» 뜬다 — 단추는 하나다', () => {
  /* 대표 지시 2026-09-20 「팝업창으로 바로 가지마라 … 이럴경우 불필요하다」.
     ⚠ 막다른 길을 막겠다고 단추를 둘로 늘리면 그 지시를 되돌리는 것이 된다. */
  const h = 편지({ policy: [자료({ 파일: 붙임, 확장자: 'pdf', 파일크기: 774447 })] });
  assert.ok(/내려받기 ↓/.test(h), '내려받기 단추가 사라졌다');
  assert.ok(!/자세히 보기/.test(h),
    '★★★ 내려받기가 있는데 「자세히 보기」까지 붙었다 — 단추가 둘이 되었다');
  assert.ok(h.indexOf('href="' + 상세 + '"') < 0,
    '★★★ 상세 쪽 링크가 되살아났다 — 2026-09-20 지시를 되돌린 것이다');
});

test('붙임도 링크도 없으면 «아무 단추도» 안 만든다', () => {
  const h = 편지({ policy: [자료({ 파일: '', 링크: '' })] });
  assert.ok(!/자세히 보기/.test(h) && !/내려받기/.test(h),
    '갈 곳이 없는데 단추를 만들었다 — 눌러도 아무 일이 안 난다');
});

/* ═══ ② 「전문 보기」는 그 한 건으로 갈 때만 ═══════════════════════════ */

test('★★★ 법제처 «대문» 주소에는 「전문 보기」를 안 붙인다', () => {
  const h = 편지({ case: [판례({ 링크: 'https://www.law.go.kr/' })] });
  assert.ok(h.indexOf('어느 판례입니다') >= 0, '판례 자체가 사라졌다');
  assert.ok(!/전문 보기/.test(h),
    '★★★ 법제처 첫 화면으로 가는 「전문 보기」가 그대로 있다 — 헛걸음을 시킨다');
  assert.ok(h.indexOf('대법원 2025두32673') >= 0,
    '★ 링크를 뗀다고 인용까지 없애면 무슨 판례인지 알 수 없다');
});

test('★★★ 법제처 «한 건» 주소에는 「전문 보기」가 붙고, 우리 쪽으로 간다', () => {
  const 한건 = 'https://www.law.go.kr/DRF/lawService.do?OC=test&target=prec&type=HTML&ID=622111';
  const h = 편지({ case: [판례({ 링크: 한건 })] });
  assert.ok(/전문 보기/.test(h),
    '(재기 값) 멀쩡한 판례의 「전문 보기」까지 사라졌다 — 잣대가 너무 좁다');
  assert.ok(/newsFullPage\?t=prec&amp;id=622111/.test(h),
    '★★★ 「전문 보기」가 우리 쪽(newsFullPage)이 아니라 법제처로 간다');
});

test('법제처가 아닌 곳이라도 «한 건»이면 「전문 보기」가 붙는다', () => {
  const h = 편지({ case: [판례({ 링크: 'https://casenote.kr/대법원/2025두32673' })] });
  assert.ok(/전문 보기/.test(h), '법제처가 아니라는 까닭만으로 링크를 떼었다');
});

test('집 주소만 있는 링크(도메인 뿐)는 «한 건»이 아니다', () => {
  ['https://casenote.kr/', 'https://casenote.kr', 'https://www.law.go.kr/'].forEach((u) => {
    const h = 편지({ case: [판례({ 링크: u })] });
    assert.ok(!/전문 보기/.test(h), '★ 대문 주소(' + u + ')에 「전문 보기」가 붙었다');
  });
});

test('★★ 법제처의 «사람이 보는» 판례 쪽은 잘라 내지 않는다', () => {
  /* ⚠⚠ 잣대를 「법제처면 target·ID 가 있어야 한다」로 두었다가 이 자리에서 울었다.
       DRF(기계용 문) 말고도 법제처에는 사람이 보는 쪽이 있다. 막을 것은 «대문»뿐이다. */
  ['https://www.law.go.kr/precInfoP.do?precSeq=622111',
    'https://www.law.go.kr/x'].forEach((u) => {
    assert.ok(/전문 보기/.test(편지({ case: [판례({ 링크: u })] })),
      '★★ 멀쩡한 법제처 쪽(' + u + ')의 「전문 보기」가 사라졌다');
  });
});

/* ═══ ③ 화살표 약속 ═══════════════════════════════════════════════════ */

test('★★★ ↓ 는 «내려받기», ↗ 는 «쪽이 열린다» — 섞지 않는다', () => {
  const 한건 = 'https://www.law.go.kr/DRF/lawService.do?OC=test&target=prec&type=HTML&ID=622111';
  const h = 편지({
    policy: [자료({ 파일: 붙임, 확장자: 'pdf', 파일크기: 774447 })],
    case: [판례({ 링크: 한건 })]
  });
  assert.ok(!/전문 보기 ↓/.test(h),
    '★★★ 「전문 보기 ↓」 — 파일이 받아지는 줄 알고 누르시게 된다');
  assert.ok(/전문 보기 ↗/.test(h), '★★★ 「전문 보기」에 ↗ 가 없다');
  assert.ok(/내려받기 ↓/.test(h), '(재기 값) 내려받기의 ↓ 까지 바꿔 버렸다');
});

/* ═══ 평문도 «같은 잣대» ══════════════════════════════════════════════ */

test('★★★ 서식을 못 읽는 프로그램에서도 법제처 대문 주소는 안 적는다', () => {
  /* ⚠ 한쪽만 고치면 «어떤 사람에게는 있고 어떤 사람에게는 없는» 편지가 된다.
       2026-09-18 에 실제로 한 번 그랬다. */
  const 짓기 = (링크) => T.평문짓기(
    { 회차: C.회차('2026-09-14'), 안: { case: [판례({ 링크: 링크 })] }, 우리글: '' }, 설, '전국');
  assert.ok(짓기('https://www.law.go.kr/').indexOf('https://www.law.go.kr/') < 0,
    '★★★ 평문에 법제처 대문 주소가 그대로 적힌다');
  const 한건 = 'https://www.law.go.kr/DRF/lawService.do?OC=test&target=prec&type=HTML&ID=622111';
  assert.ok(짓기(한건).indexOf(한건) >= 0,
    '(재기 값) 멀쩡한 판례 주소까지 평문에서 사라졌다');
});
