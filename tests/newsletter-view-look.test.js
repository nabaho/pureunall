'use strict';
/* 「자세히 보기」 창을 «우리 얼굴»로 — 손님이 보는 유일한 우리 웹 쪽이다
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-13: 「팝업창의 디자인을 좀더 이쁘게 하고 너무 무미 건조하다」

   ⚠ 이 창은 손님이 편지에서 눌러 들어오는 «유일한 우리 웹 쪽»이다. 흰 상자에
     회색 띠 하나가 전부라, 어디서 온 쪽인지도 누구에게 물어야 하는지도 알 수 없었다.
   ★ 편지가 쓰는 빛깔(갈·살구·짙은갈)을 그대로 쓴다 — 편지와 창이 «한 집»으로 보이게.

   ★ 여기서 못 박는 것은 «꾸밈값»이 아니라 «규칙»이다:
     ① 머리에 «우리 이름»이 있다 — 어디서 온 쪽인지 알게
     ② 꼬리에 «연락처»가 있다 — 궁금하면 물어볼 길이 보이게
     ③ 창이 화면 «가운데» 선다 — 짧은 글 하나가 맨 위에 붙어 있으면 버려진 것처럼 보인다
     ④ 「움직임을 줄여 달라」는 설정을 «따른다»
     ⑤ 편지 «안»은 손대지 않는다 — 메일과 달라지면 안 된다

   ⚠ 이 파일은 «판단하는 층»만 본다(functions/news-view.js). 인터넷을 안 두드린다. */

const test = require('node:test');
const assert = require('node:assert');
const NV = require('../functions/news-view.js');

const 쪽 = () => NV.쪽('2026년 09월 2주차', '<div id="n-news-0" data-pop="1">가</div>');

test('★★ 머리에 «우리 이름»이 있다 — 어디서 온 쪽인지 알게', () => {
  /* ⚠ 손님은 메일에서 눌러 들어온다. 흰 상자만 뜨면 누가 보낸 것인지 알 수 없다. */
  const h = 쪽();
  assert.ok(h.indexOf('푸른노무법인') >= 0,
    '★★ 창 어디에도 법인 이름이 없다 — 누가 보낸 쪽인지 알 수 없다');
});

test('★★ 꼬리에 «연락처»가 있다 — 궁금하면 물어볼 길이 보이게', () => {
  const h = 쪽();
  assert.ok(/041-556-0035/.test(h),
    '★★ 물어볼 길이 없다 — 없는쪽 에는 있는데 정작 읽는 쪽에는 없었다');
});

test('★ 회차 이름이 창에 남는다 — 언제 것인지 알게', () => {
  assert.ok(쪽().indexOf('2026년 09월 2주차') >= 0, '회차 이름이 어디에도 없다');
});

test('★★ 창이 화면 «가운데» 선다 — 맨 위에 붙으면 버려진 것처럼 보인다', () => {
  /* ⚠ 짧은 글 한 문단짜리가 화면 꼭대기에 붙고 아래가 통째로 비어 있었다
       (대표 화면 2026-09-13). 그것이 「무미건조」의 큰 몫이다. */
  const m = /#pop\.on\{([^}]*)\}/.exec(쪽());
  assert.ok(m, '#pop.on 규칙을 못 찾았다');
  assert.ok(!/align-items:\s*flex-start/.test(m[1]),
    '★★ 창이 맨 위에 붙는다 — 아래가 통째로 빈다');
  assert.ok(/align-items:\s*center/.test(m[1]), '가운데로 안 세운다');
});

test('★★ 「움직임을 줄여 달라」는 설정을 «따른다»', () => {
  /* ⚠ 어지럼을 타는 분이 있다. 브라우저 설정을 켜 두면 그것을 지켜야 한다 —
       안 지키면 예쁘게 만든 것이 누군가에게는 괴로움이 된다. */
  const h = 쪽();
  assert.ok(/@keyframes/.test(h), '움직임이 아예 없다 — 규칙을 볼 것이 없다');
  assert.ok(/prefers-reduced-motion/.test(h),
    '★★ 움직임 줄이기 설정을 안 본다');
  const m = /@media\s*\(prefers-reduced-motion:\s*reduce\)\{([\s\S]*?)\}\s*\}/.exec(h);
  assert.ok(m, 'prefers-reduced-motion 규칙의 속을 못 찾았다');
  assert.ok(/animation:\s*none/.test(m[1]), '설정을 켜도 그대로 움직인다');
});

test('★★★ 창 바탕은 여전히 «꽉» 덮는다 — 예쁘게 하려다 뒤를 비추면 안 된다', () => {
  /* ⚠⚠ 대표 지시 2026-09-12 「뒤에 배경에 또 내용이 이중으로 있는것 처럼보인다」.
       그림자·그러데이션을 넣다가 반투명으로 바꾸기 쉬운 자리라 여기서 한 번 더 못 박는다. */
  const m = /#pop\{[^}]*background:([^;]+);/.exec(쪽());
  assert.ok(m, '창 바탕 규칙을 못 찾았다');
  assert.ok(!/rgba|transparent|\.\d/.test(m[1]),
    '★★★ 창 바탕이 비친다(' + m[1].trim() + ')');
});

test('★★ 편지 «안»은 손대지 않는다 — 메일과 달라지면 안 된다', () => {
  /* ⚠⚠ 창을 꾸미다가 편지 속 글자·빛깔까지 바꾸면, 메일로 본 것과 눌러서 본 것이
       달라진다. 꾸밈은 «창 껍데기»에만 건다. */
  const h = 쪽();
  const 껍데기밖 = /#pop\s+\.bd\s+(p|div|span|td|table|b)\b[^{]*\{/.exec(h);
  assert.ok(!껍데기밖,
    '★★ 창이 편지 속 글자에 꾸밈을 건다(' + (껍데기밖 && 껍데기밖[0]) + ')');
  assert.ok(h.indexOf('<div id="n-news-0" data-pop="1">가</div>') >= 0,
    '전문이 그대로 안 들어갔다');
});

test('누를 수 있다는 표시는 그대로 — 예쁘게 하려다 잃지 않는다', () => {
  const h = 쪽();
  assert.ok(/\[data-pop\]\{cursor:pointer\}/.test(h), '누를 수 있다는 표시가 없다');
  assert.ok(h.indexOf('id="popt"') >= 0, '꼭지 이름 자리가 사라졌다');
  assert.ok(h.indexOf('id="popx"') >= 0, '닫기 단추가 사라졌다');
});

test('★ 「없는 쪽」도 같은 얼굴이다 — 한쪽만 꾸미면 따로 논다', () => {
  const h = NV.없는쪽('초안');
  assert.ok(h.indexOf('푸른노무법인') >= 0, '법인 이름이 없다');
  assert.ok(/041-556-0035/.test(h), '연락처가 없다');
  assert.ok(h.indexOf(NV.까닭말['초안']) >= 0, '까닭을 안 말한다');
});
