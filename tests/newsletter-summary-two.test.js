'use strict';
/* 요약판을 «좌우 두 칸»으로 · 첨부는 «안 붙인다» · 차림표는 «따라온다»
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-13(시험 편지를 받아 보시고):
     「이렇게 첨부하면 안된다.
      그리고 이부분 틀고정 해라 캡쳐3.
      캡쳐4 너무 아래로 길게 내려온다 차라리 좌우로 나누어서 한화면에 모두 나올 수
      있게 저절 해달라.」

   ⚠ 받으신 시험 편지에 파일 «다섯 개 3.65MB»가 붙어 나갔다.
     142곳이면 한 번에 518MB 다. 게다가 편지 안에는 이미 «내려받기» 단추가 있다 —
     같은 것을 두 벌로 보내면서 큰 메일로 스팸 판정만 부른다.
   ⚠ 요약이 꼭지 넷을 «세로로 줄줄이» 늘어놓아 화면을 한참 내려야 했다.

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ①★★★ 편지에 파일을 «안 붙인다» — 내려받기 단추로 간다
     ② 요약 꼭지를 «둘씩 나란히» 놓는다
     ③ 나란히 놓아도 «무엇도 잃지 않는다» — 줄·곁말·누를 자리 그대로
     ④ 홀수여도 오른쪽이 «깨지지 않는다»
     ⑤ 차림표가 굴러도 «따라온다»(웹 쪽) — 메일에서는 해롭지 않게 무시된다

   ⚠ 인터넷도 브라우저도 두드리지 않는다. */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { stripComments, stripJs } = require('./strip-comments');
const C = require('../js/pu-news-core.js');
const T = require('../js/pu-news-tpl.js');

const ROOT = path.join(__dirname, '..');
const news = stripComments(
  fs.readFileSync(path.join(ROOT, 'pu-news.html'), 'utf8').replace(/\r\n/g, '\n'));

const 설정 = { 이름: '푸른노무법인', 추적밑주소: 'https://x.kr' };
const 기사 = (n, 글) => ({ 갈래: '기사', 제목: 'ㄱ' + n, 링크: 'https://n.kr/' + n,
  언론사: '매일노동뉴스', 우리말: 글 || ('우리가 쓴 ' + n + '번째 한 줄입니다.') });
const 자료 = (n) => ({ 갈래: '자료', 제목: '자료' + n, 링크: 'https://www.moel.go.kr/v/' + n,
  발행처: '고용노동부', 파일: 'https://www.moel.go.kr/f/' + n, 파일이름: 'a' + n + '.pdf',
  파일자리: 'newsdocs/' + n + '.pdf', 파일크기: 700000, 우리말: '자료 한 줄 ' + n });

/* ⚠ d.회차 는 «글자»가 아니라 Core.회차() 가 만든 한 벌이다(열쇠·이름·범위).
     글자로 두면 회열이 빈 채로 웹주소가 안 서고, 요약판이 통째로 «안 만들어진다» —
     그래도 편지는 만들어지므로 알아채기 어렵다. 실제로 여기서 한 번 걸렸다. */
const 회차 = (추가) => Object.assign({
  날짜: '2026-09-13', 회차: C.회차('2026-09-13'),
  우리글: '이번 주 한마디입니다.',
  안: { news: [기사(1), 기사(2), 기사(3)], policy: [자료(1), 자료(2)],
        case: [], hr: [자료(3)] },
}, 추가 || {});

const 요약 = () => T.편지짓기(회차(), 설정, { 미리보기: true, 요약: true })
  || T.편지짓기(회차(), 설정, { 미리보기: true });

/* ══════════════════════════════════════════════════════════════════════════
   ① 첨부를 «안 붙인다»
   ══════════════════════════════════════════════════════════════════════════ */

test('★★★ 편지에 파일을 «안 붙인다» — 내려받기 단추로 간다', () => {
  /* ⚠⚠ 실측 2026-09-13: 시험 편지에 다섯 개 3.65MB 가 붙어 나갔다.
       142곳이면 518MB 다. 편지 안에 이미 내려받기 단추가 있는데 같은 것을 두 벌로
       보내면서, 큰 메일로 스팸 판정만 부른다. */
  /* ★ 재는 기계(Core.첨부모으기)는 «그대로 둔다» — 한도·겹침·자리 지키기가 거기 있고,
       다시 붙이기로 하시면 그 문만 열면 된다. 막는 자리는 «화면»이다.
     ⚠ 붙일까 말까는 대표께서 뒤집으신 «결정»이라, 재는 기계를 부수지 않는다. */
  const i = news.indexOf('function 첨부셈(');
  assert.ok(i > 0, '첨부셈 을 못 찾음');
  const fn = news.slice(i, news.indexOf('\n}', i));
  assert.ok(/파일들:\s*\[\]/.test(fn), '★★★ 화면이 아직 파일을 실어 보낸다');
  assert.ok(/const 첨부붙일까 = false/.test(news), '★★★ 첨부 문이 열려 있다');
  /* 세 길(시험·자동발송 준비·진짜 보내기)이 모두 이 문을 지난다 */
  assert.equal((news.match(/files:\s*첨\.파일들/g) || []).length, 3,
    '★★ 첨부셈 을 안 거치고 파일을 싣는 길이 생겼다');
});

test('★★ 붙이지 않아도 «내려받기 단추»는 그대로 간다', () => {
  /* ⚠ 붙이기를 끄면서 단추까지 잃으면 자료를 받을 길이 «아예» 없어진다. */
  const 편 = T.편지짓기(회차(), 설정, { 미리보기: true });
  assert.ok(편, '편지가 안 만들어졌다');
  assert.ok(편.서식.indexOf('내려받기') >= 0, '★★ 내려받기 단추가 사라졌다');
  assert.ok(편.서식.indexOf('https://www.moel.go.kr/f/1') >= 0, '파일 주소가 안 실렸다');
});

test('★ 화면이 「첨부 안 붙음」을 «말한다» — 조용히 빠지면 안 된다', () => {
  const i = news.indexOf('function 첨부셈(');
  assert.ok(i > 0, '첨부셈 을 못 찾음');
  const fn = news.slice(i, news.indexOf('\n}', i));
  assert.ok(/붙이지 않습니다|안 붙입니다|내려받기/.test(fn),
    '★ 첨부를 왜 안 붙이는지 화면이 말하지 않는다');
});

/* ══════════════════════════════════════════════════════════════════════════
   ② 요약을 «좌우 두 칸»으로
   ══════════════════════════════════════════════════════════════════════════ */

test('★★★ 요약 꼭지를 «둘씩 나란히» 놓는다', () => {
  /* ⚠⚠ 넷을 세로로 줄줄이 놓아 화면을 한참 내려야 했다(대표 화면 2026-09-13). */
  const tpl = stripJs(
    fs.readFileSync(path.join(ROOT, 'js/pu-news-tpl.js'), 'utf8').replace(/\r\n/g, '\n'));
  assert.ok(tpl.indexOf('function 요약두칸(') >= 0,
    '★★★ 둘씩 나란히 놓는 자리가 없다');
  const i = tpl.indexOf('function 요약두칸(');
  const fn = tpl.slice(i, i + 2000);
  assert.ok(/width="50%"|width:\s*50%/.test(fn), '반씩 나누지 않는다');
  assert.ok(/valign="top"/.test(fn),
    '★ 위로 안 맞춘다 — 줄 수가 다르면 짧은 쪽이 가운데로 떠 보인다');
});

test('★★ 나란히 놓아도 «무엇도 잃지 않는다»', () => {
  const 편 = 요약();
  assert.ok(편, '요약 편지가 안 만들어졌다');
  const h = 편.서식;
  ['우리가 쓴 1번째', '우리가 쓴 3번째', '자료 한 줄 1', '이번 주 한마디']
    .forEach((s) => assert.ok(h.indexOf(s) >= 0, '요약에서 잃었다: ' + s));
  assert.ok(h.indexOf('매일노동뉴스') >= 0, '곁말(언론사)을 잃었다');
  assert.ok(h.indexOf('#n-news-0') >= 0, '★★ 줄마다 제 건으로 가는 자리를 잃었다');
});

test('★★ 꼭지가 «홀수»여도 오른쪽이 안 깨진다', () => {
  /* ⚠ 셋이면 마지막 줄의 오른쪽이 빈다. 빈 채로 두면 표가 무너지는 메일 프로그램이
       있다 — 빈 칸을 «명시로» 둔다. */
  const d = 회차({ 안: { news: [기사(1)], policy: [자료(1)], case: [], hr: [] } });
  const 편 = T.편지짓기(d, 설정, { 미리보기: true, 요약: true })
    || T.편지짓기(d, 설정, { 미리보기: true });
  assert.ok(편, '홀수일 때 편지가 안 만들어졌다');
  const tpl = stripJs(
    fs.readFileSync(path.join(ROOT, 'js/pu-news-tpl.js'), 'utf8').replace(/\r\n/g, '\n'));
  const i = tpl.indexOf('function 요약두칸(');
  assert.ok(/&nbsp;|빈칸|''/.test(tpl.slice(i, i + 2000)),
    '★★ 홀수일 때 오른쪽을 안 채운다');
});

/* ══════════════════════════════════════════════════════════════════════════
   ③ 차림표가 «따라온다»
   ══════════════════════════════════════════════════════════════════════════ */

test('★★ 차림표가 굴러도 «따라온다» — 웹 쪽에서', () => {
  /* 대표 지시 2026-09-13 「이부분 틀고정 해라」.
     ⚠ 메일 프로그램은 position 을 대개 무시한다 — 거기서는 그냥 옛날처럼 붙어 있다.
       해롭지 않다. 통하는 곳(웹 전문 보기)에서만 따라오면 된다. */
  const NV = require('../functions/news-view.js');
  const h = NV.쪽('ㄱ', '<div>속</div>');
  assert.ok(/position:\s*sticky/.test(h),
    '★★ 웹 쪽에서 차림표가 안 따라온다');
  assert.ok(/z-index/.test(h), '따라오는 띠가 글 밑으로 깔린다');
});
