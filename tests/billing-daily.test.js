'use strict';
/* 「어느 날 났나」를 날마다 갈라 본다 (대표 물음 2026-09-19
   「자동으로 돌면서 사용하는 것 횟수를 줄일수 없나 계속 쓸데없이 비용나가는거 아닌가?」)

   ── 왜 이 셈이 중요한가 ──
   이번 달 실시간DB ₩25,298 가운데 ₩18,977(75%)이 9/16·9/17 «이틀»에 났다.
   나머지 17일은 하루 평균 ₩370 이었다. 「이번 달 얼마」만 보면 «계속 새는 것»처럼
   보이지만, 날마다 갈라 보면 «이틀 사고»였다는 것이 한눈에 보인다.
   이 둘을 못 가리면 이미 막은 구멍을 또 막으러 다니게 된다.

   ── 못 박는 것 ──
   ① 첫날은 «모른다»로 남긴다 — 0 은 「그날 안 썼다」로 읽힌다
   ② 같은 날 점이 여럿이면 «마지막» 누적이 그날 끝이다
   ③ 「그 밖」 = 전체 − 아는 것. 전체를 모르면 그 밖도 «모른다»
   ④ 날은 «서울 기준»으로 가른다 — UTC 로 가르면 아침 9시 전이 어제로 간다
   ⑤ 「계속 새나」는 가운뎃값으로 잰다 — 하루 크게 샌 날이 판정을 뒤집으면 안 된다

   실행: node --test tests/billing-daily.test.js */
const test = require('node:test');
const assert = require('node:assert/strict');
const B = require('../scripts/billing-daily.js');

/* 서울 2026-09-18 00:30 = UTC 2026-09-17 15:30 */
const 서울자정뒤 = Date.UTC(2026, 8, 17, 15, 30);
/* 서울 2026-09-18 23:30 = UTC 2026-09-18 14:30 */
const 서울밤 = Date.UTC(2026, 8, 18, 14, 30);

test('④★★ 날은 «서울 기준»으로 가른다 — UTC 로 가르면 하루가 밀린다', () => {
  assert.equal(B.서울날짜(서울자정뒤), '2026-09-18',
    '★★ 서울 새벽 0시 30분이 전날로 갔습니다 — 하루치가 통째로 옆 날에 얹힙니다');
  assert.equal(B.서울날짜(서울밤), '2026-09-18');
  assert.notEqual(B.서울날짜(서울자정뒤), new Date(서울자정뒤).toISOString().slice(0, 10),
    '★ 서울과 UTC 가 같아졌습니다 — 시차를 안 더하고 있습니다');
});

test('①★★ 첫날은 «모른다»로 남긴다 — 0 은 「그날 안 썼다」로 읽힌다', () => {
  const r = B.날마다({
    [Date.UTC(2026, 8, 16, 3)]: 1000,
    [Date.UTC(2026, 8, 17, 3)]: 1500,
  });
  const 날들 = Object.keys(r).sort();
  assert.equal(r[날들[0]], null, '★★ 첫날에 숫자가 들어갔습니다 — 앞이 없는데 얼마 늘었는지 어떻게 압니까');
  assert.equal(r[날들[1]], 500, '둘째 날은 늘어난 만큼이어야 합니다');
});

test('②★ 같은 날 점이 여럿이면 «마지막» 누적이 그날 끝이다', () => {
  const 어제 = Date.UTC(2026, 8, 16, 3);
  const r = B.날마다({
    [어제]: 100,
    [Date.UTC(2026, 8, 17, 1)]: 200,
    [Date.UTC(2026, 8, 17, 9)]: 500,   // 같은 날 늦은 점
    [Date.UTC(2026, 8, 17, 5)]: 300,   // 순서가 뒤섞여 와도
  });
  assert.equal(r['2026-09-17'], 400, '★ 그날의 마지막 누적(500)에서 앞날(100)을 빼야 합니다');
});

test('③★★ 「그 밖」 = 전체 − 아는 것 · 전체를 모르면 그 밖도 «모른다»', () => {
  const 달 = {
    total: { [Date.UTC(2026, 8, 16, 3)]: 0, [Date.UTC(2026, 8, 17, 3)]: 1000 },
    database: { [Date.UTC(2026, 8, 16, 3)]: 0, [Date.UTC(2026, 8, 17, 3)]: 400 },
    storage: { [Date.UTC(2026, 8, 16, 3)]: 0, [Date.UTC(2026, 8, 17, 3)]: 100 },
  };
  const 표 = B.달표(달);
  const 줄 = 표.find((r) => r.날짜 === '2026-09-17');
  assert.equal(줄.그밖, 500, '★ 전체 1000 − (400+100) = 500 이어야 합니다');
  const 첫줄 = 표.find((r) => r.날짜 === '2026-09-16');
  assert.equal(첫줄.total, null);
  assert.equal(첫줄.그밖, null, '★★ 전체를 모르는 날에 「그 밖 0」이 찍히면 「안 나갔다」로 읽힙니다');
});

test('③-2★ 아는 칸이 하나도 없으면 그 밖을 «전체와 같게» 내놓지 않는다', () => {
  const 표 = B.달표({ total: { [Date.UTC(2026, 8, 16, 3)]: 0, [Date.UTC(2026, 8, 17, 3)]: 700 } });
  const 줄 = 표.find((r) => r.날짜 === '2026-09-17');
  assert.equal(줄.그밖, null,
    '★ 쪼갠 값이 하나도 없는데 「그 밖 = 전체」로 적으면, 갈라 본 적도 없으면서 갈라 본 척이 됩니다');
});

test('⑤★★ 「계속 새나」는 가운뎃값으로 — 하루 크게 샌 날이 판정을 뒤집으면 안 된다', () => {
  /* 날마다 거의 같은 값 + 사고 하루 */
  const 고정 = [550, 560, 540, 570, 555, 565, 10000];
  const r = B.고정비냐(고정);
  assert.ok(r && r.고름,
    '★★ 하루 사고 때문에 「고정비가 아니다」로 뒤집혔습니다 — 그러면 이미 막은 구멍을 또 막으러 갑니다');
  assert.ok(Math.abs(r.가운데 - 557) < 30, '가운뎃값이 날마다 나가는 값에 가까워야 합니다: ' + r.가운데);

  /* 쓰는 만큼 붙는 값 — 들쭉날쭉하면 고정비가 아니다 */
  const 들쭉 = [0, 40, 108, 600, 1200, 3000, 10201];
  const r2 = B.고정비냐(들쭉);
  assert.ok(r2 && !r2.고름, '★ 들쭉날쭉한데 «날마다 같다»고 말하면 엉뚱한 곳을 파게 됩니다');

  /* 잰 날이 너무 적으면 아예 말하지 않는다 */
  assert.equal(B.고정비냐([500, 510]), null, '★ 이틀로 「계속 샌다」를 말하면 안 됩니다');
  assert.equal(B.고정비냐([]), null);
});

test('★ 갈라 보는 항목이 포털 사용액 창과 «같다» — 두 벌이면 한쪽만 고쳐진다', () => {
  const fs = require('node:fs');
  const path = require('node:path');
  const src = fs.readFileSync(path.join(__dirname, '..', 'js', 'pu-billing.js'), 'utf8');
  const m = src.match(/var PARTS = \[([^\]]*)\]/);
  assert.ok(m, '★ pu-billing.js 의 PARTS 를 못 찾았습니다 — 검사가 헛돕니다');
  const 화면것 = m[1].split(',').map((s) => s.trim().replace(/['"]/g, '')).filter(Boolean);
  B.항목들.forEach((c) => {
    assert.ok(화면것.indexOf(c.key) >= 0,
      '★★ 이 표만 아는 항목이 있습니다(' + c.key + ') — 화면과 다른 「그 밖」이 나옵니다');
  });
});
