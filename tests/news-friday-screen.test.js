/* 금요일 자동 준비 — «화면»이 서버와 같은 말을 한다 (대표 지시 2026-09-27)
   ═══════════════════════════════════════════════════════════════════════════
   「매주 금요일 13시에 자동으로 기사와 내용을 정리해서 저장하고 월요일에 자동으로
    보낼수 있게」 · 「금요일에 370-6 메일로 … 검토해달라고 해라」

   서버(functions/news-friday.js)는 다 되어 있었는데 화면이 따라오지 않았다.
   그대로 두면 이렇게 된다 —
     ㉠ 금요일 자동 확정본을 주말에 고치시면 화면이 「⚠ 낡았다 — 이대로 두면 안 나갑니다」
        를 띄운다. 그런데 월요일 서버는 «고치신 내용으로 다시 지어» 보낸다. 거짓 경고다 —
        검토하고 고치신 뒤 안 나갈까 봐 다시 누르시게 된다.
     ㉡ AI 가 «사람 손 없이» 우리 말로 옮긴 기사가 목록에 「✎ 우리 말 있음」으로 뜬다 —
        사람이 쓴 것과 똑같이 보인다. 법인 이름으로 나가는 글이라 사람이 봐야 한다.
     ㉢ 금요일 준비를 «끌 곳»이 없다(서버는 금요일준비 === false 를 읽는데 화면에 칸이 없다).
     ㉣ 서버가 혼자 돌았는지·왜 멈췄는지 볼 곳이 없다.

   ■ 이 검사는 «실제로 돌려» 본다 — 「어딘가에 그 글자가 있다」가 아니다. */

'use strict';

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { stripByName } = require('./strip-comments');
const { cutFn } = require('./cut-fn');

const Core = require('../js/pu-news-core.js');
const ROOT = path.join(__dirname, '..');
const 화면 = stripByName('pu-news.html',
  fs.readFileSync(path.join(ROOT, 'pu-news.html'), 'utf8').replace(/\r\n/g, '\n'));
const 서버 = fs.readFileSync(path.join(ROOT, 'functions/news-friday.js'), 'utf8');

const 회차하나 = () => ({
  열쇠: '2026-10-w1', 회차: { 이름: '2026년 10월 1주' }, 범위: '자문중',
  우리글: '이번 주 한마디입니다.',
  안: { news: [{ 갈래: '기사', 제목: '원문 제목', 우리말: '우리가 쓴 글',
    링크: 'https://example.kr/a', 언론사: '가나일보' }] }
});

function 상태(예약본, 회차, 설정) {
  const 짐 = { App: { 예약본, 설정: 설정 || {} }, Core, esc: (s) => String(s) };
  vm.createContext(짐);
  vm.runInContext(cutFn(화면, 'function 예약본상태('), 짐);
  return vm.runInContext('예약본상태(' + JSON.stringify(회차) + ')', 짐);
}

/* ═══ ㉠ 자동 확정본은 고쳐도 «낡았다»고 하지 않는다 ═══════════════════════ */

test('★★★ 금요일 «자동» 확정본을 고쳐도 화면이 거짓 경고를 안 한다', () => {
  const d = 회차하나();
  const 자동 = { 상태: '준비', 회차열쇠: d.열쇠, 보낼날: '2026-10-05',
    바탕도장: Core.바탕도장(d), 자동: true };

  const 그대로 = 상태(자동, d, { 자동발송: true });
  assert.equal(그대로.꼴, '', '안 고쳤는데 경고가 뜬다');
  assert.match(그대로.글, /금요일 자동/, '★★ 금요일에 자동으로 준비한 것인지 안 알려 준다');

  const 고친 = 회차하나(); 고친.우리글 = '주말에 고쳤습니다';
  const r = 상태(자동, 고친, { 자동발송: true });
  assert.equal(r.꼴, '',
    '★★★ 자동 확정본인데 고쳤다고 「⚠ 낡았다」를 띄운다 — 월요일엔 고친 대로 나가는데 거짓 경고다');
  assert.ok(!/안 나갑니다/.test(r.곁),
    '★★★ 고친 대로 나가는데 「안 나갑니다」라고 한다');
  assert.match(r.곁, /고치신 내용으로/, '★★ 고친 것이 어떻게 되는지 안 말한다');
});

test('★★★ «사람이» 준비한 확정본은 예전 그대로 — 고치면 «낡았다»', () => {
  /* ⚠ 자동이 아닌 확정본은 서버가 다시 짓지 않는다(누르신 순간의 편지가 약속이다).
       자동을 고치다 이쪽까지 조용하게 만들면, 정말 안 나가는 주에 아무 표시가 없다. */
  const d = 회차하나();
  const 사람 = { 상태: '준비', 회차열쇠: d.열쇠, 보낼날: '2026-10-05',
    바탕도장: Core.바탕도장(d) };
  const 고친 = 회차하나(); 고친.우리글 = '고쳤습니다';
  const r = 상태(사람, 고친, { 자동발송: true });
  assert.equal(r.꼴, 'warn', '★★★ 사람 확정본을 고쳤는데 경고가 사라졌다 — 월요일에 안 나간다');
  assert.match(r.곁, /안 나갑니다/);
});

test('★★ 자동발송이 꺼져 있으면 «✔» 옆에 안 나간다고 적는다', () => {
  const d = 회차하나();
  const 자동 = { 상태: '준비', 회차열쇠: d.열쇠, 보낼날: '2026-10-05',
    바탕도장: Core.바탕도장(d), 자동: true };
  const 꺼짐 = 상태(자동, d, { 자동발송: false });
  assert.match(꺼짐.곁, /꺼져 있어/, '★★ 꺼져 있는데 ✔ 만 보여 나가는 줄 아신다');
  const 켜짐 = 상태(자동, d, { 자동발송: true });
  assert.ok(!/꺼져 있어/.test(켜짐.곁), '(재기 값) 켜져 있는데 꺼졌다고 한다');
});

/* ═══ ㉡ AI 가 쓴 줄은 «사람 글»처럼 안 보인다 ═════════════════════════════ */

test('★★★ AI 가 사람 손 없이 옮긴 기사는 목록에 따로 표시된다', () => {
  const 몸 = cutFn(화면, 'function 꼭지칸하나(');
  assert.match(몸, /x\.자동옮김\s*===\s*true/,
    '★★★ 자동옮김 표를 안 본다 — AI 글이 「우리 말 있음」으로 뜬다');
  /* 자동글이면 「우리 말 있음」보다 «먼저» 걸려야 한다 — 뒤에 있으면 늘 우리 말로 뜬다 */
  const 자동자리 = 몸.indexOf('자동글 ?');
  const 사람자리 = 몸.indexOf('✎ 우리 말 있음');
  assert.ok(자동자리 > 0 && 사람자리 > 자동자리,
    '★★★ 「우리 말 있음」이 먼저 걸려 AI 표가 영영 안 뜬다');
  assert.match(몸, /🤖 AI 가 쓴 글/, '★★ AI 표의 글귀가 없다');
});

test('★★★ 줄을 열어 «저장»하면 AI 표가 걷힌다 — 읽으셨다는 뜻', () => {
  const 몸 = cutFn(화면, 'function 우리말저장(');
  assert.match(몸, /delete x\.자동옮김/, '★★★ 저장해도 「아직 안 읽음」이 영영 남는다');
});

test('★★ 서버가 붙이는 표와 화면이 읽는 표가 «같은 이름»이다', () => {
  /* ⚠ 한쪽만 이름을 바꾸면 표가 안 붙거나 안 읽혀 AI 글이 조용히 사람 글처럼 보인다 */
  assert.match(서버, /자동옮김\s*=\s*true/, '서버가 자동옮김 표를 안 붙인다');
});

/* ═══ ㉢ 끄는 곳 ══════════════════════════════════════════════════════════ */

test('★★★ 설정에 「금요일 자동 준비」 스위치가 있고, 저장된다', () => {
  assert.match(화면, /id="cfgFri"/, '★★★ 금요일 준비를 끌 곳이 없다');
  const 저장 = cutFn(화면, 'function 설정저장(');
  assert.match(저장, /금요일준비:\s*g\('cfgFri'\)\s*!==\s*'n'/,
    '★★★ 스위치를 바꿔도 저장이 안 된다 — 또는 «빈 값»이 꺼짐으로 저장된다');
});

test('★★ 화면과 서버가 «같은 잣대»로 끈다 — 꺼짐을 고른 때만', () => {
  /* 서버는 === false 일 때만 건너뛴다. 화면이 빈 값을 false 로 저장하면 옛 판 화면에서
     아무거나 저장하는 순간 금요일 준비가 조용히 꺼진다. */
  assert.match(서버, /설정\.금요일준비\s*===\s*false/, '서버의 끄는 잣대가 바뀌었다');
});

/* ═══ ㉣ 돌았는지 보인다 ══════════════════════════════════════════════════ */

function 기록줄(기록) {
  const 짐 = { App: { 금요일기록: 기록 }, esc: (s) => String(s).replace(/</g, '&lt;') };
  vm.createContext(짐);
  vm.runInContext(cutFn(화면, 'function 금요일기록줄('), 짐);
  return vm.runInContext('금요일기록줄()', 짐);
}

test('★★★ 마지막 금요일 준비가 «어떻게 끝났는지» 화면에 보인다', () => {
  assert.match(기록줄(null), /아직 한 번도 안 돌았습니다/, '★★ 처음엔 아무 말이 없다');

  const 잘됨 = 기록줄({ 날: '2026-10-02', 때: Date.UTC(2026, 9, 2, 4, 0), 확정본: true,
    받는수: 142, AI기사: 3, AI한마디: true, 메일: '보냄', 알림: [] });
  assert.match(잘됨, /142곳/, '★★★ 몇 곳으로 나갈지 안 보인다');
  assert.match(잘됨, /AI 기사 3건/, '★★ AI 가 몇 건 썼는지 안 보인다');
  assert.match(잘됨, /검토 메일 보냄/, '★★ 검토 메일이 갔는지 안 보인다');

  const 못함 = 기록줄({ 날: '2026-10-02', 확정본: false, 못한까닭: '받는 곳이 없습니다',
    메일: '보냄', 알림: [] });
  assert.match(못함, /받는 곳이 없습니다/, '★★★ 왜 못 만들었는지 안 보인다');

  const 메일실패 = 기록줄({ 날: '2026-10-02', 확정본: true, 받는수: 1, 메일: '인증 실패', 알림: [] });
  assert.match(메일실패, /검토 메일 못 보냄/, '★★★ 검토 메일이 안 갔는데 말이 없다');

  const 건너뜀 = 기록줄({ 날: '2026-10-02', 건너뜀: '꺼짐' });
  assert.match(건너뜀, /건너뜀/, '★★ 꺼 두어 건너뛴 것이 안 보인다');
});

test('★★ 기록 글자는 «씻어서» 심는다 — 서버가 쓴 값이라도', () => {
  const r = 기록줄({ 날: '2026-10-02', 확정본: false, 못한까닭: '<img src=x onerror=alert(1)>',
    메일: '보냄', 알림: ['<script>x</script>'] });
  assert.ok(!/<img|<script/.test(r), '★★ 기록 글자가 그대로 심긴다');
});

test('★ 기록을 «맨 끝»에서 읽는다 — 위 차례가 밀리면 다른 칸이 엉뚱한 값을 받는다', () => {
  assert.match(화면, /App\.금요일기록\s*=[\s\S]{0,160}v\[12\]/,
    '★ 금요일 기록을 v[12] 가 아닌 자리에서 읽는다 — 차례를 확인하라');
  assert.match(화면, /newsletter\/fridayLog'\)\.orderByKey\(\)\.limitToLast\(1\)/,
    '★ 마지막 한 줄만 읽지 않는다 — 기록이 쌓이면 통째로 받는다');
});
