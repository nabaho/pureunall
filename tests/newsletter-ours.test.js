test('★★★ 꼬리의 «약속»이 편지가 하는 일과 맞는다', () => {
  /* 꼬리는 받는 분에게 «우리는 이렇게 합니다»라고 약속하는 자리다.
     ⚠⚠ 2026-09-18 에 기사 원문 링크를 걷었다. 꼬리가 그대로 「원문 링크는 함께
       밝힙니다」라고 적혀 있으면, 읽은 분은 링크를 찾다가 못 찾는다 —
       어긋난 안내는 없는 것보다 나쁘다. 값이 아니라 «둘이 맞는가»를 본다. */
  /* ⚠⚠ 2026-09-20 에 또 어긋났다. 기사에 «제목과 원문 링크»가 다시 실리는데
       꼬리는 「직접 정리한 글«만» 싣습니다」라고 적혀 있었다 — 거짓말이 된다.
     ★ 값이 아니라 «둘이 맞는가»를 본다. 그래야 다음에 또 바뀌어도 이 검사가 산다. */
  const 쓴것 = 편지({ news: [기사({ 우리말: '우리 정리' })] });
  const 안쓴것 = 편지({ news: [기사()] });
  [['서식', 안쓴것.서식], ['평문', 안쓴것.본문]].forEach(([어디, 글]) => {
    const 제목나가나 = 글.indexOf('원문제목입니다') >= 0;
    const 정리한것만 = /정리한 글만 싣습니다/.test(글);
    assert.ok(!(정리한것만 && 제목나가나),
      '★★★ ' + 어디 + ' 꼬리는 「정리한 글«만» 싣는다」는데 원문 제목이 나간다');
  });
  [['서식', 쓴것.서식], ['평문', 쓴것.본문]].forEach(([어디, 글]) => {
    assert.ok(/본문을 옮기지 않/.test(글),
      '★★★ ' + 어디 + ' 꼬리가 «안 넘는 선»(본문은 안 옮긴다)을 안 밝힌다');
  });
});

