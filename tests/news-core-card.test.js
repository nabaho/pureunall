/* 뉴스레터 «핵심 카드» — 데이터 층(js/pu-news-core.js) (대표 지시 2026-10-13)
   ═══════════════════════════════════════════════════════════════════════
   「정말 중요한 정보를 핵심만 전달하게 … 아주 쉽고 직관적으로」 → 목업 승인.

   ■ 이 검사가 지키는 것 (값이 아니라 «규칙»)
     ㉠ 카드는 «최대 3장»이고, 제목 없는 것·이상한 주소는 걸러진다 — 사람이 쓴 글이라 믿지 않는다
     ㉡ 「그 밖의 소식 N건」은 «카드로 올린 건»을 뺀 수다 — 링크로 짝짓는다
     ㉢ AI 는 «후보»만 낸다: 번호가 가리키는 건의 링크를 쓰고(AI 가 준 주소는 안 믿는다),
        건에 없는 날짜는 «비운다»(법률 문장은 지어내면 더 나쁘다)
     ㉣ ★ 핵심이 «없는» 회차의 지문(바탕도장)은 예전과 한 글자도 같아야 한다 — 안 그러면 이미 준비된 확정본이 전부 «낡았다»가 된다 */

const test = require('node:test');
const assert = require('node:assert');
const C = require('../js/pu-news-core.js');

const 카드 = (덧) => Object.assign({ 종류: '노동법', 제목: '유급휴일은 꼭 주어야 합니다', 설명: '1주 평균 1회 이상입니다.',
  대상: '모든 사업장', 할일: '휴일 부여 기록 확인', 때: '상시 적용', 링크: 'https://www.law.go.kr/a' }, 덧 || {});

/* ═══ ㉠ 다듬기 ═══ */

test('★ 카드는 «최대 3장»이다 — 억지로 늘리지도 못한다', () => {
  const 많이 = [1, 2, 3, 4, 5].map((n) => 카드({ 제목: '카드 ' + n }));
  const 나옴 = C.핵심다듬기(많이);
  assert.strictEqual(나옴.length, C.핵심한도);
  assert.deepStrictEqual(나옴.map((c) => c.제목), ['카드 1', '카드 2', '카드 3'], '앞의 석 장이 남아야 한다');
  assert.ok(C.핵심한도 <= 3, '대표가 승인한 것은 «3가지»다');
});

test('★ 제목 없는 카드는 카드가 아니다 — 건너뛴다(다음 카드가 그 자리를 채운다)', () => {
  const 나옴 = C.핵심다듬기([카드({ 제목: '   ' }), 카드({ 제목: '둘째' }), { 설명: '제목이 없다' }, null, 'x']);
  assert.deepStrictEqual(나옴.map((c) => c.제목), ['둘째']);
  assert.strictEqual(C.핵심있나({ 핵심: [{ 설명: '제목 없음' }] }), false);
  assert.strictEqual(C.핵심있나({ 핵심: [카드()] }), true);
  assert.strictEqual(C.핵심있나({}), false);
  assert.strictEqual(C.핵심있나(null), false);
});

test('★ 파이어베이스가 돌려주는 «번호 붙은 객체» 꼴도 받는다 — 듬성듬성한 배열은 그렇게 온다', () => {
  const 나옴 = C.핵심다듬기({ 0: 카드({ 제목: '가' }), 2: 카드({ 제목: '나' }), 10: 카드({ 제목: '다' }) });
  assert.deepStrictEqual(나옴.map((c) => c.제목), ['가', '나', '다'], '번호 «숫자» 차례로 펴야 한다(문자 차례면 10 이 2 앞에 선다)');
});

test('★★ 주소는 http(s) 만 — javascript: 같은 것은 «비운다»(카드는 남는다)', () => {
  ['javascript:alert(1)', 'data:text/html,x', 'ftp://a.example', '//evil.example', ' vbscript:x'].forEach((나쁜) => {
    const c = C.핵심다듬기([카드({ 링크: 나쁜 })])[0];
    assert.ok(c, '주소가 나빠도 카드는 남아야 한다');
    assert.strictEqual(c.링크, '', '나쁜 주소가 카드에 남았다: ' + 나쁜);
  });
  assert.strictEqual(C.핵심다듬기([카드({ 링크: ' https://a.example/x ' })])[0].링크, 'https://a.example/x');
});

test('칸마다 글자 한도가 있고, 줄바꿈·제어문자는 한 칸 띄어쓰기로 — 카드 키가 제각각이 되지 않는다', () => {
  const c = C.핵심다듬기([카드({ 제목: '가'.repeat(500), 설명: '나\n\n다\t라\u0000마', 때: '다'.repeat(99), 종류: '' })])[0];
  Object.keys(C.핵심칸한도).forEach((k) => {
    if (typeof c[k] === 'string') assert.ok(c[k].length <= C.핵심칸한도[k], k + ' 칸이 한도(' + C.핵심칸한도[k] + ')를 넘었다');
  });
  assert.ok(!/[\n\t\u0000]/.test(c.설명), '줄바꿈·제어문자가 남았다');
  assert.ok(c.종류, '종류가 비면 기본 딱지가 있어야 한다');
});

/* ═══ ㉡ 그 밖의 소식 ═══ */

test('★ 「그 밖의 소식」은 «카드로 올린 건»을 뺀 수다 — 링크로 짝짓는다', () => {
  const 안 = {
    news: [{ 갈래: '기사', 제목: 'a', 링크: 'https://n.example/1' }, { 갈래: '기사', 제목: 'b', 링크: 'https://n.example/2' }],
    policy: [{ 갈래: '자료', 제목: 'c', 링크: 'https://g.example/3' }],
    case: [{ 갈래: '판례', 제목: 'd', 링크: 'https://p.example/4' }]
  };
  const 셈 = C.핵심밖건수(안, [카드({ 링크: 'https://g.example/3' }), 카드({ 링크: 'https://p.example/4' })]);
  assert.strictEqual(셈.총, 4);
  assert.strictEqual(셈.밖, 2, '카드로 올린 둘을 빼야 한다');
  assert.deepStrictEqual(셈.갈래별, { 기사: 2 }, '갈래별은 «남은 것»만 센다');
});

test('링크가 없는 카드는 어느 건에서 왔는지 모른다 — 그 밖의 소식에서 «함부로 빼지 않는다»', () => {
  const 안 = { news: [{ 갈래: '기사', 제목: 'a', 링크: 'https://n.example/1' }] };
  assert.strictEqual(C.핵심밖건수(안, [카드({ 링크: '' })]).밖, 1);
  assert.strictEqual(C.핵심밖건수(안, []).밖, 1);
  assert.strictEqual(C.핵심밖건수(null, [카드()]).밖, 0, '안이 비어도 넘어지지 않는다');
});

/* ═══ ㉢ AI 후보 ═══ */

const 회차자료 = () => ({
  상태: '초안',
  안: {
    news: [{ 갈래: '기사', 제목: '유급휴일 안내', 우리말: '1주 평균 1회 유급휴일', 링크: 'https://n.example/55', 언론사: '노동뉴스' },
      { 갈래: '기사', 제목: '끄긴 건', 링크: 'https://n.example/off', 안실음: true }],
    policy: [{ 갈래: '자료', 제목: '지원사업 모집', 링크: 'https://g.example/9', 기한: '10/31까지' }],
    case: [{ 갈래: '판례', 제목: '근로자 판단 기준', 링크: 'https://p.example/7', 인용: '대법원 2024도14708 (2026. 2. 12.)' }]
  },
  우리글: '이번 주 한마디'
});

test('후보 거리는 «편지에 실릴 건»만이다 — ㅁ 를 끈 건·한마디는 안 넘긴다', () => {
  const { 거리, 원본 } = C.핵심거리(회차자료());
  assert.strictEqual(거리.length, 3);
  assert.strictEqual(원본.length, 거리.length, '번호와 원본 건이 한 쌍이어야 한다');
  assert.ok(거리.every((r, i) => r.번호 === i), '번호는 원본 목록의 차례다');
  assert.ok(!JSON.stringify(거리).includes('끄긴 건'), 'ㅁ 를 끈 건이 AI 에게 갔다');
  assert.ok(!JSON.stringify(거리).includes('한마디'), '한마디가 AI 에게 갔다');
});

test('★★ AI 에게 «링크를 안 넘긴다» — 주소를 지어내지 못하게', () => {
  const { 거리 } = C.핵심거리(회차자료());
  assert.ok(!/https?:\/\//.test(JSON.stringify(거리)), '링크가 AI 에게 넘어갔다');
  assert.ok(!/https?:\/\//.test(C.핵심후보지시(거리).split('\n\n').slice(0, -1).join('\n\n')), '지시문 자체에 주소가 든다');
});

test('★★★ 후보 지시에 «지어내지 말 것»·«억지로 채우지 말 것»·«없으면 빈 칸»이 있다 — 법률 글이다', () => {
  const 지시 = C.핵심후보지시([]);
  assert.match(지시, /억지로 채우지 마세요/, '3개를 채우려고 끼워 넣게 된다');
  assert.match(지시, /빈 배열/, '해당이 없을 때 «아무것도 안 고른다»를 허락하지 않았다');
  assert.match(지시, /지어내지 마세요/, '지어내기 금지가 빠졌다');
  assert.match(지시, /적힌 그대로/, '날짜·숫자를 «적힌 그대로»만 쓰라는 선이 빠졌다');
  assert.match(지시, /빈 문자열/, '모르는 칸을 비우라는 말이 없다 — AI 가 채우려 든다');
  assert.match(지시, /시행일|기한/, '고르는 기준(시행일·기한)이 빠졌다');
  assert.match(지시, /직접 해야 할 일/, '고르는 기준(할 일)이 빠졌다');
  assert.match(지시, /과태료|분쟁/, '고르는 기준(위험)이 빠졌다');
});

test('★★ 후보 받기: 번호가 가리키는 건의 «우리 링크»를 쓴다 — AI 가 준 주소는 안 믿는다', () => {
  const { 원본 } = C.핵심거리(회차자료());
  const 답 = JSON.stringify([{ 번호: 0, 종류: '노동법', 제목: '유급휴일을 꼭 주세요', 설명: '1주 평균 1회입니다.', 대상: '전 사업장', 할일: '기록 확인', 때: '', 링크: 'https://evil.example/x' }]);
  const 나옴 = C.핵심후보받기(답, 원본);
  assert.strictEqual(나옴.length, 1);
  assert.strictEqual(나옴[0].링크, 'https://n.example/55', 'AI 가 준 주소가 들어갔다');
  assert.ok(나옴[0].출처, '어느 건에서 온 후보인지 사람이 알아야 한다');
});

test('★★★ 후보의 «때»에 든 숫자가 그 건 글에 없으면 비운다 — 날짜를 지어낸 것이다', () => {
  const { 원본 } = C.핵심거리(회차자료());
  const 지어냄 = C.핵심후보받기(JSON.stringify([{ 번호: 1, 종류: '지원 사업', 제목: '지원사업 모집', 설명: '기업 모집', 때: '12/25까지' }]), 원본);
  assert.strictEqual(지어냄[0].때, '', '건에 없는 날짜가 그대로 들어갔다');
  assert.deepStrictEqual(지어냄[0].비운칸, ['때']);
  const 맞음 = C.핵심후보받기(JSON.stringify([{ 번호: 1, 종류: '지원 사업', 제목: '지원사업 모집', 설명: '기업 모집', 때: '10/31까지' }]), 원본);
  assert.strictEqual(맞음[0].때, '10/31까지', '건에 적힌 날짜까지 지워 버렸다');
  assert.ok(!맞음[0].비운칸, '멀쩡한 칸을 비웠다고 알린다');
});

test('후보 받기: 같은 건 두 번·없는 번호·4장째는 버린다 · 깨진 답은 던진다', () => {
  const { 원본 } = C.핵심거리(회차자료());
  const 행 = (번호, 제목) => ({ 번호, 종류: '꼭 확인', 제목, 설명: '' });
  const 나옴 = C.핵심후보받기('```json\n' + JSON.stringify([행(0, '가'), 행(0, '가 또'), 행(99, '없는 번호'), 행(-1, '음수'), 행(1, '나'), 행(2, '다'), 행(0, '넷째')]) + '\n```', 원본);
  assert.deepStrictEqual(나옴.map((c) => c.제목), ['가', '나', '다']);
  assert.throws(() => C.핵심후보받기('이건 JSON 이 아닙니다', 원본), /읽지 못했습니다/);
  assert.throws(() => C.핵심후보받기('{"a":1}', 원본), /모양이 맞지 않습니다/);
  assert.deepStrictEqual(C.핵심후보받기('[]', 원본), [], '«고를 것이 없다»는 정당한 답이다');
});

/* ═══ ㉣ 지문 — 핵심이 없는 회차는 예전과 한 글자도 같아야 한다 ═══ */

test('★★★ 핵심이 «없는» 회차의 지문은 핵심 칸이 있어도 없어도(빈 것·제목 없는 것) 같다', () => {
  const 바탕 = { 회차: { 이름: '2026년 10월 2주차', 기간: 'a~b' }, 범위: '자문중', 우리글: '가',
    안: { news: [{ 제목: 'x', 링크: 'https://a.example/1' }] }, 지역뉴스: [] };
  const 기준 = C.바탕도장(바탕);
  [undefined, null, [], {}, [{ 설명: '제목 없음' }], 'x'].forEach((핵) => {
    assert.strictEqual(C.바탕도장(Object.assign({}, 바탕, { 핵심: 핵 })), 기준,
      '핵심이 없는데 지문이 달라졌다 — 이미 준비된 확정본이 전부 «낡았다»가 된다: ' + JSON.stringify(핵));
  });
});

test('핵심 카드를 고치면 지문이 달라진다 · 후보를 고쳐도 안 달라진다(안 나가는 것이다)', () => {
  const 바탕 = { 회차: { 이름: 'w', 기간: 'a~b' }, 범위: '자문중', 우리글: '가', 안: {}, 지역뉴스: [] };
  const 하나 = C.바탕도장(Object.assign({}, 바탕, { 핵심: [카드()] }));
  assert.notStrictEqual(하나, C.바탕도장(바탕), '카드를 넣었는데 지문이 같다 — 고쳐도 «확정본이 낡았다»가 안 뜬다');
  assert.notStrictEqual(하나, C.바탕도장(Object.assign({}, 바탕, { 핵심: [카드({ 할일: '다른 할 일' })] })), '카드 글을 고쳤는데 지문이 같다');
  assert.notStrictEqual(하나, C.바탕도장(Object.assign({}, 바탕, { 핵심: [카드(), 카드({ 제목: '둘째' })] })));
  assert.strictEqual(C.바탕도장(Object.assign({}, 바탕, { 핵심후보: [카드()] })), C.바탕도장(바탕), '안 나가는 후보가 지문을 바꾼다');
});
