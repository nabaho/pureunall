'use strict';
/* 창을 «한눈에 들어오게» — 글자를 키우고, 뒤 빈 자리에 우리 얼굴을 둔다
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-13:
     「팝업창 뒤 배경에 좀 뭔가를 넣고 싶다. 푸른노무법인의 안내등
      내용이 너무 무미 건조하다. 아니면 급여제도 활용가이드 등의 글자를 좀더
      크게하고 팝업의 글자를 좀더 많이 크게해서 쉽게 한번에 눈에 들어오게
      바꿨으면 좋겠다.」

   ⚠ 창 뒤가 «종이빛 한 장»뿐이라, 넓은 화면일수록 휑했다.
   ⚠ 글자는 편지 그대로(13.5px 제목·14px 본문)라 창에서도 작았다.

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ①★★ 키우는 길은 «돋보기»다 — 글자마다 크기를 다시 매기지 않는다
        (그러면 편지와 창이 서로 다른 글이 된다)
     ② 뒤 자리에 «우리 것»을 둔다 — 편지가 아니라
     ③★★★ 뒤에 둔 것이 «누르기를 막지 않는다» — 바깥을 누르면 닫혀야 한다
     ④ 뒤가 여전히 «꽉» 덮는다 — 편지가 비치면 두 벌처럼 보인다
     ⑤ 지어내지 않는다 — 이름과 전화만 쓴다

   ⚠ 인터넷도 브라우저도 두드리지 않는다. */

const test = require('node:test');
const assert = require('node:assert');
const NV = require('../functions/news-view.js');

const 쪽 = () => NV.쪽('2026년 09월 2주차', '<div id="n-policy-0" data-pop="1">가</div>');

/* ══════════════════════════════════════════════════════════════════════════
   ① 글자를 «돋보기»로 키운다
   ══════════════════════════════════════════════════════════════════════════ */

test('★★ 창 속 글자를 «돋보기»로 키운다 — 글자마다 다시 매기지 않는다', () => {
  /* ⚠⚠ 제목·본문·곁말을 하나씩 키우면 편지와 창이 «서로 다른 글»이 된다.
       비율만 키우면 편지가 정한 결(제목이 본문보다 얼마나 큰가)이 그대로 산다. */
  const m = /#pop\s+\.bd\{([^}]*)\}/.exec(쪽());
  assert.ok(m, '#pop .bd 규칙을 못 찾았다');
  assert.ok(/zoom:\s*1\.[12]\d?/.test(m[1]),
    '★★ 돋보기가 없다 — 글자가 편지 그대로라 창에서도 작다: ' + m[1]);
});

test('★★★ 글자마다 «크기를 다시 매기지» 않는다', () => {
  /* ⚠⚠ 여기가 무너지면 메일로 본 것과 눌러서 본 것이 달라진다. */
  const h = 쪽();
  const 낱개 = /#pop\s+\.bd\s+(p|div|span|td|table|b|a|strong)\b[^{]*\{/.exec(h);
  assert.ok(!낱개,
    '★★★ 창이 편지 속 글자를 하나씩 고친다(' + (낱개 && 낱개[0]) + ')');
});

test('★ 글자를 키운 만큼 창도 «넓힌다» — 안 그러면 줄만 잘게 쪼개진다', () => {
  const m = /#pop\s+\.in\{([^}]*)\}/.exec(쪽());
  assert.ok(m, '#pop .in 규칙을 못 찾았다');
  const w = /width:\s*min\((\d+)px/.exec(m[1]);
  assert.ok(w, '창 너비 규칙을 못 찾았다');
  assert.ok(Number(w[1]) >= 720,
    '★ 창이 아직 좁다(' + w[1] + 'px) — 키운 글자가 잘게 쪼개진다');
  assert.ok(/94vw|9\dvw/.test(m[1]), '좁은 화면에서 넘친다');
});

/* ══════════════════════════════════════════════════════════════════════════
   ② 뒤 자리에 «우리 것»을 둔다
   ══════════════════════════════════════════════════════════════════════════ */

test('★★ 창 뒤에 «우리 얼굴»이 있다 — 종이빛 한 장은 휑하다', () => {
  const h = 쪽();
  assert.ok(/id="popbg"|class="bg"/.test(h),
    '★★ 창 뒤에 아무것도 없다');
  const m = /<div[^>]*(?:id="popbg"|class="bg")[^>]*>([\s\S]*?)<\/div>\s*<div class="in">/.exec(h);
  assert.ok(m, '뒤 자리의 속을 못 찾았다');
  assert.ok(m[1].indexOf('푸른노무법인') >= 0, '뒤에 법인 이름이 없다');
  assert.ok(/041-556-0035/.test(m[1]), '뒤에 물어볼 길이 없다');
});

test('★★★ 뒤에 둔 것이 «누르기를 막지 않는다» — 바깥을 누르면 닫혀야 한다', () => {
  /* ⚠⚠ 닫는 길은 셋이다: 닫기 단추 · 바깥 누르기 · Esc.
       뒤 자리를 덮개처럼 깔면 «바깥 누르기»가 통째로 죽는다 —
       그런데 화면은 멀쩡해 보여, 닫으려다 안 닫히는 것으로만 겪게 된다. */
  const h = 쪽();
  const m = /#pop\s+\.bg\{([^}]*)\}/.exec(h);
  assert.ok(m, '#pop .bg 규칙을 못 찾았다');
  assert.ok(/pointer-events:\s*none/.test(m[1]),
    '★★★ 뒤 자리가 누르기를 가로챈다 — 바깥을 눌러도 안 닫힌다');
  /* 닫는 길 셋이 그대로 있나 */
  const 글 = /<script>([\s\S]*?)<\/script>/.exec(h)[1];
  assert.ok(글.indexOf('e.target===p') >= 0, '바깥 누르기로 닫는 길이 사라졌다');
  assert.ok(글.indexOf('Escape') >= 0, 'Esc 로 닫는 길이 사라졌다');
  assert.ok(글.indexOf('popx') >= 0, '닫기 단추로 닫는 길이 사라졌다');
});

test('★★ 뒤가 여전히 «꽉» 덮는다 — 편지가 비치면 두 벌처럼 보인다', () => {
  const m = /#pop\{[^}]*background:([^;]+);/.exec(쪽());
  assert.ok(m, '창 바탕 규칙을 못 찾았다');
  assert.ok(!/rgba|transparent|\.\d/.test(m[1]),
    '★★ 창 바탕이 비친다(' + m[1].trim() + ')');
});

test('★ 뒤 자리에 «지어낸 것»이 없다 — 이름과 전화뿐이다', () => {
  /* ⚠ 주소·대표자·자격 같은 것을 지어 넣으면 손님이 그것을 사실로 읽는다.
       코드가 이미 아는 것(이름·전화)만 쓴다. */
  const m = /<div[^>]*(?:id="popbg"|class="bg")[^>]*>([\s\S]*?)<\/div>\s*<div class="in">/.exec(쪽());
  const 글 = m[1].replace(/<[^>]+>/g, ' ').replace(/\s+/g, ' ').trim();
  assert.ok(!/[0-9]{2,3}-[0-9]{3,4}-[0-9]{4}/.test(글.replace('041-556-0035', '')),
    '★ 모르는 전화번호가 들어갔다: ' + 글);
  assert.ok(!/(시|군|구)\s|로\s\d|번지|빌딩|\d+층/.test(글),
    '★ 지어낸 주소가 들어갔다: ' + 글);
});
