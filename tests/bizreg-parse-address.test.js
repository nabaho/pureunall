'use strict';
/* 「ocr 한거 확인했는데 주소가 빠진적도 있다」 (대표 지시 2026-09-14)

   ■ 무엇이 빠졌나 — 실측
   2026-09-14 에 올린 법인 사업자등록증에서 **사업장 소재지가 통째로 안 담겼다.**
   원본은 또렷했고(390KB · 1838×2600) 사람 눈에는 소재지가 두 줄이나 보인다.
   그 판독은 «무료 판독 길»(read.free=true · freeFrom='ocr')이었다 — 즉 Gemini 가
   아니라 **우리 파서**(bizregParse)가 만든 결과였다. 까닭이 셋이었다:

     ① **시·도 목록에 정식 명칭이 없었다.** 국세청 등록증은 늘 「충청남도」로 찍히는데
        목록에는 「충남」만 있었다 — 충청·전라·경상 도의 등록증은 아예 안 걸린다.
     ② **첫 규칙이 「본 점 소 재 지」 줄의 콜론에서 막혔다.** 담는 글자에 콜론이 없어,
        사업장 소재지 뒤에 본점 소재지가 한 줄 더 오는 **법인** 등록증이 통째로 실패했다
        (개인사업자 등록증에는 그 줄이 없어 여태 안 드러났다).
     ③ 걸리더라도 **다음 칸 이름이 꼬리에 붙었다** — 「… 103 본 점 소 재 지」.

   ■ 덤으로 드러난 것 — 「발 급 사 유 : 대표자 변경」
   같은 등록증에서 **대표자가 「변경」으로** 담겨 있었다. 대표자 라벨이 흐려 안 읽히면
   그 줄이 «유일하게 남은 대표자 글자»라 반드시 걸린다. 사람 이름이 아닌 말은 안 담는다.

   ⚠ 예시는 늘 가나상사·홍길동이다 — 진짜 의뢰인 이름을 검사에 적지 않는다.

   실행: node --test tests/bizreg-parse-address.test.js */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');

const R = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(R, 'js', 'pu-doc-read.js'), 'utf8');

/* 파서 하나만 떼어 돌린다 — 층 전체를 싣지 않아도 이 규칙은 그대로 재진다. */
function parser() {
  const m = src.match(/function bizregParse\(text\)[\s\S]*?\n  \}/);
  assert.ok(m, '★ bizregParse 를 못 찾았습니다');
  const ctx = { RegExp, String, Number, Object };
  vm.createContext(ctx);
  vm.runInContext('function bizNoValid(){return true;}\n' + m[0] + '\nthis.p = bizregParse;', ctx);
  return ctx.p;
}
const parse = parser();

/* 국세청 법인 사업자등록증의 «실제 줄 모양» — 라벨에 낱자 사이 빈칸이 들어간다. */
function 등록증(o) {
  o = o || {};
  const 도 = o.도 || '충청남도';
  return [
    '사업자등록증',
    '( 법인사업자 )',
    '등록번호 : 123-81-03842',
    '법 인 명 ( 단 체 명 ) : 가나상사주식회사',
    o.대표자흐림 ? '' : '대 표 자 : 홍길동',
    '개 업 연 월 일 : 2003 년 02 월 15 일    법인등록번호 : 161411-0012430',
    '사 업 장  소 재 지 : ' + 도 + ' 가나시 나다로 103',
    o.본점 === false ? '' : '본 점 소 재 지 : ' + 도 + ' 가나시 나다로 103',
    '사 업 의 종 류 : 업태 서비스   종목 검수',
    '발 급 사 유 : 대표자 변경',
    '2024 년 06 월 11 일',
    '가 나 세 무 서 장'
  ].filter(Boolean).join('\n');
}

/* ══════ ① 주소 — 시·도 «정식 명칭»에서 빠지지 않는다 ══════ */

const 도들 = ['충청남도', '충청북도', '전라남도', '전라북도', '경상남도', '경상북도',
  '강원특별자치도', '제주특별자치도', '세종특별자치시', '서울특별시', '경기도',
  '충남', '경북', '서울'];

test('★★ 시·도를 «정식 명칭»으로 적어도 주소를 읽는다 — 등록증은 늘 정식 명칭이다', () => {
  const 못읽은 = [];
  도들.forEach(function (도) {
    const r = parse(등록증({ 도: 도 }));
    if (!r.address || r.address.indexOf(도) !== 0) 못읽은.push(도 + ' → ' + (r.address || '(없음)'));
  });
  assert.deepEqual(못읽은, [],
    '★★ 이 도의 등록증에서 주소가 빠집니다:\n  ' + 못읽은.join('\n  ') + '\n' +
    '  국세청 등록증은 「충남」이 아니라 「충청남도」로 찍힙니다 — 줄임말만 적어 두면\n' +
    '  충청·전라·경상 도의 업체 주소가 통째로 안 담깁니다.');
});

test('★★ 「본 점 소 재 지」 줄이 있어도 읽는다 — 법인 등록증은 늘 두 줄이다', () => {
  const 있음 = parse(등록증({ 본점: true }));
  const 없음 = parse(등록증({ 본점: false }));
  assert.equal(있음.address, '충청남도 가나시 나다로 103',
    '★★ 본점 줄이 한 줄 더 오면 통째로 실패했습니다 — 개인사업자 등록증에는 그 줄이\n' +
    '  없어서 여태 안 드러났을 뿐, 법인은 **전부** 이 모양입니다.');
  assert.equal(없음.address, '충청남도 가나시 나다로 103');
});

test('★★ 주소 꼬리에 «다음 칸 이름»이 붙지 않는다 — 그대로 업체관리로 들어간다', () => {
  const r = parse(등록증({ 도: '충남' }));
  assert.equal(r.address, '충남 가나시 나다로 103',
    '★★ 「… 103 본 점 소 재 지」 처럼 라벨이 딸려 붙었습니다. 주소가 아닌 글자가\n' +
    '  업체 주소로 저장되고, 나중에 그것으로 우편물이 나갑니다.');
  assert.ok(!/소\s*재\s*지|본\s*점|업\s*태|종\s*목/.test(r.address), '★ 라벨이 섞였습니다');
});

test('★ 사업장과 본점이 다르면 «사업장» 쪽을 쓴다', () => {
  const t = [
    '등록번호 : 123-81-03842',
    '법 인 명 ( 단 체 명 ) : 가나상사주식회사',
    '대 표 자 : 홍길동',
    '사 업 장  소 재 지 : 충청남도 가나시 나다로 103',
    '본 점 소 재 지 : 서울특별시 마바구 사아로 9',
    '사 업 의 종 류 : 업태 서비스   종목 검수'
  ].join('\n');
  assert.equal(parse(t).address, '충청남도 가나시 나다로 103',
    '★ 업체관리가 쓰는 것은 «사업장» 주소입니다 — 본점을 담으면 엉뚱한 곳으로 갑니다');
});

/* ══════ ② 대표자 — 사람 이름이 아닌 말을 담지 않는다 ══════ */

test('★★ 「발 급 사 유 : 대표자 변경」을 대표자로 읽지 않는다', () => {
  const r = parse(등록증({ 대표자흐림: true }));
  assert.notEqual(r.ceo, '변경',
    '★★ 실제로 ceo 가 「변경」으로 저장돼 있었습니다. 대표자 라벨이 흐려 안 읽히면\n' +
    '  「발급 사유: 대표자 변경」이 «유일하게 남은 대표자 글자»라 반드시 걸립니다.');
  assert.ok(!r.ceo,
    '★ 틀린 이름을 담느니 «비워 두는 편»이 낫습니다 — 비어 있으면 사람이 채웁니다.');
});

test('★★ 그래도 «진짜 대표자»는 그대로 읽는다 — 막느라 못 읽으면 안 된다', () => {
  const r = parse(등록증({}));
  assert.equal(r.ceo, '홍길동', '★★ 사유 낱말을 막다가 멀쩡한 이름까지 막았습니다');
  assert.equal(r.name, '가나상사주식회사', '★ 상호가 틀렸습니다');
  assert.equal(r.bizNo, '123-81-03842');
  assert.equal(r.bizType, '서비스');
  assert.equal(r.bizCategory, '검수');
});

test('★ 사유 줄에 «진짜 이름»이 적힌 경우는 살린다 — 줄을 통째로 버리지 않는다', () => {
  const t = [
    '등록번호 : 123-81-03842',
    '법 인 명 ( 단 체 명 ) : 가나상사주식회사',
    '사 업 장  소 재 지 : 충청남도 가나시 나다로 103',
    '발 급 사 유 : 대표자 김철수 으로 변경'
  ].join('\n');
  assert.equal(parse(t).ceo, '김철수',
    '★ 막는 것은 «낱말»이지 줄이 아닙니다 — 줄째 버리면 이런 등록증의 대표자를 놓칩니다');
});

/* ══════ ③ 이 파서를 쓰는 길이 «실제로» 있다 ══════ */

test('★ 무료 판독이 이 파서를 쓴다 — 안 쓰면 이 검사가 아무것도 안 지킨다', () => {
  assert.match(src, /function freeRead\(/, '★ 무료 판독 입구가 없습니다');
  assert.match(src, /bizregFields\(/, '★ 무료 판독이 파서를 안 씁니다');
  assert.match(src, /read\.free = true/, '★ 무료 판독 표시가 없습니다');
});
