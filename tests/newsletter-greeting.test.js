/* 인사 칸 — 명절·특별한 주에만 나오는 칸 (대표 지시 2026-09-23)
   ═══════════════════════════════════════════════════════════════════════════
   「뉴스레터에 부정기적인 특별 판례나 추석 설 명절 인사등을 영상 또는 화면으로도
    보내고 싶은데 이부분도 시스템 만들수 있나?」

   ■ 무엇을 만들었나
     머리 바로 아래에 «그림 한 장 + 인사말»이 들어가는 칸을 두었다.
     넣은 주에만 나오고, 안 넣은 주에는 «통째로 사라진다».

   ■ 이 검사가 지키는 것 — 대부분은 «안 바뀌는 것»을 지킨다
     ㉠ 인사를 안 넣은 주의 편지는 «한 글자도» 안 바뀐다      ← 제일 중요하다
     ㉡ 넣으면 «머리 다음, 꼭지 앞»에 선다
     ㉢ 남의 서버 그림은 «안 실린다» — 열람 시각이 새는 구멍이다
     ㉣ 평문에도 «같이» 실린다 — 서식만 고치는 실수가 2026-09-18 에 실제로 났다
     ㉤ 인사만 있고 꼭지가 비어도 편지가 «만들어진다» (명절 인사만 보내는 주)
     ㉥ ▶ 는 그림 «위에 겹치지 않는다» — 아웃룩에서 겹친 글자는 무너진다
     ㉦ 움직이는 화면이 없으면 ▶ 도 «없다» — 눌러도 아무 데도 안 가는 손잡이는 안 둔다 */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { 주석걷기 } = require('./helpers/strip-comments.js');

const 뿌리 = path.join(__dirname, '..');
const C = require('../js/pu-news-core.js');
const T = require('../js/pu-news-tpl.js');
const 화면 = 주석걷기(fs.readFileSync(path.join(뿌리, 'pu-news.html'), 'utf8'));

const 설 = { 회사이름: '푸른노무법인', 보내는주소: '370-6@hanmail.net' };
const 우리그림 = 'https://nabaho.github.io/pureunall/img/news-banner.png';
const 남의그림 = 'https://evil.example.com/track.png';

const 기사한줄 = {
  갈래: '기사', 제목: '원문제목입니다', 우리말: '우리가 쓴 줄입니다.',
  링크: 'https://www.labortoday.co.kr/news/articleView.html?idxno=1',
  언론사: '매일노동뉴스'
};

function 편지(덧, 안) {
  return T.편지짓기(
    Object.assign({ 회차: C.회차('2026-09-28'), 안: 안 === undefined ? { news: [기사한줄] } : 안 },
      덧 || {}),
    설, { 미리보기: true });
}

/* ═══ ㉠ 인사를 «안 넣으면» 편지가 한 글자도 안 바뀐다 ═══════════════════
   ★ 이 검사 하나가 나머지 전부보다 중요하다. 인사 칸은 «부정기»라
     쉰 주 가운데 마흔여덟 주는 안 쓴다. 그 마흔여덟 주가 안전해야 한다.
   ⚠ 글자 하나까지 견준다 — 「거의 같다」로 두면 빈 칸·빈 줄이 슬그머니 들어온다. */
test('★★★ 인사가 없으면 평소 편지가 한 글자도 안 바뀐다', () => {
  const 없음 = 편지({});
  const 빈값 = 편지({ 인사: {} });
  const 빈글 = 편지({ 인사: { 그림: '', 제목: '  ', 글: '' } });
  assert.ok(없음 && 없음.서식, '편지가 만들어져야 한다');
  assert.strictEqual(빈값.서식, 없음.서식, '빈 인사가 서식을 바꾸면 안 된다');
  assert.strictEqual(빈값.본문, 없음.본문, '빈 인사가 평문을 바꾸면 안 된다');
  assert.strictEqual(빈글.서식, 없음.서식, '공백뿐인 인사도 서식을 바꾸면 안 된다');
  assert.strictEqual(빈글.본문, 없음.본문, '공백뿐인 인사도 평문을 바꾸면 안 된다');
});

/* ═══ ㉡ 넣으면 «머리 다음, 꼭지 앞» ═════════════════════════════════════
   ⚠ 자리를 «글자»로 박지 않는다 — 차례만 본다. 머리 글귀가 바뀌어도 안 깨진다. */
test('인사는 머리 다음·꼭지 앞에 선다', () => {
  const r = 편지({ 인사: { 그림: 우리그림, 제목: '풍성한 한가위 되십시오', 글: '고맙습니다.' } });
  const h = r.서식;
  const 인사자리 = h.indexOf('풍성한 한가위 되십시오');
  const 머리자리 = h.indexOf('PUREUN LABOR LAW FIRM');
  const 꼭지자리 = h.indexOf('우리가 쓴 줄입니다.');
  assert.ok(인사자리 > 0, '인사 제목이 편지에 있어야 한다');
  assert.ok(머리자리 > 0 && 꼭지자리 > 0, '머리와 꼭지가 있어야 자리를 견준다');
  assert.ok(머리자리 < 인사자리, '인사는 머리 «다음»이다');
  assert.ok(인사자리 < 꼭지자리, '인사는 꼭지 «앞»이다');
  assert.ok(h.includes('고맙습니다.'), '인사말이 실려야 한다');
  /* ★ 차림표(목차)보다도 «앞»이다 — 대표께서 승낙하신 목업 순서다(2026-09-23).
     ⚠ 처음 만들 때 이것을 안 봐서 차림표 «뒤»에 붙었다 — 화면으로 보고서야 알았다.
       인사는 편지를 여는 말이다. 목차 뒤에 오면 붙잡힌 차림표 밑으로 지나가
       목차의 일부처럼 보인다. */
  const 차림표자리 = h.indexOf('data-stick="1"');
  assert.ok(차림표자리 > 0, '차림표가 있어야 자리를 견준다');
  assert.ok(인사자리 < 차림표자리, '인사는 차림표 «앞»이다 — 목업 순서');
});

/* ═══ ㉢ 남의 서버 그림은 안 실린다 ══════════════════════════════════════
   ⚠ 이것은 «모양»이 아니라 «새는 구멍»이다. 남의 서버 그림을 그대로 실으면
     받는 쪽이 편지를 여는 순간 그 서버가 「언제 열었나」를 가져간다.
   ★ 발송기(mail-send.js IMG_HOST_OK)가 한 번 더 막지만, 여기서도 막는다 —
     문이 둘이라야 한쪽이 뚫려도 안 샌다. */
test('★★ 인사 그림도 «우리 것»만 실린다', () => {
  const 남 = 편지({ 인사: { 그림: 남의그림, 제목: '인사말입니다' } });
  assert.ok(!남.서식.includes('evil.example.com'), '남의 서버 그림이 실리면 안 된다');
  assert.ok(남.서식.includes('인사말입니다'), '그림이 걸려도 «글»은 남아야 한다');
  const 우 = 편지({ 인사: { 그림: 우리그림, 제목: '인사말입니다' } });
  assert.ok(우.서식.includes(우리그림), '우리 그림은 실려야 한다');
});

/* ═══ ㉣ 평문에도 «같이» 실린다 ══════════════════════════════════════════
   ⚠⚠ 2026-09-18 에 서식만 고치고 평문을 잊어, 서식을 못 읽는 프로그램으로
     받으신 분에게 다른 편지가 간 적이 있다. 그 자리를 여기서 막는다. */
test('★★ 평문에도 인사가 실린다 — 서식만 고치면 걸린다', () => {
  const r = 편지({ 인사: { 그림: 우리그림, 제목: '풍성한 한가위 되십시오',
    글: '올 한 해도 함께해 주셔서 고맙습니다.', 서명: '대표노무사 권형하 드림' } });
  assert.ok(r.본문.includes('풍성한 한가위 되십시오'), '평문에 인사 제목이 있어야 한다');
  assert.ok(r.본문.includes('올 한 해도 함께해 주셔서 고맙습니다.'), '평문에 인사말이 있어야 한다');
  assert.ok(r.본문.includes('대표노무사 권형하 드림'), '평문에 서명이 있어야 한다');
  /* 평문에 그림 주소를 쏟지 않는다 — 글로 읽는 사람에게 주소는 소음이다 */
  assert.ok(!r.본문.includes(우리그림), '평문에 그림 주소를 적지 않는다');
});

/* ═══ ㉤ 인사만 있어도 편지가 만들어진다 ═════════════════════════════════
   ★ 「실을 것이 없으면 안 만든다」는 규칙이 있다 — 빈 껍데기를 막는 규칙이다.
     그런데 명절 인사만 보내는 주가 있다. 인사는 «사람이 손으로 쓴 것»이라
     실수로 생기지 않는다 — 그래서 실을 것으로 친다. */
test('인사만 있고 꼭지가 비어도 편지가 만들어진다', () => {
  const 빈꼭지 = 편지({ 인사: { 제목: '새해 복 많이 받으십시오' } }, {});
  assert.ok(빈꼭지 && 빈꼭지.서식, '인사만 있어도 편지가 나와야 한다');
  assert.ok(빈꼭지.서식.includes('새해 복 많이 받으십시오'));
  /* 그래도 «아무것도 없으면» 여전히 안 만든다 */
  assert.strictEqual(편지({}, {}), null, '인사도 꼭지도 없으면 편지를 만들지 않는다');
});

/* ═══ ㉥㉦ ▶ 는 그림 «아래» 띠로, 그것도 갈 곳이 있을 때만 ═════════════
   ⚠ 그림 «위»에 겹친 글자는 아웃룩에서 무너진다 — position 을 모른다.
     그래서 겹치지 않고 아래 한 줄로 내린다.
   ⚠ 움직이는 화면이 없으면 ▶ 도 없다. 눌러도 아무 데도 안 가는 손잡이를
     두면 받는 분이 한 번 눌러 보고 «고장 난 편지»로 여긴다. */
test('★★ ▶ 는 움직이는 화면이 있을 때만, 그림 위에 겹치지 않는다', () => {
  const 없 = 편지({ 인사: { 그림: 우리그림, 제목: '인사말입니다' } });
  assert.ok(!없.서식.includes('▶'), '갈 곳이 없으면 ▶ 를 그리지 않는다');

  const 있 = 편지({ 인사: { 그림: 우리그림, 제목: '인사말입니다',
    움직임: 'https://asia-northeast3-pureun-erp.cloudfunctions.net/newsShow?i=x' } });
  assert.ok(있.서식.includes('▶'), '갈 곳이 있으면 ▶ 를 그린다');
  assert.ok(!/position\s*:\s*absolute/.test(있.서식),
    '겹치기(position:absolute)는 아웃룩에서 무너진다 — 쓰지 않는다');
  /* 평문에도 «볼 곳»이 남아야 한다 — 서식을 못 읽는 분도 눌러 보실 수 있게 */
  assert.ok(있.본문.includes('newsShow'), '평문에도 보는 주소가 있어야 한다');
});

/* ═══ 글자가 새지 않는다 ════════════════════════════════════════════════ */
test('인사 글자는 씻긴다 — 태그가 편지로 새지 않는다', () => {
  const r = 편지({ 인사: { 제목: '<script>나쁜것</script>', 글: '따옴표"와 <b>굵게</b>' } });
  assert.ok(!r.서식.includes('<script>'), '태그가 그대로 새면 안 된다');
  assert.ok(!r.서식.includes('<b>굵게</b>'), '남이 넣은 태그가 살아나면 안 된다');
  assert.ok(r.서식.includes('&lt;script&gt;'), '글자로 바뀌어 보여야 한다');
});

/* ═══ 화면에 넣는 칸이 있는가 ═══════════════════════════════════════════
   ⚠ 값을 박지 않는다 — «칸이 있는가»만 본다. */
test('관리 화면에 인사를 넣는 칸이 있다', () => {
  assert.ok(/인사/.test(화면), '화면에 인사 칸이 있어야 한다');
  ['greetTitle', 'greetBody', 'greetImg'].forEach((id) => {
    assert.ok(new RegExp('id\\s*=\\s*["\']' + id + '["\']').test(화면),
      '화면에 ' + id + ' 칸이 있어야 한다');
  });
});
