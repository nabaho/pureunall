'use strict';
/* 홈페이지 공지(주간 노동 브리핑)도 «골고루»
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-14: 뉴스레터를 골고루로 바꾼 뒤,
   「홈페이지 공지도 골고루로 맞출까요?」에 「네」.

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ① 공지도 신문사가 돌아가며 앞자리를 갖는다
     ② 고르기는 «버리지 않는다» — 차례만 바꾼다. 몇 건까지는 글짓기가 정한다
     ③ 날짜 창과 뺄말 거르개는 그대로다 — 골고루가 그것을 덮어쓰지 않는다
     ④ «잣대가 둘»이 되지 않게 — 화면(Core)과 서버(news-brief)가 같은 답을 낸다

   ⚠⚠ ④ 가 이 검사의 핵심이다. functions/ 는 따로 배포되어 ../js 를 못 읽는다.
     그래서 같은 규칙을 두 군데 적을 수밖에 없는데, 두 군데 적힌 규칙은 «반드시»
     한쪽만 고쳐진다. 그때 화면에서 본 차례와 공지에 나간 차례가 달라지고,
     아무도 그것을 모른다. 둘을 나란히 세워 견주는 검사가 그 유일한 그물이다. */

const test = require('node:test');
const assert = require('node:assert');

const B = require('../functions/news-brief.js');
const C = require('../js/pu-news-core.js');

/* 모은날이 늦은 것(새 것)을 한 신문사로 몰아 둔다 — 실제로 이렇게 온다 */
function 창고(줄들) {
  const o = {};
  줄들.forEach(function (x, i) { o['k' + i] = x; });
  return o;
}
function 한줄(누구, 날, 제목) {
  return { 제목: 제목 || (누구 + ' 근로시간 소식 ' + 날), 링크: 'https://x.test/' + 누구 + 날,
    언론사: 누구, 모은날: 날 };
}

test('★★ 서버에도 골고루가 있다', () => {
  assert.equal(typeof B.골고루, 'function', '★★ news-brief 에 골고루가 없다');
});

test('★★★ 화면과 서버가 «같은 답»을 낸다 — 잣대가 둘이 되면 안 된다', () => {
  /* ⚠⚠ 한쪽만 고쳐지는 날이 반드시 온다. 그날 이 검사가 붉어야 한다.
       붉지 않으면, 화면에서 고르신 차례와 공지에 나간 차례가 달라진 채로 나간다. */
  const 거리 = [
    { 언론사: '가', 제목: 'a1' }, { 언론사: '가', 제목: 'a2' },
    { 언론사: '나', 제목: 'b1' }, { 언론사: '다', 제목: 'c1' },
    { 언론사: '', 제목: '출처없음' }, { 언론사: '나', 제목: 'b2' },
    { 언론사: '가', 제목: 'a3' }
  ];
  /* ⚠ 서로 다른 벌을 준다 — 같은 벌을 주면 앞 함수가 비운 통을 뒤가 받는다 */
  const 서버것 = B.골고루(거리.map((x) => Object.assign({}, x)));
  const 화면것 = C.골고루(거리.map((x) => Object.assign({}, x)));
  assert.deepEqual(서버것.map((x) => x.제목), 화면것.map((x) => x.제목),
    '★★★ 서버와 화면의 차례가 다르다 — 규칙이 갈라졌다');
});

test('★★★ 공지도 신문사가 «돌아가며» 앞자리를 갖는다', () => {
  /* ⚠⚠ 모은날순 그대로면, 기사를 많이 내는 신문사가 앞 열두 자리를 다 먹는다.
       신문사를 넷으로 늘려 놓고 공지에는 한 곳만 실리는 꼴이 된다. */
  const 줄 = [];
  /* 새 것(09-13)을 한 신문사가 여섯 줄로 차지한다 — 실제로 이렇게 온다 */
  for (let i = 0; i < 6; i++) {
    줄.push(한줄('매일노동뉴스', '2026-09-13', '매일 소식 ' + i));
  }
  줄.push(한줄('참여와혁신', '2026-09-12'));
  줄.push(한줄('안전저널', '2026-09-12'));
  const 나온것 = B.주간뉴스고르기(창고(줄), '2026-09-14', 7).slice(0, 3)
    .map((x) => x.언론사);
  assert.equal(new Set(나온것).size, 3,
    '★★★ 앞 셋이 ' + 나온것.join(', ') + ' 이다 — 돌아가며 고르지 않았다');
});

test('★★ 고르기는 «버리지 않는다» — 차례만 바꾼다', () => {
  const 줄 = [한줄('가', '2026-09-13'), 한줄('나', '2026-09-12'), 한줄('가', '2026-09-11')];
  const 나온것 = B.주간뉴스고르기(창고(줄), '2026-09-14', 7);
  assert.equal(나온것.length, 3, '★★ 줄이 없어졌다 — 골고루가 버리는 일이 되었다');
});

test('★★ 날짜 창은 그대로다 — 골고루가 «지난 한 주»를 덮어쓰지 않는다', () => {
  /* ⚠ 차례를 바꾸는 일과 「어느 주 것인가」를 가르는 일은 다른 일이다.
       섞으면 지지난 주 기사가 공지에 실린다. */
  const 줄 = [한줄('가', '2026-09-13'), 한줄('나', '2026-08-01')];
  const 나온것 = B.주간뉴스고르기(창고(줄), '2026-09-14', 7);
  assert.equal(나온것.length, 1, '★★ 창 밖(2026-08-01) 것이 따라 들어왔다');
  assert.equal(나온것[0].언론사, '가');
});

test('★★ 뺄말 거르개도 그대로다 — 부고가 공지로 새어 나가지 않는다', () => {
  /* ⚠ 창고에는 거르개를 «늘리기 전에» 담긴 것이 남아 있다. */
  const 줄 = [
    { 제목: '[부고] ○○○ 노동대학원장 빙모상', 링크: 'https://x.test/1',
      언론사: '가', 모은날: '2026-09-13' },
    한줄('나', '2026-09-13')
  ];
  const 나온것 = B.주간뉴스고르기(창고(줄), '2026-09-14', 7);
  assert.equal(나온것.length, 1, '★★ 부고가 새어 나갔다');
});

test('★ 한 신문사 «안»에서는 새 것이 앞이다 — 최신순을 잃지 않는다', () => {
  const 줄 = [
    한줄('가', '2026-09-11', '가-옛것'), 한줄('가', '2026-09-13', '가-새것'),
    한줄('나', '2026-09-12', '나것')
  ];
  const 가것 = B.주간뉴스고르기(창고(줄), '2026-09-14', 7)
    .filter((x) => x.언론사 === '가').map((x) => x.제목);
  assert.deepEqual(가것, ['가-새것', '가-옛것'], '★ 신문사 안에서 최신순이 깨졌다');
});
