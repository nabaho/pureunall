'use strict';
/* ㅁ 를 눌렀는데 «아무 일도 안 일어나는» 것을 없앤다
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-14: 「체크표시 눌렀는데 반응 안한다」

   ⚠⚠ 무엇이 일어났는지 «알아볼 길»이 없었다. 눌러도 그대로인 까닭이 셋인데
     셋 다 말없이 지나갔다:
       ① 그 줄을 못 찾았다            → if(!것) return;   (아무 말 없음)
       ② 판이 어긋나 저장이 거절됐다   → 화면을 다시 읽고 «되돌아간다»
       ③ 저장이 터졌다               → 그때만 말한다
     ①②는 화면이 «그대로»다. 고장인지 내가 잘못 눌렀는지 대표께서 알 길이 없다.

   ★★ 그 가운데 ②는 «고칠 수 있는» 것이다.
     판은 「내가 읽어 온 뒤 남이 고쳤나」를 보는 잣대다. 화면은 열 때 한 번만 읽으므로,
     창을 오래 열어 둔 채 다른 데서(사람이든 스크립트든) 회차를 고치면 그 창의 판은
     영영 낡은 채로 남는다 — 누를 때마다 거절되고, 누를 때마다 되돌아간다.
     ⚠ 실제로 그랬다: 2026-09-14 실측, 서버 판 1 · 고친이 「claude(대표 지시)」 —
       화면에서 저장된 적이 «한 번도» 없었다.
     ★ ㅁ 한 칸은 «켬/끔»이다. 글을 섞는 일이 아니라 그 줄의 깃발 하나를 다시 세우는
       일이라, 새로 읽은 것 위에 «같은 자리»에 다시 걸면 뜻이 어긋날 수 없다.
       그래서 이것만은 한 번 다시 해 본다. 그래도 안 되면 «말한다».
   ⚠ 글(우리말·목차)을 고치는 자리에는 이 되풀이를 두지 않는다 — 섞으면 어느 쪽 글인지
     아무도 모른다. 그것이 판을 둔 까닭이다. */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { stripComments } = require('./strip-comments');

const ROOT = path.join(__dirname, '..');
const 날글 = fs.readFileSync(path.join(ROOT, 'pu-news.html'), 'utf8').replace(/\r\n/g, '\n');
const news = stripComments(날글);

const 함수 = (이름) => {
  const i = news.indexOf('function ' + 이름 + '(');
  assert.ok(i > 0, 이름 + ' 을 못 찾음');
  return news.slice(i, news.indexOf('\n}', i));
};

test('★★★ ㅁ 는 «말없이 되돌아가지» 않는다', () => {
  /* ⚠⚠ 지금은 회차저장이 돌려주는 참/거짓을 버리고 그냥 render() 한다.
       거절되면 화면이 스스로 되돌아가는데, 대표께는 «아무 일도 안 일어난» 것으로 보인다. */
  const fn = 함수('실음바꾸기');
  assert.ok(!/회차저장\(d\)\.then\(render\)/.test(fn),
    '★★★ 저장 결과를 버리고 있다 — 거절돼도 아무 말이 없다');
  assert.ok(/toast\(/.test(fn),
    '★★★ 안 됐을 때 말해 주는 자리가 없다');
});

test('★★★ 판이 낡았으면 «한 번 다시» 해 본다 — 창을 오래 열어 두면 늘 거절된다', () => {
  /* ⚠⚠ 화면은 열 때 한 번만 회차를 읽는다. 그 뒤 다른 데서 고치면 그 창의 판은
       영영 낡는다 — 새로 고치기 전에는 ㅁ 가 «한 번도» 안 먹는다.
     ★ 새로 읽은 것 위에 같은 깃발을 다시 세우고 한 번 더 저장한다. */
  const fn = 함수('실음바꾸기');
  /* 회차저장이 거절되면 «스스로» 새로 읽어 둔다 — 그 뒤 다시 집어 와야 새 판이 잡힌다 */
  const 읽기수 = (fn.match(/지금회차\(\)/g) || []).length;
  assert.ok(읽기수 >= 2,
    '★★★ 거절된 뒤 새 판을 다시 집어 오지 않는다(지금회차 ' + 읽기수 + '번)');
  const 저장수 = (fn.match(/회차저장\(/g) || []).length;
  assert.ok(저장수 >= 2,
    '★★★ 다시 해 보지 않는다(저장 ' + 저장수 + '번) — 첫 거절로 끝난다');
});

test('★★★ 다시 걸 때 «그 줄을 다시 찾는다» — 번째를 믿으면 엉뚱한 기사를 뺀다', () => {
  /* ⚠⚠ 새로 읽은 안 에서는 «차례가 달라져 있을 수» 있다(누가 ▲▼ 로 옮겼거나 뺐거나).
       같은 번째 줄에 깃발을 걸면 «엉뚱한 기사»가 편지에서 빠진다 — 조용히, 표시 없이.
       되풀이를 두면서 이것을 안 하면, 고치려던 것보다 나쁜 것을 만든다.
     ★ 링크(없으면 제목)로 다시 찾는다. 못 찾으면 걸지 않고 말한다. */
  const 찾기 = 함수('_줄찾기');
  assert.ok(/링크/.test(찾기) && /제목/.test(찾기),
    '★★★ 링크·제목으로 안 찾는다 — 번째만 믿으면 엉뚱한 줄을 건드린다');
  assert.ok(/findIndex|indexOf|filter|find\(/.test(찾기),
    '★★★ 새 목록에서 찾아보는 자리가 없다');
  assert.ok(/return null/.test(찾기),
    '★★★ 못 찾았을 때 «없다»고 하지 않는다 — 엉뚱한 줄을 돌려주면 그것을 뺀다');
  assert.ok(/_줄찾기\(/.test(함수('실음바꾸기')),
    '★★★ 다시 걸 때 그 찾기를 안 쓴다');
});

test('★★ 그 줄을 못 찾으면 «말한다» — 말없이 돌아서지 않는다', () => {
  const fn = 함수('실음바꾸기');
  assert.ok(!/if\(!것\)\s*return;/.test(fn),
    '★★ 줄을 못 찾았을 때 말없이 돌아선다');
});

test('★★★ 화면 글의 «문법이 어긋나 있지» 않다 — 어긋나면 단추가 하나도 안 먹는다', () => {
  /* ⚠⚠ 이것이 «가장 조용한» 고장이다. 인라인 <script> 안에 문법이 어긋난 곳이
       하나라도 있으면 그 덩이가 통째로 안 돌아간다 — 화면은 멀쩡히 그려져 있는데
       ㅁ 도, ▲▼ 도, 단추도 아무것도 안 먹는다. 겉으로는 「반응이 없다」뿐이다.
     ★ 2026-09-14 에 「체크표시가 안 먹는다」를 쫓을 때, 이것부터 확인해야
       엉뚱한 곳을 파지 않는다는 것을 배웠다. 그때는 다행히 멀쩡했다.
     ⚠ 브라우저를 띄우지 않는다 — new Function 이 문법만 본다. */
  const 덩이 = [...날글.matchAll(/<script(?![^>]*\bsrc=)[^>]*>([\s\S]*?)<\/script>/g)];
  assert.ok(덩이.length >= 1, '인라인 <script> 를 못 찾았다');
  덩이.forEach((m, i) => {
    const 줄 = 날글.slice(0, m.index).split('\n').length;
    assert.doesNotThrow(() => new Function(m[1]),
      '★★★ ' + (i + 1) + '째 <script>(줄 ' + 줄 + ' 부터) 의 문법이 어긋났다 — '
      + '그 덩이의 단추가 하나도 안 먹는다');
  });
});

test('★ 글을 고치는 자리에는 «되풀이를 두지 않는다» — 섞으면 어느 쪽 글인지 모른다', () => {
  /* ⚠ 판을 둔 까닭이 이것이다. ㅁ(깃발 하나)만 예외로 둔다. */
  const fn = 함수('목차고치기');
  assert.ok(!/회차다시읽기/.test(fn),
    '★ 글을 고치는 자리까지 자동으로 다시 하고 있다 — 남의 글을 덮어쓴다');
});
