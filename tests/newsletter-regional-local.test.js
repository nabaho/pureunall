"use strict";
/* 지역뉴스에 «진짜 지역»을 넣는다 — 지방관서 공지 게시판
   ═══════════════════════════════════════════════════════════════════════════
   대표 물음 2026-09-13: 「다른지역 정보 가지고 오는건 어떻게 되었나」

   ⚠ 실측 2026-09-13: 지역뉴스 기계는 다 돌고 있었다(날마다 07:10, 출처 3/3 읽음).
     그런데 «출처 셋이 전부 고용노동부 중앙 RSS»고 셋 다 지역이 「전국」이었다.
     쌓인 후보 20건도 전부 「전국」. 지역뉴스 칸에 전국 소식만 들어오고 있었다 —
     기계는 도는데 «지역 정보는 한 건도» 없었다.

   ★ 어디를 넣나 — 짐작이 아니라 받는 곳 주소에서 나온 답이다(실측 2026-09-13):
     충남 100곳 남짓(천안 60 · 아산 26 · 서산 5 · 당진 4 · 예산 3) · 경기 10곳.
     → 대전지방고용노동청 «천안지청»(천안·아산·당진·예산 관할)과 «서산지청».

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ① 출처 등록부에 «전국이 아닌» 것이 있다 — 없으면 지역뉴스가 아니다
     ② 지방관서는 RSS 가 없다 — 게시판(HTML)을 읽는 길이 따로 있어야 한다
     ③ 게시판의 «상대 링크»를 절대 주소로 세운다 — 안 그러면 공식링크 검사에 걸려
        한 건도 안 들어온다
     ④ 지역 딱지는 받는 곳 지역과 «맞물려야» 한다 (지역뉴스고르기)
     ⑤ 관서 살림 공지(채용·개인정보 제공)는 안 담는다

   ⚠ 인터넷을 두드리지 않는다 — 실제로 받아 온 조각을 여기 박아 두고 본다. */

const test = require("node:test");
const assert = require("node:assert");
const R = require("../functions/news-region.js");
const C = require("../js/pu-news-core.js");

/* 2026-09-13 실측: /local/cheonan/news/notice/noticeList.do 에서 «그대로» 받아 온 꼴.
   ⚠⚠ href 가 「noticeView.do?bbs_seq=…」 하나뿐이다 — 앞에 /local/… 이 «안 붙어 있다».
     처음에 이 조각을 「/local/cheonan/…」으로 지어 놓고 검사를 세웠더니 다 통과했는데,
     진짜 게시판을 두드려 보니 링크가 moel.go.kr/noticeView.do 로 서서 «죽은 주소»였다.
     ★ 박아 두는 조각은 «내가 바라는 꼴»이 아니라 «저쪽이 내놓는 꼴»이어야 한다. */
const 천안조각 = [
  '<td class="title">',
  '<a href="noticeView.do?bbs_seq=20260900013">',
  "[안내] '26년 제4회차 신규 입국 외국인 근로자(체류자격 E-9) 고용허가서 신청 일정 안내",
  '</a></td><td>2026-09-01</td>',
  '<td class="title">',
  '<a href="noticeView.do?bbs_seq=20260800078">',
  '[안내] 폭염중대경보 발령 시 작업중지 이행계획서 제출 안내',
  '</a></td><td>2026-08-05</td>',
  '<td class="title">',
  '<a href="noticeView.do?bbs_seq=20260900402">',
  '[공고] 개인정보 목적 외 제3자 제공[290차]',
  '</a></td><td>2026-09-11</td>',
  '<td class="title">',
  '<a href="noticeView.do?bbs_seq=20260800797">',
  '[공고] 2026년 하반기 대전지방고용노동청 천안지청 청년인턴 채용 서류전형 합격자 공고',
  '</a></td><td>2026-08-20</td>',
].join("\n");

const 천안샘 = () => R.출처들.find((x) => x.id === "moel-cheonan");

/* ══════════════════════════════════════════════════════════════════════════
   ① 등록부에 «전국이 아닌» 출처가 있다
   ══════════════════════════════════════════════════════════════════════════ */

test("★★ 지역 출처가 «하나라도» 있다 — 전부 전국이면 지역뉴스가 아니다", () => {
  const 지역것 = R.출처들.filter((x) => String(x.지역 || "전국") !== "전국");
  assert.ok(지역것.length >= 1,
    "★★ 출처가 전부 「전국」이다 — 기계는 도는데 지역 정보는 한 건도 안 들어온다");
});

test("★ 받는 곳이 몰려 있는 «충남»을 덮는다", () => {
  /* ⚠ 값(몇 곳인가)이 아니라 «받는 곳 지역과 맞물리는가»를 못 박는다. */
  const 충남것 = R.출처들.filter((x) => String(x.지역 || "").indexOf("충남") === 0);
  assert.ok(충남것.length >= 1, "★ 충남 출처가 없다 — 받는 곳의 대부분이 거기다");
});

test("지역 출처의 딱지가 «지역코드»가 쓰는 말과 같은 꼴이다", () => {
  /* ⚠ 「충청남도」라고 적으면 지역뉴스고르기가 「충남/천안시」와 못 맞춘다.
       두 곳이 서로 다른 말을 쓰면 조용히 한 건도 안 간다. */
  R.출처들.filter((x) => String(x.지역 || "전국") !== "전국").forEach((s) => {
    const 광역 = String(s.지역).split("/")[0];
    assert.equal(C.지역코드(광역 + " 어딘가시"), C.지역코드(광역 + " 어딘가시"),
      "지역코드가 못 읽는 말이다: " + s.지역);
    assert.ok(/^(서울|부산|대구|인천|광주|대전|울산|세종|경기|강원|충북|충남|전북|전남|경북|경남|제주)(\/|$)/
      .test(String(s.지역)), "지역 딱지가 광역 이름으로 시작하지 않는다: " + s.지역);
  });
});

/* ══════════════════════════════════════════════════════════════════════════
   ② 게시판(HTML) 읽기 — 지방관서에는 RSS 가 없다
   ══════════════════════════════════════════════════════════════════════════ */

test("★★ 지방관서는 «게시판»으로 읽는다 — RSS 를 기다리면 영원히 안 온다", () => {
  const s = 천안샘();
  assert.ok(s, "★ 천안지청 출처가 없다");
  assert.equal(s.방식, "board",
    "★★ 지방관서를 rss 로 읽으려 한다 — moel 지청에는 RSS 가 없다(실측 2026-09-13, 404)");
  assert.ok(s.밑주소, "게시판 상대 링크를 세울 밑주소가 없다");
});

test("★★★ 게시판에서 «쓸모 있는 것만» 후보로 담는다", () => {
  const 것 = R.후보만들기(천안조각, 천안샘(), {}, 1789000000000);
  const 제목들 = 것.map((x) => x.제목);
  assert.ok(제목들.some((t) => t.indexOf("고용허가서") >= 0),
    "★★★ 외국인 고용허가서 일정을 못 담았다 — 천안·아산 제조 사업장이 제일 챙기는 것이다");
  assert.ok(제목들.some((t) => t.indexOf("작업중지") >= 0),
    "★ 폭염 작업중지 안내를 못 담았다 — 관련말이 좁다");
  assert.ok(!제목들.some((t) => t.indexOf("개인정보 목적 외") >= 0),
    "관서 살림 공지(개인정보 제공)가 들어왔다");
  assert.ok(!제목들.some((t) => t.indexOf("청년인턴 채용") >= 0),
    "관서 채용 공고가 들어왔다");
});

test("★★ 게시판의 «상대 링크»를 절대 주소로 세운다", () => {
  /* ⚠⚠ 여기가 무너지면 공식링크인가() 가 전부 떨어뜨려 «한 건도» 안 들어온다.
       그런데 화면에는 「출처 읽음」으로 뜬다 — 조용히 아무 일도 안 하는 꼴이다. */
  const 것 = R.후보만들기(천안조각, 천안샘(), {}, 1789000000000);
  assert.ok(것.length > 0, "★★ 한 건도 못 담았다 — 상대 링크를 못 세웠다");
  것.forEach((x) => {
    /* ★★★ 여기가 알맹이다. moel.go.kr/noticeView.do 로 서면 «죽은 링크»인데
         겉보기에는 멀쩡한 moel 주소라 공식링크인가() 도 그냥 지나간다 —
         죽은 링크가 114곳으로 나가고 나서야 안다. 관서 길까지 붙어 있어야 한다. */
    assert.ok(/^https:\/\/www\.moel\.go\.kr\/local\/cheonan\/news\/notice\/noticeView\.do\?/
      .test(x.링크), "★★★ 링크가 관서 게시판을 안 가리킨다(죽은 주소): " + x.링크);
    assert.ok(R.공식링크인가(x.링크), "공식 링크 검사를 못 지난다: " + x.링크);
  });
});

test("★ 출처마다 목록주소의 «관서 길»을 이어받는다 — 서산 것이 천안으로 서면 안 된다", () => {
  const 서산 = R.출처들.find((x) => x.id === "moel-seosan");
  const 것 = R.후보만들기(천안조각, 서산, {}, 1789000000000);
  assert.ok(것.length > 0, "서산 출처로는 한 건도 못 담았다");
  것.forEach((x) => assert.ok(x.링크.indexOf("/local/seosan/") >= 0,
    "★ 서산 공지가 천안 길로 선다: " + x.링크));
});

test("게시판 후보도 «지역·출처·상태»를 갖춰 온다 — 화면이 그대로 쓴다", () => {
  const 것 = R.후보만들기(천안조각, 천안샘(), {}, 1789000000000);
  const x = 것[0];
  assert.equal(x.지역, 천안샘().지역, "지역 딱지가 안 붙었다");
  assert.equal(x.상태, "검토대기", "★ 손 안 거치고 바로 나갈 상태로 담았다");
  assert.equal(x.sourceKind, "regionalNewsSource", "갈래 딱지가 없다");
  assert.ok(x.id && x.id.indexOf("regional-news-") === 0, "열쇠 꼴이 다르다");
});

test("이미 담은 링크는 «두 번» 담지 않는다", () => {
  const 첫 = R.후보만들기(천안조각, 천안샘(), {}, 1789000000000);
  const 있던것 = {};
  첫.forEach((x) => { 있던것[x.id] = x; });
  const 둘 = R.후보만들기(천안조각, 천안샘(), 있던것, 1789000000001);
  assert.equal(둘.length, 0, "같은 공지를 날마다 새로 담는다 — 검토함이 밀린다");
});

/* ══════════════════════════════════════════════════════════════════════════
   ③ 받는 곳과 맞물리나
   ══════════════════════════════════════════════════════════════════════════ */

test("★★ 충남 지역뉴스가 «천안 사업장»에 닿는다 — 안 닿으면 넣은 뜻이 없다", () => {
  const 뉴스 = [{ 지역: "충남", 제목: "천안지청 공지", 상태: "승인" }];
  assert.equal(C.지역뉴스고르기(뉴스, C.지역코드("충남 천안시 서북구 어딘가")).length, 1,
    "★★ 충남 소식이 천안 사업장에 안 간다");
  assert.equal(C.지역뉴스고르기(뉴스, C.지역코드("충남 아산시 어딘가")).length, 1,
    "충남 소식이 아산 사업장에 안 간다");
  assert.equal(C.지역뉴스고르기(뉴스, C.지역코드("경기도 평택시 어딘가")).length, 0,
    "★ 충남 소식이 경기 사업장까지 간다 — 지역을 가르는 뜻이 없다");
});

test("«서산시»로 좁힌 소식은 서산에만 간다", () => {
  const 뉴스 = [{ 지역: "충남/서산시", 제목: "서산지청 공지", 상태: "승인" }];
  assert.equal(C.지역뉴스고르기(뉴스, C.지역코드("충남 서산시 어딘가")).length, 1, "서산에 안 간다");
  assert.equal(C.지역뉴스고르기(뉴스, C.지역코드("충남 천안시 어딘가")).length, 0,
    '서산지청 공지가 천안까지 간다');
});
