/* 시험 발송 — 보낼 때 «주소를 골라» 넣는다
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-13:
     「시험발송에서 샘플로 메일 주소 넣고 보낼수 있게 할 수 있나」
     「법인에서 권형하에게 개인에게 보내서 잘 가는지 확인하고 싶다.」

   ★ 왜 필요한가 — 법인 메일에서 «개인 메일»로 보내 봐야 진짜로 가는지 안다.
     같은 집(법인 계정)으로만 보내면 스팸함으로 가는지·그림이 막히는지 알 수 없다.
   ⚠ 그 전에는 설정에 적어 둔 주소 한 곳으로만 갔다. 다른 곳으로 한 번 보내 보려면
     설정을 고쳤다가 되돌려야 했다.

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ① 보낼 때 주소를 «물어본다» — 설정을 고치러 가지 않는다
     ② 설정에 적힌 것이 «미리 채워져» 있다 — 늘 같은 곳이면 그냥 확인만 하면 된다
     ③ 넣은 주소를 «기억한다» — 다음에 또 안 친다
     ④★★★ 시험 문으로 «여럿에게» 못 보낸다 — 여기는 대량 발송을 안 거치는 문이다
     ⑤ 이메일 꼴이 아니면 «안 보낸다»
     ⑥ 무엇이 어디로 가는지 «확인 창»에 그 주소가 적힌다

   ⚠ 화면 글을 읽는 검사다. 인터넷도 브라우저도 두드리지 않는다. */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { stripComments } = require('./strip-comments');

const ROOT = path.join(__dirname, '..');
const news = stripComments(
  fs.readFileSync(path.join(ROOT, 'pu-news.html'), 'utf8').replace(/\r\n/g, '\n'));

const 시험발송 = () => {
  const i = news.indexOf('async function 시험발송(');
  assert.ok(i > 0, '시험발송 을 못 찾음');
  const 끝 = news.indexOf('\n}', i);
  assert.ok(끝 > i, '시험발송 의 끝을 못 찾음');
  return news.slice(i, 끝);
};

test('★★ 보낼 때 주소를 «물어본다» — 설정을 고치러 가지 않는다', () => {
  const fn = 시험발송();
  assert.ok(/window\.prompt\(|prompt\(/.test(fn),
    '★★ 주소를 물어보지 않는다 — 설정에 적힌 한 곳으로만 간다');
});

test('★★★ 물어본 답을 «실제로 쓴다» — 묻고 버리면 묻지 않은 것과 같다', () => {
  /* ⚠⚠ 이 검사는 처음에 이빨이 없었다. 「prompt 가 있나」와 「시험받을주소()가 있나」만
       보았더니, 받을곳을 설정값으로 되돌려 놓아도 그대로 통과했다 —
       주소를 물어보고 «버리는» 코드를 못 잡는다. 값이 어디로 흐르는지를 못 박는다. */
  const fn = 시험발송();
  assert.ok(/받을곳\s*=\s*넣은것/.test(fn),
    '★★★ 물어본 주소가 받을곳으로 안 간다 — 묻기만 하고 버린다');
  assert.ok(!/받을곳\s*=\s*시험받을주소\(\)/.test(fn),
    '★★★ 받을곳을 설정값으로 되돌려 놓았다 — 물어본 뜻이 없다');
  /* 보내는 자리까지 그 값이 가야 한다 */
  assert.ok(/to:\s*받을곳/.test(fn), '★★ 서버로 보낼 때 다른 주소를 쓴다');
});

test('★ 설정에 적힌 주소가 «미리 채워져» 있다', () => {
  /* ⚠ 늘 같은 곳으로 보내는 날이 대부분이다. 미리 채워 두지 않으면
       날마다 긴 주소를 손으로 친다 — 오타 한 자면 시험이 허공으로 간다. */
  const fn = 시험발송();
  assert.ok(fn.indexOf('시험받을주소()') >= 0,
    '★ 설정에 적어 둔 주소를 미리 채우지 않는다');
});

test('★ 넣은 주소를 «기억한다» — 다음에 또 안 친다', () => {
  const fn = 시험발송();
  assert.ok(/시험주소/.test(fn),
    '★ 손으로 넣은 주소를 안 적어 둔다 — 다음에 또 쳐야 한다');
});

test('★★★ 시험 문으로 «여럿에게» 못 보낸다', () => {
  /* ⚠⚠ 여기가 알맹이다. 시험 문(시험즉시URL)은 대량 발송기를 «안 거친다» —
       수신거부·간격·추적열쇠 바꿔 넣기가 다 그 길에 있다.
       명단을 통째로 붙여 넣으면 그 모든 장치를 건너뛴 편지가 나간다. */
  /* ⚠⚠ 이 검사도 처음에 이빨이 없었다. 「함수 안에 쉼표가 있나」를 보고 있었는데
       쉼표는 어디에나 있다. 막는 곳(if(false) 로 바꿔도) 그대로 통과했다.
     ★ «넣은것»을 재는 그 자리를 못 박는다. */
  const fn = 시험발송();
  assert.ok(/\[,;\]\/\.test\(넣은것\)/.test(fn),
    '★★★ 넣은 주소에 쉼표·세미콜론이 있는지 «안 본다» — 명단을 붙여 넣으면 그대로 나간다');
  assert.ok(/\\s\/\.test\(넣은것\)/.test(fn),
    '★★ 빈칸으로 나눈 여러 주소를 안 막는다');
  assert.ok(/한 곳/.test(fn), '왜 막혔는지 안 알려 준다');
});

test('★★ 이메일 «꼴»이 아니면 안 보낸다', () => {
  const fn = 시험발송();
  assert.ok(/\[\^\\s@\]\+@\[\^\\s@\]\+/.test(fn) || /@[^\s]*\\\./.test(fn)
    || fn.indexOf('주소꼴인가') >= 0,
    '★★ 이메일 꼴을 안 본다 — 오타가 그대로 서버로 간다');
});

test('★★ 확인 창에 «그 주소»가 적힌다 — 어디로 가는지 보고 누른다', () => {
  const fn = 시험발송();
  const i = fn.indexOf('confirm(');
  assert.ok(i > 0, '확인 창이 없다 — 누르자마자 나간다');
  const 창 = fn.slice(i, i + 400);
  assert.ok(창.indexOf('받을곳') >= 0,
    '★★ 확인 창이 받을 주소를 안 보여 준다');
});

test('★ 「나에게」가 아니다 — 단추 이름이 거짓이면 안 된다', () => {
  /* ⚠ 이제 아무 데나 골라 보낼 수 있다. 「나에게 시험 발송」이라고 적어 두면
       화면이 거짓말을 한다. */
  const i = news.indexOf('onclick="시험발송()"');
  assert.ok(i > 0, '시험 발송 단추를 못 찾음');
  const 줄 = news.slice(Math.max(0, i - 200), i + 200);
  assert.ok(줄.indexOf('나에게') < 0,
    '★ 단추가 아직 「나에게」라고 말한다 — 이제 골라 보낼 수 있다');
});

test('시험은 여전히 «거래처에 안 나간다»고 밝힌다', () => {
  /* ⚠ 좁히다가 이 말을 잃으면, 골라 넣는 칸이 생긴 만큼 더 무섭다. */
  const fn = 시험발송();
  assert.ok(fn.indexOf('거래처에는 나가지 않습니다') >= 0,
    '★ 거래처에 안 나간다는 말이 사라졌다');
});
