'use strict';
/* 메일도 «좌우로 넓게» — 700 → 980 (대표 지시 2026-09-26)
   ═══════════════════════════════════════════════════════════════════════════
   「몇번째 요청했는데 캡쳐3의 화면과 같이 좌우로 넓게 정리해서 보내는 방식으로
    몇번요청했다」

   ⚠⚠ 2026-09-17 에 「좌우로 넓게」를 듣고 «웹 전문 보기»만 넓혔다. 메일은 700 그대로였고,
     그 결정이 검사에까지 「메일은 700 이라야 한다」로 굳어 있었다.
     실측(2026-09-26): 대표님 다음메일의 읽는 칸은 1,600px 남짓인데 편지만 700 —
     오른쪽이 통째로 비어 있었다. 「메일의 한계」가 아니었다.

   ■ 이 검사가 지키는 것
     ㉠ 안 주면 메일도 980 — 되돌리면 같은 말씀을 네 번째로 하시게 된다
     ㉡ 그래도 «아웃룩이 모르는 것»은 메일에 하나도 없다 (칸틀·단·늘임)
     ㉢ 그 자리를 «표»가 맡는다 — 자료 셋씩, 기사 두 칸
     ㉣★ 발송기를 «실제로 지나도» 그 표가 살아남는다 (STYLE_OK 에서 지워지면 헛일이다)
     ㉤ 글이 하나도 안 줄었다 — 넓히면서 버린 것이 없어야 한다
     ㉥ 좁게 지으면 예전 그대로 — 지난 회차를 다시 그리는 자리 */

const test = require('node:test');
const assert = require('node:assert');

const C = require('../js/pu-news-core.js');
const T = require('../js/pu-news-tpl.js');
const MS = require('../functions/mail-send.js');

const 설 = { 회사이름: '푸른노무법인', 회신주소: '370-6@daum.net' };
const 자료 = (n) => ({ 갈래: '자료', 제목: '자료 ' + n, 발행처: '고용노동부', 발행일: '20260901',
  파일: 'https://www.moel.go.kr/f' + n + '.pdf', 파일크기: 320000,
  목차: ['한 눈에 보는 제도', '자주 묻는 질문'] });
const 기사 = (n) => ({ 갈래: '기사', 한줄: '한 줄 ' + n,
  우리말: '우리가 쓴 글 ' + n + ' 입니다. 사업장에서 확인하실 것을 적었습니다.',
  언론사: '매일노동뉴스', 링크: 'https://www.labortoday.co.kr/news/articleView.html?idxno=' + n });

function 거리() {
  return {
    회차: C.회차('2026-09-21'), 상태: '초안', 범위: '자문중',
    우리글: '개정 노조법 시행 여섯 달을 짚습니다. 이번 주에는 시행령 개정안이 10월 1일부터 시행됩니다.',
    지역뉴스: [],
    안: {
      news: [1, 2, 3, 4].map(기사),
      policy: [1, 2, 3, 4, 5, 6].map(자료),
      case: [{ 갈래: '판례', 딱지: '[판례]', 제목: '판례 하나', 인용: '대법원 2026다1',
        링크: 'https://www.law.go.kr/LSW/precInfoP.do?target=prec&ID=622111' }],
      hr: [자료(9)]
    }
  };
}
const 짓 = (옵션) => T.편지짓기(거리(), 설,
  Object.assign({ 요약: false, 미리보기: true }, 옵션 || {})).서식;
const 폭읽기 = (h) => {
  const m = /<table[^>]*width="(\d{3,4})"[^>]*style="width:\1px/.exec(h);
  assert.ok(m, '편지 폭을 못 읽었다');
  return Number(m[1]);
};
const 셈 = (h, s) => (h.split(s).length - 1);

/* ═══ ㉠ 메일도 980 ═══════════════════════════════════════════════════ */
test('★★★ 안 주면 메일도 980 이다 — 700 으로 되돌리지 말 것', () => {
  assert.strictEqual(폭읽기(짓()), T.전문넓이,
    '★★★ 메일이 아직 좁다 — 대표께서 같은 말씀을 네 번째로 하시게 된다');
  assert.ok(T.전문넓이 >= 900, '전문 폭이 안 넓다');
});

test('★★ 메일과 웹이 «같은 폭»이다 — 눌러 넘어갈 때 글이 움찔하지 않게', () => {
  assert.strictEqual(폭읽기(짓()), 폭읽기(짓({ 넓이: T.전문넓이, 웹: true })));
});

/* ═══ ㉡ 아웃룩이 모르는 것은 메일에 없다 ═════════════════════════════ */
test('★★★ 넓어져도 메일에는 칸틀·단·늘임이 «하나도» 없다', () => {
  const 메일 = 짓();
  ['display:grid', 'grid-template-columns', 'column-count', 'break-inside', 'display:flex']
    .forEach((것) => assert.ok(메일.indexOf(것) < 0,
      '⚠ 메일에 ' + 것 + ' 이 샜다 — 아웃룩이 모른다(카드가 통째로 무너진다)'));
});

test('★★ 웹은 칸틀·단을 그대로 쓴다 — 넓힌다고 웹을 망가뜨리지 않았다', () => {
  const 웹 = 짓({ 넓이: T.전문넓이, 웹: true });
  assert.ok(웹.indexOf('display:grid') >= 0, '웹에서 칸틀이 사라졌다 — 단추 바닥이 어긋난다');
  assert.ok(웹.indexOf('column-count:2') >= 0, '웹에서 단이 사라졌다');
});

/* ═══ ㉢ 그 자리를 표가 맡는다 ═══════════════════════════════════════ */
test('★★★ 넓은 메일의 자료는 «표로 셋씩» — 여섯 장이면 두 줄', () => {
  const 메일 = 짓();
  /* 자료 7장(정책 6 + 인사노무 1) → 정책 2줄×3 + 인사노무 1줄×3 = 9칸 */
  assert.strictEqual(셈(메일, 'width="33%"'), 9,
    '자료 칸이 셋씩 아홉이 아니다 — 마지막 줄의 빈 칸까지 만들어야 가로줄이 안 끊긴다');
});

test('★★★ 넓은 메일의 기사는 «두 칸 표»로 갈린다 — 980px 한 줄로 쏟아지지 않게', () => {
  const 메일 = 짓();
  assert.ok(메일.indexOf('width="50%"') >= 0, '기사를 두 칸으로 안 가른다');
  /* ⚠ 가르는 잣대는 «건»이다 — 문단 한 덩이를 가운데서 자르면 안 된다.
       네 건이면 둘·둘로 갈리고, 글자는 하나도 안 없어져야 한다. */
  [1, 2, 3, 4].forEach((n) => assert.ok(메일.indexOf('우리가 쓴 글 ' + n) >= 0,
    '기사 ' + n + ' 이 두 칸으로 가르는 사이에 사라졌다'));
});

test('★ 기사가 하나뿐이면 두 칸으로 안 가른다 — 한쪽이 통째로 빈다', () => {
  const d = 거리(); d.안.news = [기사(1)];
  const h = T.편지짓기(d, 설, { 요약: false, 미리보기: true }).서식;
  const 기사자리 = h.indexOf('우리가 쓴 글 1');
  assert.ok(기사자리 > 0, '기사가 안 실렸다');
  /* 자료 칸의 33% 는 있어도, 기사 둘레에 50% 칸은 없어야 한다 */
  assert.ok(h.slice(기사자리 - 600, 기사자리).indexOf('width="50%"') < 0,
    '기사 한 건을 두 칸으로 갈랐다 — 오른쪽이 빈다');
});

test('★★ 한마디는 «읽기 폭»으로 모인다 — 한 덩이 문단이라 가를 수 없다', () => {
  const 메일 = 짓();
  const i = 메일.indexOf('id="n-hr-w"');
  assert.ok(i > 0, '한마디 칸을 못 찾았다');
  const 판 = 메일.slice(i, i + 900);
  const m = /<table[^>]*align="center"[^>]*width="(\d{3})"/.exec(판);
  assert.ok(m, '한마디가 980px 한 줄로 쏟아진다 — 읽기 폭으로 안 모았다');
  assert.ok(Number(m[1]) >= 600 && Number(m[1]) <= 820,
    '읽기 폭이 ' + m[1] + 'px 다 — 너무 좁거나 너무 넓다');
});

/* ═══ ㉣ 발송기를 «실제로» 지나도 살아남는다 ═════════════════════════
   ⚠⚠ 여기가 핵심이다. 발송기(STYLE_OK)가 지워 버리면 아무리 잘 지어도 헛일이다. */
test('★★★ 발송기를 지난 뒤에도 «세 칸·두 칸»이 그대로 있다', () => {
  const 씻긴 = MS.sanitizeHtml(짓());
  assert.strictEqual(셈(씻긴, 'width="33%"'), 9, '발송기가 자료 세 칸을 지웠다');
  assert.ok(씻긴.indexOf('width="50%"') >= 0, '발송기가 기사 두 칸을 지웠다');
  assert.ok(/<table[^>]*width="980"/.test(씻긴), '발송기가 편지 폭을 지웠다');
  /* ⚠⚠ 폭은 «속성»과 «꾸밈» 두 곳에 적혀 있다. 속성만 봐서는 부족하다 —
       발송기의 STYLE_OK 에서 width 가 빠져도 속성은 남아 검사가 헛돈다(되돌림 검사에서 드러났다).
       메일 프로그램은 둘이 다르면 꾸밈을 따르므로, 꾸밈이 지워지면 자리가 어긋난다. */
  assert.ok(씻긴.indexOf('width:980px') >= 0,
    '발송기가 «꾸밈» 폭(width:980px)을 지웠다 — 속성만으로는 폭이 안 잡힌다');
  assert.ok(씻긴.indexOf('width:33%') >= 0, '발송기가 «꾸밈» 칸 폭(width:33%)을 지웠다');
});

test('★★ 발송기를 지나도 «글»이 하나도 안 없어진다', () => {
  const 씻긴 = MS.sanitizeHtml(짓());
  [1, 2, 3, 4].forEach((n) => assert.ok(씻긴.indexOf('우리가 쓴 글 ' + n) >= 0, '기사 ' + n + ' 이 사라졌다'));
  [1, 2, 3, 4, 5, 6].forEach((n) => assert.ok(씻긴.indexOf('자료 ' + n) >= 0, '자료 ' + n + ' 이 사라졌다'));
  assert.ok(씻긴.indexOf('10월 1일부터 시행됩니다') >= 0, '한마디가 사라졌다');
  assert.ok(씻긴.indexOf('판례 하나') >= 0, '판례가 사라졌다');
});

/* ═══ ㉤ 넓히면서 글을 버리지 않았다 ═════════════════════════════════ */
test('★★★ 700 으로 지을 때와 «실린 글»이 똑같다 — 넓히면서 버린 것이 없다', () => {
  const 글만 = (h) => h.replace(/<[^>]+>/g, ' ').replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ').trim();
  assert.strictEqual(글만(짓()), 글만(짓({ 넓이: 700 })),
    '★★★ 넓히면서 실린 글이 달라졌다 — 모양만 바뀌어야 한다');
});

/* ═══ ㉥ 좁게 지으면 예전 그대로 ═════════════════════════════════════ */
test('★★ 좁게 지으면 둘씩·단 없음 — 지난 회차를 다시 그리는 자리', () => {
  const 좁 = 짓({ 넓이: 700 });
  assert.strictEqual(폭읽기(좁), 700, '준 폭을 안 지킨다');
  assert.ok(좁.indexOf('width="50%"') >= 0, '좁은데 자료가 둘씩이 아니다');
  assert.ok(좁.indexOf('width="33%"') < 0, '좁은데 셋씩이다 — 한 칸이 200px 남짓이라 글이 쏟아진다');
  assert.ok(좁.indexOf('align="center" width="7') < 0, '좁은데 읽기 폭 칸을 만들었다 — 더 좁아진다');
});

/* ═══ 화면이 «웹일 때만» 웹이라고 알려 준다 ═════════════════════════ */
test('★★ 전문을 담을 때만 «웹»이라고 알려 준다 — 메일은 표로 짜야 한다', () => {
  const fs = require('node:fs');
  const path = require('node:path');
  const { 주석걷기, 함수몸 } = require('./helpers/strip-comments.js');
  const 화면 = 주석걷기(fs.readFileSync(path.join(__dirname, '..', 'pu-news.html'), 'utf8'));
  const 담기 = 함수몸(화면, '전문담기');
  assert.ok(담기 && /웹:\s*true/.test(담기), '전문을 담을 때 «웹»이라고 안 알려 준다 — 웹에서 칸틀이 사라진다');
  const 편지 = 함수몸(화면, '지금편지');
  assert.ok(편지, '지금편지 를 못 찾았다');
  assert.ok(!/웹:\s*true/.test(편지), '★★ 메일을 «웹»으로 짓는다 — 아웃룩에서 카드가 무너진다');
  assert.ok(!/넓이:/.test(편지), '메일에 폭을 따로 준다 — 한 곳(편지짓기)에서만 정해야 한다');
});
