'use strict';
/* 신문사를 여럿 두고, 뉴스는 «골고루 다섯 이내»로
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-14: 「매일노동뉴스 이외 다양한 노동관련 뉴스를 가지고 올수 없나.
   그리고 뉴스는 골고루 5개 이내로만 하고 싶다.」

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ① 신문사는 «여럿»이다 — 한 곳만 읽으면 그 신문사의 관심사가 곧 우리 관심사가 된다
     ② 한 곳이 안 열려도 «나머지는 읽는다» — 한 곳이 멎었다고 그 주가 비면 안 된다
     ③ 담을 때 «돌아가며» 고른다 — 많이 실은 신문사가 다섯 자리를 다 먹지 않게
     ④ 주간노동뉴스는 «다섯을 넘지 않는다»
     ⑤ 어디 것인지 «적는다» — 남의 글이라 출처가 빠지면 안 된다

   ⚠ 인터넷을 두드리지 않는다. 실제로 받아 온 조각을 여기 박아 두고 그것으로 본다. */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('fs');
const path = require('path');

const B = require('../functions/news-brief.js');
const C = require('../js/pu-news-core.js');

const 어디 = (이름) => path.join(__dirname, '..', 이름);
const 글 = (이름) => fs.readFileSync(어디(이름), 'utf8');

/* ══════════════════════════════════════════════════════════════════════════
   ① 신문사 목록
   ══════════════════════════════════════════════════════════════════════════ */

test('★★★ 신문사가 «여럿»이다 — 한 곳만 읽지 않는다', () => {
  /* ⚠ 한 곳만 읽으면 그 신문사가 무엇을 중히 여기는지가 곧 우리 뉴스레터의
       관심사가 된다. 대표께서 「다양한 노동관련 뉴스」라 하신 것이 이 뜻이다. */
  assert.ok(Array.isArray(B.뉴스샘들), '뉴스샘들이 목록이 아니다');
  assert.ok(B.뉴스샘들.length >= 3,
    '★★★ 신문사가 ' + B.뉴스샘들.length + '곳뿐이다 — 여럿이라 할 수 없다');
});

test('★ 신문사마다 «이름»과 «주소»가 있고, 주소는 https 다', () => {
  /* ⚠ 이름이 없으면 편지에 출처를 못 적는다 — 남의 글을 출처 없이 싣게 된다. */
  B.뉴스샘들.forEach((S) => {
    assert.ok(S && String(S.이름 || '').trim(), '이름 없는 샘: ' + JSON.stringify(S));
    assert.ok(/^https:\/\//.test(String(S.주소 || '')),
      '★ ' + S.이름 + ' 의 주소가 https 가 아니다: ' + S.주소);
  });
});

test('★ 같은 곳을 두 번 적지 않는다 — 두 번 읽으면 그 신문사만 두 몫이 된다', () => {
  const 본것 = {};
  B.뉴스샘들.forEach((S) => {
    const k = String(S.주소).toLowerCase();
    assert.ok(!본것[k], '★ 같은 주소가 두 번 있다: ' + S.주소);
    본것[k] = 1;
  });
});

test('★★ 매일노동뉴스를 «빼지 않는다» — 지금 쓰고 있던 곳이다', () => {
  /* ⚠ 다양하게 하라는 말은 쓰던 곳을 버리라는 말이 아니다. */
  assert.ok(B.뉴스샘들.some((S) => /labortoday/.test(String(S.주소))),
    '★★ 매일노동뉴스가 사라졌다');
});

test('★★ 모으는 쪽이 «샘 목록을 돌며» 읽는다 — 한 곳만 읽는 줄이 남아 있으면 안 된다', () => {
  /* ⚠ 목록만 늘리고 읽는 쪽을 안 고치면 «조용히» 한 곳만 읽는다.
       화면에는 아무 표시도 안 난다 — 그래서 검사로 본다. */
  const s = 글('functions/index.js');
  assert.ok(/브리핑부품\.뉴스샘들/.test(s),
    '★★ index.js 가 뉴스샘들을 쳐다보지 않는다 — 한 곳만 읽고 있다');
  assert.ok(!/브리핑샘\.뉴스이름/.test(s),
    '★★ 한 곳만 읽던 옛 줄(브리핑샘.뉴스이름)이 남아 있다');
});

test('★★★ 한 곳이 안 열려도 «나머지는 읽는다»', () => {
  /* ⚠⚠ 여럿을 한 try 로 묶으면 첫 곳이 멎는 순간 뒤가 통째로 안 읽힌다.
       그 주 뉴스레터가 비는데, 기록에는 「못 읽었습니다」 한 줄뿐이라 까닭을 모른다.
     ★ 샘 하나마다 try 가 «안»에 있어야 한다. */
  const s = 글('functions/index.js');
  const m = /for \(const S of 브리핑부품\.뉴스샘들\)\s*\{([\s\S]*?)\n  \}/.exec(s);
  assert.ok(m, '★★★ 샘을 하나씩 도는 고리를 못 찾았다');
  assert.ok(/try\s*\{/.test(m[1]) && /catch/.test(m[1]),
    '★★★ 고리 «안»에 try/catch 가 없다 — 한 곳이 멎으면 나머지도 안 읽는다');
});

/* ══════════════════════════════════════════════════════════════════════════
   ② 거르개 — 제목 낱말만 보는 탓에 생기는 헛걸림
   ══════════════════════════════════════════════════════════════════════════ */

test('★★ 「연차총회」를 «연차휴가»로 잘못 읽지 않는다', () => {
  /* ⚠ 2026-09-14 실측: 연합뉴스에서 「국제금융센터세계연합 연차총회」가
       노동 기사로 걸려 들어왔다. 노동말의 「연차」가 「연차총회」에 맞은 것이다.
       종합지를 안 넣기로 했어도, 전문지에도 협회 총회 기사는 온다. */
  assert.equal(B.노동글인가('부산서 국제금융센터세계연합 연차총회…금융환경 변화 논의'), false);
  /* ★ 진짜 연차휴가 기사는 그대로 걸려야 한다 — 거르개를 너무 넓히면 안 된다 */
  assert.equal(B.노동글인가('연차휴가 미사용수당 지급 기준 바뀐다'), true);
});

/* ══════════════════════════════════════════════════════════════════════════
   ③ 골고루 — 많이 실은 신문사가 자리를 다 먹지 않게
   ══════════════════════════════════════════════════════════════════════════ */

test('★★★ 돌아가며 고른다 — 한 신문사가 앞자리를 다 차지하지 않는다', () => {
  /* ⚠⚠ 모아 둔 것은 «모은 날»순이라, 기사를 많이 내는 신문사가 맨 앞을 줄줄이
       차지한다. 그대로 다섯을 끊으면 다섯이 다 한 곳 것이 된다 —
       신문사를 넷으로 늘린 뜻이 그 자리에서 사라진다. */
  const 줄 = [
    { 언론사: '가', 제목: '가1' }, { 언론사: '가', 제목: '가2' },
    { 언론사: '가', 제목: '가3' }, { 언론사: '가', 제목: '가4' },
    { 언론사: '나', 제목: '나1' }, { 언론사: '다', 제목: '다1' }
  ];
  const 나온것 = C.골고루(줄).slice(0, 3).map((x) => x.언론사);
  assert.deepEqual(나온것, ['가', '나', '다'],
    '★★★ 앞 셋이 ' + 나온것.join(',') + ' 이다 — 돌아가며 고르지 않았다');
});

test('★ 골고루 골라도 «하나도 잃지 않는다» — 차례만 바꾼다', () => {
  /* ⚠ 골고루가 «버리는» 일이 되면 안 된다. 몇 개까지 실을지는 꼭지가 정한다. */
  const 줄 = [
    { 언론사: '가', 제목: 'a' }, { 언론사: '나', 제목: 'b' },
    { 언론사: '가', 제목: 'c' }, { 제목: '출처없음' }
  ];
  const 나온것 = C.골고루(줄);
  assert.equal(나온것.length, 4, '★ 줄이 없어졌다');
  assert.deepEqual(나온것.map((x) => x.제목).sort(), ['a', 'b', 'c', '출처없음']);
});

test('★ 한 신문사 안에서는 «오던 차례»가 그대로다 — 새 것이 앞이다', () => {
  const 줄 = [
    { 언론사: '가', 제목: '새것' }, { 언론사: '가', 제목: '옛것' },
    { 언론사: '나', 제목: 'n' }
  ];
  const 가것 = C.골고루(줄).filter((x) => x.언론사 === '가').map((x) => x.제목);
  assert.deepEqual(가것, ['새것', '옛것']);
});

test('빈 것·이상한 것을 줘도 멎지 않는다', () => {
  assert.deepEqual(C.골고루(), []);
  assert.deepEqual(C.골고루(null), []);
  assert.deepEqual(C.골고루([null, undefined]), []);
});

/* ══════════════════════════════════════════════════════════════════════════
   ④ 다섯 이내 — 꼭지가 정하고, 담는 쪽이 지킨다
   ══════════════════════════════════════════════════════════════════════════ */

test('★★★ 주간노동뉴스는 «다섯을 넘지 않는다»', () => {
  const g = C.꼭지찾기('news');
  assert.ok(g, '주간노동뉴스 꼭지를 못 찾았다');
  assert.ok(g.몇개 <= 5,
    '★★★ 주간노동뉴스가 ' + g.몇개 + '개까지다 — 대표 지시는 「5개 이내」다');
});

test('★★★ 실제로 담아도 다섯을 넘지 않고, 한 곳 것만 담기지 않는다', () => {
  /* ★ 값이 아니라 «규칙»을 본다: 몇개가 셋으로 바뀌어도 이 검사는 산다. */
  const 모음 = {};
  const 신문 = ['매일노동뉴스', '참여와혁신', '아웃소싱타임스', '안전저널'];
  for (let i = 0; i < 24; i++) {
    /* ⚠ 앞쪽(모은날이 늦은 것)을 한 신문사로 몰아 둔다 — 실제로 이렇게 온다 */
    const 누구 = i < 12 ? 신문[0] : 신문[1 + (i % 3)];
    모음['k' + i] = {
      제목: '근로시간 관련 소식 ' + i, 링크: 'https://example.test/' + i,
      언론사: 누구, 모은날: '2026-09-' + String(30 - i).padStart(2, '0')
    };
  }
  /* ⚠ 회차 기간을 비워 둔다 — 「어느 주 것인가」를 가리는 일은 여기서 볼 것이 아니다.
       날짜 창까지 함께 걸면, 창이 바뀔 때 이 검사가 엉뚱하게 붉어진다. */
  const 안 = C.자동으로담기(모음, {}, { 기간시작: '', 기간끝: '' });
  const 담긴것 = (안.news || []).filter(Boolean);

  const 몇개 = C.꼭지찾기('news').몇개;
  assert.ok(담긴것.length <= 몇개,
    '★★★ ' + 담긴것.length + '건이 담겼다 — 꼭지가 정한 ' + 몇개 + '건을 넘었다');

  const 신문수 = Object.keys(담긴것.reduce((o, x) => {
    o[String(x.언론사 || '?')] = 1; return o;
  }, {})).length;
  assert.ok(신문수 >= 2,
    '★★★ 담긴 ' + 담긴것.length + '건이 모두 한 신문사 것이다 — 골고루가 아니다');
});

test('★★ 어디 것인지 «적는다» — 출처 없이는 남의 글을 싣지 않는다', () => {
  const 모음 = {
    a: { 제목: '임금체불 단속 강화', 링크: 'https://example.test/a',
      언론사: '참여와혁신', 모은날: '2026-09-29' }
  };
  const 안 = C.자동으로담기(모음, {}, { 기간시작: '', 기간끝: '' });
  assert.equal((안.news[0] || {}).언론사, '참여와혁신',
    '★★ 담기면서 언론사가 사라졌다');
});
