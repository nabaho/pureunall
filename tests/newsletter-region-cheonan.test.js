"use strict";
/* 천안시 기업지원을 «지역뉴스»로 읽는다 — 잣대는 넓히지 않고 «등록한 집만» 연다
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-13:
     「중소기업 육성자금 이자 지원 · 농공단지 물류비 지원 · 해외시장개척단 ·
      전시박람회 참가 지원 … 꼭지를 넓히는 일(노무 → 노무+기업지원) 이것도 같이해라」

   ★ 왜 «지역뉴스»인가 — 정책 꼭지에는 지역을 가르는 장치가 없다.
     천안시 공고를 거기 담으면 경기·대구 사업장에도 부평구 공고처럼 남의 동네 것이 간다.
     지역뉴스에는 지역뉴스고르기가 있어 「충남/천안시」로 좁힐 수 있다.

   ★★★ 공식링크 잣대를 go.kr 로 «통째로 넓히지 않는다».
     그러면 링크 하나만 잘못 긁어도 엉뚱한 기관 글이 우리 법인 이름으로 나간다.
     대신 «등록부에 적힌 집»만 연다 — 새 집을 열려면 등록부에 적어야 하니
     저절로 검토를 거친다. 좁고, 스스로 지켜진다.

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ① 잣대는 «등록한 집»만 연다 — go.kr 아무 데나가 아니다
     ② 천안시 소식은 «천안에만» 간다
     ③ 기업지원 말(육성자금·물류비·판로)이 관련말에 있다
     ④ 지자체 행정(공시송달·주민등록·민방위)은 «안 담는다»

   ⚠ 인터넷을 두드리지 않는다 — 2026-09-13 에 받아 온 조각으로 본다. */

const test = require("node:test");
const assert = require("node:assert");
const R = require("../functions/news-region.js");
const C = require("../js/pu-news-core.js");

const 천안시샘 = () => R.출처들.find((x) => x.id === "cheonan-company");

/* 2026-09-13 실측: /bbs/BBSMSTR_000000000241/list.do 의 «진짜» 줄 꼴.
   ⚠⚠ 제목이 <a href=…> 가 아니라 «<button onclick="fn_search_detail('아이디')">» 다.
     처음에 href 꼴로 지어 놓고 검사를 통과시켰더니 진짜 판에서 «0건»이 나왔다.
     ★ 박아 두는 조각은 저쪽이 내놓는 꼴이어야 한다 — 두 번째로 걸린 자리다. */
const 한줄 = (id, 제목) => [
  '<tr><td data-cell-header="제목" class="board__table--title">',
  '<button onclick="fn_search_detail(\'' + id + '\'); return false;" class="board__link">',
  '<div class="board__subject-content"><div class="board__subject-text-wrap type1">',
  '<strong class="board__subject-text">' + 제목 + '</strong>',
  '</div></div></button></td><td>2026-09-09</td></tr>',
].join("\n");

const 천안시조각 = [
  '<tbody>',
  한줄("B000000507174Fe7mJ1", "2026년 천안시 중소기업 육성자금 이자 지원계획 추가접수 공고"),
  한줄("B00000405814MTRM5Sv", "2026 농공단지 물류비 지원사업 공고 (2차)"),
  한줄("B00000402121xHlDdQz", "천안시 중소기업 우수제품 홍보판매관 참가기업 모집 공고"),
  한줄("B00000402122aaaaaaa", "2026년 민방위 보충1차 집합교육 통지서 반송에 따른 공시송달 공고"),
  '</tbody>',
].join("\n");

/* ══════════════════════════════════════════════════════════════════════════
   ① 잣대 — «등록한 집»만 연다
   ══════════════════════════════════════════════════════════════════════════ */

test("★★★ 잣대는 «등록부에 적힌 집»만 연다 — go.kr 아무 데나가 아니다", () => {
  /* ⚠⚠ go.kr 을 통째로 열면 링크 하나만 잘못 긁어도 엉뚱한 기관 글이
       우리 법인 이름으로 114곳에 나간다. 등록한 집만 열면 새 집을 들이려면
       등록부에 적어야 하니 저절로 검토를 거친다. */
  assert.equal(R.공식링크인가("https://www.moel.go.kr/local/cheonan/news/notice/noticeView.do?bbs_seq=1"),
    true, "고용노동부를 막는다");
  assert.equal(R.공식링크인가("https://www.cheonan.go.kr/bbs/BBSMSTR_000000000241/view.do?nttId=600"),
    true, "★ 등록한 천안시를 안 연다");
  assert.equal(R.공식링크인가("https://www.chungnam.go.kr/cnportal/bbs/view.do?nttId=1"),
    false, "★★★ 등록하지 않은 집이 열렸다 — 잣대가 go.kr 로 넓어졌다");
  assert.equal(R.공식링크인가("https://www.korea.kr/news/x.do"),
    false, "★★★ 아무 go.kr 이나 열린다");
  assert.equal(R.공식링크인가("https://cheonan.go.kr.example.com/x"),
    false, "★★★ 이름만 흉내 낸 집이 지나간다");
  assert.equal(R.공식링크인가("http://www.cheonan.go.kr/bbs/x"),
    false, "http 를 연다 — https 만 받아야 한다");
});

/* ══════════════════════════════════════════════════════════════════════════
   ② 천안시 소식은 천안에만
   ══════════════════════════════════════════════════════════════════════════ */

test("★★ 천안시 소식은 «천안에만» 간다", () => {
  const s = 천안시샘();
  assert.ok(s, "★ 천안시가 서버 출처에 없다");
  assert.equal(s.지역, "충남/천안시", "지역을 시까지 안 좁혔다");
  const 뉴스 = [{ 지역: s.지역, 상태: "승인" }];
  assert.equal(C.지역뉴스고르기(뉴스, C.지역코드("충남 천안시 서북구")).length, 1, "천안에 안 간다");
  assert.equal(C.지역뉴스고르기(뉴스, C.지역코드("충남 아산시")).length, 0,
    "★★ 천안시 공고가 아산까지 간다");
  assert.equal(C.지역뉴스고르기(뉴스, C.지역코드("경기도 평택시")).length, 0,
    "★★ 천안시 공고가 경기까지 간다");
});

/* ══════════════════════════════════════════════════════════════════════════
   ③ 기업지원은 담고, 지자체 행정은 안 담는다
   ══════════════════════════════════════════════════════════════════════════ */

test("★★ 제목이 «단추(onclick)»에 있어도 읽고, 상세 주소를 세운다", () => {
  /* ⚠⚠ 이 판에는 제목 링크가 «없다». 단추를 눌러 여는 꼴이라 href 만 찾으면 0건이다.
       ★ 상세 주소는 목록길이 아니라 «상세길 + 아이디»로 세운다. */
  const 것 = R.후보만들기(천안시조각, 천안시샘(), {}, 1789000000000);
  assert.ok(것.length > 0, "★★ 한 건도 못 읽었다 — 단추 꼴을 못 읽는다");
  const 하나 = 것.find((x) => x.제목.indexOf("육성자금") >= 0);
  assert.ok(하나, "육성자금 줄을 못 찾았다");
  assert.equal(하나.링크,
    "https://www.cheonan.go.kr/bbs/BBSMSTR_000000000241/view.do?nttId=B000000507174Fe7mJ1",
    "★★ 상세 주소가 틀리다: " + 하나.링크);
});

test("★★★ 기업지원 공고를 담는다 — 대표가 이름 대어 말씀하신 것들이다", () => {
  const 것 = R.후보만들기(천안시조각, 천안시샘(), {}, 1789000000000);
  const 제목들 = 것.map((x) => x.제목);
  assert.ok(제목들.some((t) => t.indexOf("육성자금") >= 0),
    "★★★ 중소기업 육성자금 이자 지원을 못 담았다");
  assert.ok(제목들.some((t) => t.indexOf("물류비") >= 0),
    "★★★ 농공단지 물류비 지원을 못 담았다");
  assert.ok(제목들.some((t) => t.indexOf("홍보판매관") >= 0),
    "★ 판로 지원(참가기업 모집)을 못 담았다");
});

test("★★ 지자체 «행정» 공고는 안 담는다 — 사업장이 챙길 일이 아니다", () => {
  /* ⚠⚠ 천안시 판에는 공시송달·주민등록·민방위가 잔뜩이다(실측 2026-09-13).
       그대로 열면 검토함이 그것으로 찬다. */
  const 것 = R.후보만들기(천안시조각, 천안시샘(), {}, 1789000000000);
  assert.ok(!것.some((x) => x.제목.indexOf("공시송달") >= 0),
    "★★ 공시송달 공고가 들어왔다");
  ["거주불명등록자 행정상관리주소 이전 직권조치 공고",
    "주민등록증 발급통지서 반송자 공고(2009년 09월생)",
    "제43회 천안시 건축위원회 심의 주요결과 공고",
    "「식품위생법」위반 과태료 체납에 따른 납부 독촉 공시송달 공고",
  ].forEach((t) => assert.equal(R.쓸모있는가(t, 천안시샘()), false,
    "★★ 지자체 행정이 들어온다: " + t));
});

test("기업지원 말을 넓히면서 «노무 쪽»은 그대로다", () => {
  /* ⚠ 한쪽을 넓히다가 다른 쪽 잣대가 헐거워지면 안 된다 */
  assert.equal(R.쓸모있는가("[안내] 대량 고용변동 신고제도 안내"), true, "노무 공지를 걸렀다");
  assert.equal(R.쓸모있는가("[공고] 기간제근로자(통계조사관) 채용 공고"), false,
    "관서 채용 공고가 다시 새어 든다");
});
