/* 연습 표본은 «진짜 발송»으로 나가지 않는다 (대표 검증 지시 2026-09-20)
   ═══════════════════════════════════════════════════════════════════════════
   「뉴스레터 시스템 전체적 검토해달라. 메일 보내고 받은사람이 팝업으로 창을 봤을때
    어색한지 불필요한 화면 없는지 …」 → 검증에서 제일 먼저 드러난 구멍이다.

   ■ 무슨 일이 있었나 (2026-09-20 실측, 회차 2026-09-w3)
     연습샘플() 은 모든 줄에 「[연습]」을 붙여 «눈에 보이게» 해 두었다. 그런데
     보내기를 막지는 «않았다» — 사람이 알아채는 데 기대고 있었다.
     그 회차에는 연습 5건 + 「[연습] 이번 주 한마디 — 이 칸만 우리가 씁니다」가
     그대로 실려 있었고, 보낼수있나() 는 ok:true 를 돌려주었다.
     대표께서 「N곳에 보내기」를 누르셨다면 그대로 자문사에 나갔다.

   ■ 이 검사가 지키는 것
     ㉠ [연습] 이 한 줄이라도 남아 있으면 «진짜 발송»은 막힌다
     ㉡ «시험 발송»은 안 막힌다 — 연습은 시험으로 하라고 만든 것이다
     ㉢ 상태(시험/초안)로는 막지 «않는다» — 시험 한 통만 보내도 상태가 시험이 되므로
        상태로 막으면 멀쩡한 회차가 영영 못 나간다
     ㉣ 화면의 세 단추가 «각각 맞는 잣대»를 쓴다 */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { 주석걷기 } = require('./helpers/strip-comments.js');

const 뿌리 = path.join(__dirname, '..');
const C = require('../js/pu-news-core.js');
const 화면 = 주석걷기(fs.readFileSync(path.join(뿌리, 'pu-news.html'), 'utf8'));

const 셈 = { 보낼곳: 120 };
const 진짜기사 = { 갈래: '기사', 제목: '유급 난임치료휴가 2일에서 4일로',
  링크: 'https://www.labortoday.co.kr/news/articleView.html?idxno=1', 언론사: '매일노동뉴스' };
const 회차 = (덧) => Object.assign({ 상태: '시험', 안: { news: [진짜기사] }, 우리글: '' }, 덧 || {});

/* ═══ ㉠ 연습이 남아 있으면 진짜 발송이 막힌다 ═══════════════════════════ */

test('★★★ [연습] 이 남아 있으면 «진짜 발송»이 막힌다', () => {
  const 연습판 = 회차({ 안: C.연습샘플(), 우리글: '[연습] 이번 주 한마디 — 이 칸만 우리가 씁니다.' });
  const r = C.보낼수있나(연습판, 셈);
  assert.equal(r.ok, false,
    '★★★ 연습 표본이 그대로 실린 회차가 «보낼 수 있다»로 나왔다 — 고객에게 연습 글이 간다');
  assert.match(String(r.까닭), /연습/,
    '★ 막기는 막았는데 «왜»를 안 말한다 — 대표께서 「고장났다」로 보신다');
});

test('★★★ 세는 자리는 제목 말고도 «우리말·한줄·요지·딱지·우리글»이다', () => {
  /* ⚠ 연습 표본은 요지에도 「[연습]」을 붙인다. 제목만 보면 그 줄을 놓친다. */
  const 자리들 = ['제목', '우리말', '한줄', '요지', '딱지'];
  자리들.forEach((자리) => {
    const 한줄 = { 갈래: '기사', 제목: '보통 제목', 링크: 'https://a.kr/x' };
    한줄[자리] = '[연습] ' + (한줄[자리] || '');
    assert.equal(C.연습남은것({ 안: { news: [한줄] } }), 1,
      '★★★ 「' + 자리 + '」에 붙은 [연습] 을 못 본다');
  });
  assert.equal(C.연습남은것({ 안: {}, 우리글: '[연습] 이번 주 한마디' }), 1,
    '★★★ 우리글에 남은 [연습] 을 못 본다 — 실제로 거기 남아 있었다');
  assert.equal(C.연습남은것(회차()), 0,
    '(재기 값) 연습이 없는 회차를 «있다»고 한다 — 멀쩡한 발송이 영영 막힌다');
});

/* ═══ ㉡ 시험 발송은 안 막힌다 ═════════════════════════════════════════ */

test('★★★ «시험 발송»은 연습이 있어도 눌린다 — 연습은 시험으로 하는 것이다', () => {
  /* 대표 지시 2026-09-03 「연습으로 보내봐야 한다」. 화면도 그렇게 적어 두고 있다:
     「⚠ 연습은 「시험 발송」으로만 하세요」. 시험까지 막으면 그 길이 없어진다. */
  const 연습판 = 회차({ 안: C.연습샘플(), 우리글: '[연습] 이번 주 한마디' });
  assert.equal(C.보낼수있나(연습판, 셈, { 시험: true }).ok, true,
    '★★★ 시험 발송까지 막혔다 — 연습 표본을 «보내 볼 길»이 사라졌다');
});

/* ═══ ㉢ 상태로는 막지 않는다 ══════════════════════════════════════════ */

test('★★★ 상태가 «시험»이라는 까닭만으로는 막지 않는다', () => {
  /* ⚠ 시험 한 통만 보내도 상태가 초안→시험이 된다(js/pu-news-core.js ⑨ 주석).
       상태로 막으면 «시험해 본 회차»는 영영 못 나간다. */
  assert.equal(C.보낼수있나(회차({ 상태: '시험' }), 셈).ok, true,
    '★★★ 상태가 시험이라고 막았다 — 시험해 본 회차가 영영 못 나간다');
});

/* ═══ ㉣ 화면의 세 단추가 각각 맞는 잣대를 쓴다 ═════════════════════════ */

test('★★★ 시험 단추만 «시험 잣대»를 쓰고, 진짜 발송·예약은 «막는 잣대»를 쓴다', () => {
  assert.match(화면, /const\s+시험갈수있나\s*=\s*Core\.보낼수있나\([^)]*\{\s*시험:\s*true\s*\}\s*\)/,
    '★★★ 화면이 시험용 잣대를 따로 안 만든다 — 연습이 시험 발송까지 잠근다');
  assert.match(화면, /onclick="시험발송\(\)"\s*\$\{시험갈수있나\.ok/,
    '★★★ 시험 발송 단추가 «막는 잣대»에 물려 있다');
  assert.match(화면, /onclick="진짜보내기\(\)"[\s\S]{0,200}?\$\{갈수있나\.ok\s*&&\s*App\.isAdmin/,
    '★★★ 진짜 발송 단추가 «시험 잣대»로 풀려 있다 — 연습이 그대로 나간다');
  assert.match(화면, /onclick="자동발송준비\(\)"[\s\S]{0,220}?\$\{갈수있나\.ok\s*&&\s*App\.isAdmin/,
    '★★★ 자동발송 예약이 «시험 잣대»로 풀려 있다 — 월요일 아침에 연습이 나간다');
});

test('못 누르는 단추는 «왜»를 달고 있다', () => {
  /* 잠긴 단추만 있고 까닭이 없으면 대표께서 「고장났다」로 보신다. */
  assert.match(화면, /onclick="진짜보내기\(\)"[\s\S]{0,120}?title="\$\{esc\(갈수있나\.ok\s*\?\s*''\s*:\s*갈수있나\.까닭\)\}"/,
    '★ 진짜 발송 단추에 까닭이 안 붙는다');
});
