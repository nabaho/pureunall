'use strict';
/* 메일로 나가는 편지를 «전문판»으로 (대표 지시 2026-09-20)
   ═══════════════════════════════════════════════════════════════════════════
   「메일에서 받을때 화면을 캡쳐2로 해라 그게 더 안정적이다.
    그리고 뉴스레터관리에도 캡쳐2와 같은 디자인 화면으로 나오게 해라」

   ⚠ 2026-09-12 에는 그 반대였다 — 「한화면에 요약만 나오게, 클릭하면 확인」.
     그래서 메일은 «요약판»(점 목록 + 전문 보기 ↗)으로 나갔다.
     그것을 뒤집는 지시다. 까닭도 대표께서 말씀하셨다 — «그게 더 안정적이다».
     요약판은 자료를 받으려면 웹으로 한 번 더 나가야 한다. 메일 프로그램이
     링크를 막거나 손님이 안 누르면 그대로 끝이다. 전문판은 편지 «안»에
     내려받기 단추까지 다 있다.
   ★ 옛 회차는 «그때 나간 그대로» 그려져야 한다 — 꼴 을 회차에 적어 두는 까닭이다.
     이 지시는 «앞으로 나갈 것»을 바꾼다. 지난 회차를 고치는 것이 아니다.

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ① 나가는 편지는 전문판이다
     ② 메일 폭은 그대로 700 — 웹 폭(980)으로 지으면 메일 프로그램이 무너진다
     ③ 미리보기와 나가는 것이 «같은 것»이다 — 시험이 시험이 되려면
     ④ 전문판에는 내려받기 단추가 «편지 안»에 있다
     ⑤ 메일은 둘씩, 웹은 셋씩 — 이미 재 보고 고른 것이라 되돌리지 않는다 */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { stripComments } = require('./strip-comments');

const ROOT = path.join(__dirname, '..');
const 날글 = fs.readFileSync(path.join(ROOT, 'pu-news.html'), 'utf8').replace(/\r\n/g, '\n');
const news = stripComments(날글);

const T = require('../js/pu-news-tpl.js');
const C = require('../js/pu-news-core.js');

const 함수 = (이름) => {
  const i = news.indexOf('function ' + 이름 + '(');
  assert.ok(i > 0, 이름 + ' 을 못 찾음');
  return news.slice(i, news.indexOf('\n}', i));
};

const 자료하나 = {
  갈래: '자료', 제목: '마트배송 직종 표준계약서 및 활용가이드',
  우리말: '고용노동부가 마트배송 기사와 맺는 위탁계약의 «정부 표준안»을 내놓았습니다.',
  발행처: '고용노동부', 기관: '고용노동부', 링크: 'https://www.moel.go.kr/a',
  파일: 'https://www.moel.go.kr/file.do?id=1', 확장자: 'hwpx', 파일크기: 64512
};

/* ══════════════════════════════════════════════════════════════════════════
   ① 나가는 편지가 전문판인가
   ══════════════════════════════════════════════════════════════════════════ */

test('★★★ 메일로 나가는 편지는 «전문판»이다', () => {
  /* ⚠ 지금편지() 하나가 시험 발송·자동발송 확정본·진짜 보내기·크게 보기를 다 짓는다.
       여기가 요약이면 네 곳이 다 요약이다. */
  const fn = 함수('지금편지');
  assert.ok(/요약:\s*false/.test(fn),
    '★★★ 나가는 편지가 아직 요약판이다 — 자료를 받으려면 웹으로 또 나가야 한다');
});

test('★★★ 메일 폭은 «그대로 700» — 웹 폭으로 지으면 메일이 무너진다', () => {
  /* ⚠⚠ 전문은 웹에서 980 으로 그린다(자료 카드 셋씩). 그 폭 그대로 메일에 넣으면
       아웃룩·네이버메일에서 표가 옆으로 삐져나가거나 글자가 깨알이 된다.
     ★ 전문판 «모양»을 쓰되 폭은 메일 폭이다 — 그래서 넓이를 넘기지 않는다. */
  const fn = 함수('지금편지');
  assert.ok(!/넓이:/.test(fn),
    '★★★ 나가는 편지에 넓이를 지정했다 — 메일은 기본 700 이라야 한다');
});

test('★★★ 회차에 적는 꼴이 «전문»이다 — 지난 회차는 그때 나간 그대로여야 한다', () => {
  /* ⚠⚠ 꼴 은 「이 회차가 어떤 모습으로 나갔나」의 기록이다. 여기를 '요약' 으로
       두면, 이번에 전문으로 보내 놓고 나중에 다시 그릴 때 «요약으로» 그려진다 —
       보낸 것과 보관한 것이 달라진다. */
  const fn = 함수('전문담기');
  assert.ok(/꼴:\s*'전문'/.test(fn),
    "★★★ 회차에 꼴:'요약' 을 적고 있다 — 보낸 모습과 다시 그린 모습이 달라진다");
});

test('★★ 미리보기와 나가는 것이 «같은 것»이다 — 시험이 시험이 되려면', () => {
  /* ⚠ 「크게 보기」가 요약인데 나가는 것이 전문이면, 보시고 승인한 것과 다른 편지가
       143곳에 나간다. 둘은 한 함수라야 한다. */
  ['크게보기', '시험발송', '자동발송준비'].forEach((이름) => {
    assert.ok(/지금편지\(/.test(함수(이름)),
      '★★ ' + 이름 + ' 이 지금편지() 를 안 쓴다 — 미리보기와 갈라진다');
  });
});

/* ══════════════════════════════════════════════════════════════════════════
   ② 전문판이 실제로 «그 모습»인가 — 편지를 지어서 본다
   ══════════════════════════════════════════════════════════════════════════ */

const 회 = C.회차(new Date('2026-09-20T00:00:00Z'));
function 지어보기(폭) {
  return T.편지짓기(
    { 회차: 회, 상태: '초안', 안: { news: [], policy: [자료하나], case: [], hr: [] } },
    { 회사이름: '푸른노무법인' },
    Object.assign({ 요약: false, 미리보기: true }, 폭 ? { 넓이: 폭 } : {})).서식;
}

test('★★★ 전문판에는 내려받기 단추가 «편지 안»에 있다', () => {
  /* ★ 이것이 「안정적이다」의 알맹이다 — 웹으로 한 번 더 나가지 않아도 받을 수 있다. */
  const 글 = 지어보기();
  assert.ok(/내려받기\s*↓/.test(글), '★★★ 편지 안에 내려받기 단추가 없다');
  assert.ok(글.indexOf('https://www.moel.go.kr/file.do?id=1') >= 0,
    '★★★ 파일 주소가 편지에 없다 — 눌러도 받을 곳이 없다');
});

test('★★ 전문판에는 「요약입니다」 띠가 «없다» — 요약이 아닌데 그렇게 적으면 거짓말이다', () => {
  const 글 = 지어보기();
  assert.ok(!/한 줄 요약입니다/.test(글),
    '★★ 전문으로 보내면서 「한 줄 요약입니다」라고 적고 있다');
});

test('★★ 메일도 셋씩이되 «표»로, 웹은 «칸틀»로 — 아웃룩은 grid 를 모른다', () => {
  /* ★ 2026-09-26 대표 지시로 메일도 980·셋씩이 됐다. 그래도 갈리는 자리는 남는다:
       웹은 칸틀(단추 바닥이 맞는다), 메일은 표(아웃룩이 아는 유일한 자리잡기). */
  const 여럿 = [1, 2, 3, 4, 5, 6].map((n) =>
    Object.assign({}, 자료하나, { 제목: '자료 ' + n, 링크: 'https://x.test/' + n }));
  const 짓기 = (옵션) => T.편지짓기(
    { 회차: 회, 상태: '초안', 안: { news: [], policy: 여럿, case: [], hr: [] } },
    { 회사이름: '푸른노무법인' },
    Object.assign({ 요약: false, 미리보기: true }, 옵션 || {})).서식;
  const 웹 = 짓기({ 넓이: T.전문넓이, 웹: true });
  const 메일 = 짓기();
  assert.ok(/display:\s*grid/.test(웹),
    '★★ 넓은 쪽에서 칸틀을 안 쓴다 — 단추 줄이 카드마다 어긋난다');
  assert.ok(!/display:\s*grid/.test(메일),
    '★★ 메일에서 칸틀을 쓴다 — 아웃룩은 grid 를 모른다');
  assert.ok(메일.indexOf('width="33%"') >= 0,
    '★★ 메일이 아직 둘씩이다 — 대표 지시 2026-09-26 「좌우로 넓게」');
});

test('★ 옛 회차는 «그때 나간 그대로» — 꼴 이 적혀 있으면 그것이 이긴다', () => {
  /* ⚠ 이 지시는 «앞으로 나갈 것»을 바꾼다. 지난 회차까지 전문으로 다시 그리면
       「그때 보낸 것」과 보관본이 달라진다. */
  const 옛 = T.편지짓기(
    { 회차: 회, 상태: '발송', 꼴: '요약',
      안: { news: [], policy: [자료하나], case: [], hr: [] } },
    { 회사이름: '푸른노무법인', 추적밑주소: 'https://x.cloudfunctions.net' },
    { 미리보기: true }).서식;
  assert.ok(/한 줄 요약입니다/.test(옛),
    '★ 꼴:요약 으로 보낸 지난 회차가 전문으로 다시 그려진다');
});
