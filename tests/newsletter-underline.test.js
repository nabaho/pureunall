/* 이번 주 한마디 — 핵심에 «밑줄» (대표 지시 2026-09-27)
   「인사노무관리에서 핵심내용은 아랫줄 표시 했으면 좋겠다」

   ■ 이 검사가 지키는 «규칙»
     ① 글 속 __핵심__ 이 편지(메일·전문)에서 밑줄(<u>)이 된다 — 발송기를 지난 뒤에도
     ② 밑줄을 못 그리는 자리(평문·한 줄 요약)에는 「__」가 안 찍힌다
     ③ 사람 글의 태그는 여전히 안 믿는다 — 손으로 적은 <u>·<script> 는 글자로 나간다
     ④ AI 에게 밑줄«만» 맡길 때 글자가 하나라도 바뀌면 «받지 않는다» (법률 글이다)
     ⑤ 짓는 지시와 긋는 지시가 같은 말을 쓴다 */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const C = require('../js/pu-news-core.js');
const T = require('../js/pu-news-tpl.js');
const MS = require('../functions/mail-send.js');
const { 주석걷기, 함수몸 } = require('./helpers/strip-comments.js');

const 화면 = 주석걷기(fs.readFileSync(path.join(__dirname, '..', 'pu-news.html'), 'utf8'));

function 회차(글) {
  return {
    회차: C.회차('2026-09-21'),
    우리글: 글,
    안: { hr: [{ 갈래: '자료', 제목: '가나상사 사례로 보는 연차 관리', 발행처: '고용노동부',
      파일: 'https://www.moel.go.kr/f1.pdf', 발행일: '20260901' }] }
  };
}
const 글 = '대법원은 하청 노동조합의 교섭 요구에 원청이 응해야 하는 범위를 정했습니다. '
  + '__원청도 실질적 지배력이 있으면 교섭 의무가 있습니다__. 사업장에서는 '
  + '__도급 계약서의 지휘·감독 조항__을 다시 보셔야 합니다.';

test('★★★ __핵심__ 이 편지에서 «밑줄»이 된다 — 발송기를 지난 뒤에도', () => {
  const 서식 = T.편지짓기(회차(글), { 회사이름: '푸른노무법인' }, { 요약: false }).서식;
  const 씻긴 = MS.sanitizeHtml(서식);
  const 밑줄 = 씻긴.match(/<u\b[^>]*>([^<]*)<\/u>/g) || [];
  assert.ok(밑줄.length >= 2, '★★★ 밑줄이 안 나간다 — 받는 분 화면에 핵심이 안 보인다');
  assert.match(씻긴, /<u\b[^>]*>원청도 실질적 지배력이 있으면 교섭 의무가 있습니다<\/u>/,
    '밑줄 안의 글이 달라졌다');
  assert.ok(씻긴.indexOf('__') < 0, '★★ 「__」 표가 그대로 찍혀 나간다');
});

test('★★ 웹 전문(팝업·전문 보기)에서도 밑줄이다', () => {
  const 웹 = T.편지짓기(회차(글), { 회사이름: '푸른노무법인' }, { 요약: false, 웹: true }).서식;
  assert.ok((웹.match(/<u\b/g) || []).length >= 2, '★★ 웹 전문에 밑줄이 없다');
  assert.ok(웹.indexOf('__') < 0, '웹 전문에 「__」가 찍힌다');
});

test('★★ 밑줄을 못 그리는 자리에는 「__」를 걷는다 — 평문·한 줄 요약', () => {
  const 평 = T.평문짓기(회차(글), { 회사이름: '푸른노무법인' });
  const 평글 = typeof 평 === 'string' ? 평 : JSON.stringify(평);
  assert.ok(평글.indexOf('원청도 실질적 지배력') >= 0, '평문에 한마디가 없다 — 검사가 헛돈다');
  assert.ok(평글.indexOf('__') < 0, '★★ 평문 메일에 「__」가 찍힌다');
  /* ⚠ 요약판은 «전문 주소»가 있어야 그려진다(없으면 저절로 전문판으로 물러선다).
       주소를 안 주면 이 검사는 전문판을 보고 «통과»한다 — 되돌림 검사에서 드러났다. */
  const 요회 = 회차('__핵심부터__ 시작하는 글입니다. 둘째 문장.');
  요회.회차.열쇠 = '2026-09-w4';
  const 요 = T.편지짓기(요회, { 회사이름: '푸른노무법인', 추적밑주소: 'https://example.test/fn' },
    { 요약: true }).서식;
  /* 요약판의 줄은 전문으로 가는 링크(추적 newsClick)를 단다 — 전문판에는 없다 */
  assert.match(요, /newsClick\?i=/, '요약판이 안 그려졌다 — 검사가 헛돈다');
  assert.ok(요.indexOf('핵심부터') >= 0, '요약에 한마디가 없다 — 검사가 헛돈다');
  assert.ok(요.indexOf('__') < 0, '★★ 한 줄 요약에 「__」가 찍힌다');
});

test('★★★ 사람 글의 태그는 여전히 안 믿는다 — 밑줄 «표»만 바뀐다', () => {
  const 서식 = T.편지짓기(회차('손으로 <u>적은</u> 것과 <script>x()</script> 그리고 __진짜 밑줄__'),
    { 회사이름: '푸른노무법인' }, { 요약: false }).서식;
  assert.ok(서식.indexOf('&lt;u&gt;적은') >= 0, '★★★ 사람이 적은 태그를 그대로 믿었다');
  assert.ok(서식.indexOf('<script>x()') < 0, '★★★ 사람이 적은 script 가 살아 나간다');
  assert.match(서식, /<u\b[^>]*>진짜 밑줄<\/u>/, '밑줄 표가 안 바뀌었다');
});

test('★ 밑줄걷기는 표만 걷고 글은 그대로다', () => {
  assert.strictEqual(T.밑줄걷기('가 __나__ 다 __라마__'), '가 나 다 라마');
  assert.strictEqual(T.밑줄걷기('표 없는 글'), '표 없는 글');
  assert.strictEqual(T.밑줄걷기(null), '');
});

test('★★★ AI 에게 밑줄«만» 맡길 때 글자가 바뀌면 받지 않는다 — 법률 글이다', () => {
  const 몸 = 함수몸(화면, '한마디밑줄긋기');
  assert.ok(몸, '한마디밑줄긋기 가 없다');
  /* 받은 답에서 표를 걷어 원문과 «같을 때만» 쓴다 */
  assert.match(몸, /PuNewsTpl\.밑줄걷기\(글\)\.trim\(\)\s*!==\s*원문/,
    '★★★ 표를 걷은 답을 원문과 견주지 않는다 — 날짜 하나 바뀌어도 그대로 나간다');
  const i견 = 몸.search(/PuNewsTpl\.밑줄걷기\(글\)/);
  const i씀 = 몸.indexOf('이제.우리글 = 글');
  assert.ok(i견 > 0 && i씀 > i견, '★★★ 견주기 «전에» 한마디를 덮어쓴다');
  /* 사람이 그 사이 고쳤으면 덮지 않는다 · 보낸 회차는 안 고친다 */
  assert.match(몸, /String\(이제\.우리글\|\|''\)\.trim\(\)\s*!==\s*원문/, '★★ 그 사이 고친 글을 덮는다');
  assert.match(몸, /상태\s*===\s*'발송'/, '★★ 보낸 회차의 한마디를 고친다');
});

test('★ 짓는 지시와 긋는 지시가 «같은 말»이다', () => {
  /* ⚠ 2026-09-28 부터 밑줄 지시·한마디 지시는 Core «한 벌»이다 — 화면과 금요일 자동 준비가 같이 부른다 */
  assert.match(함수몸(화면, '한마디초안짓기'), /Core\.한마디지시\(/, '★ 한마디를 지을 때 한 벌 지시를 안 부른다');
  assert.ok(C.한마디지시([]).indexOf(C.밑줄지시) >= 0, '★ 한마디를 지을 때 밑줄을 안 긋는다');
  assert.match(함수몸(화면, '한마디밑줄긋기'), /Core\.밑줄지시/, '긋는 지시가 따로 논다');
  assert.match(C.밑줄지시, /__[^_]+__/, '밑줄지시에 표(__)가 안 적혀 있다');
});
