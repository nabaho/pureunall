'use strict';
/* 자료 카드에 «우리 글»을 싣는다 — 제목만 던져 놓지 않는다
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-13: 「우리글 니가 정리해서 달라. 필요한부분 자동으로」

   ⚠ 실측 2026-09-13: 자료 넷에 우리 설명을 달아 두었는데 편지에 «한 줄도»
     안 나갔다. 자료카드가 그리는 것은 제목·목차·발행처·내려받기뿐이라
     우리말을 앉힐 자리가 아예 없었다. 달아 두고도 안 보이면 없는 것과 같다.

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ① 자료에 우리말이 있으면 카드에 «실린다»
     ② 우리말이 목차보다 «앞선다» — 우리가 쓴 것이 남이 매긴 차례보다 값지다
     ③ 우리말이 없으면 «옛대로» 목차를 쓴다 — 있던 것을 빼앗지 않는다
     ④ 둘 다 없으면 «아무것도 지어내지 않는다»

   ⚠ 인터넷을 두드리지 않는다. */

const test = require('node:test');
const assert = require('node:assert');

const T = require('../js/pu-news-tpl.js');

const 설정 = { 이름: '푸른노무법인' };
const 감 = (자료) => T.편지짓기(
  { 날짜: '2026-09-13', 안: { news: [], policy: [자료], case: [], hr: [] } },
  설정, { 미리보기: true }
);

const 바탕 = {
  갈래: '자료',
  제목: '사업주와 인사담당자를 위한 난임치료휴가 및 급여제도 활용가이드',
  링크: 'https://www.moel.go.kr/policy/policydata/view.do?bbs_seq=20260800716',
  발행처: '고용노동부',
  발행일: '2026-08-24',
  파일: 'https://www.moel.go.kr/common/downloadFile.do?file_seq=20260801571',
  파일이름: '난임치료휴가 활용가이드.pdf',
  확장자: 'pdf',
};

test('★ 자료에 우리말이 있으면 카드에 실린다 — 달아 두고도 안 보이면 없는 것이다', () => {
  const 내글 = '난임치료휴가는 지금 연 6일, 그중 2일이 유급입니다.';
  const 편 = 감(Object.assign({}, 바탕, { 우리말: 내글 }));
  assert.ok(편, '편지가 안 만들어졌다');
  assert.ok(편.서식.indexOf(내글) >= 0,
    '★ 자료에 붙인 우리말이 편지 서식에 «안 실렸다» — 자료카드에 자리가 없다');
});

test('★ 우리말이 «목차보다 앞선다» — 우리가 쓴 것이 남이 매긴 차례보다 값지다', () => {
  const 내글 = '취업규칙에 옛 기준이 남아 있는 곳이 아직 많습니다.';
  const 목차한줄 = '제1장 제도의 개요';
  const 편 = 감(Object.assign({}, 바탕, { 우리말: 내글, 목차: [목차한줄, '제2장 신청 절차'] }));
  assert.ok(편.서식.indexOf(내글) >= 0, '우리말이 안 실렸다');
  assert.ok(편.서식.indexOf(목차한줄) < 0,
    '★ 우리말이 있는데 목차까지 같이 나온다 — 카드가 두 배로 길어진다');
});

test('우리말이 없으면 «옛대로» 목차를 쓴다 — 있던 것을 빼앗지 않는다', () => {
  const 목차한줄 = '제1장 제도의 개요';
  const 편 = 감(Object.assign({}, 바탕, { 목차: [목차한줄] }));
  assert.ok(편.서식.indexOf(목차한줄) >= 0,
    '우리말을 넣느라 목차가 사라졌다 — 옛 회차가 빈 카드로 그려진다');
});

test('★ 둘 다 없으면 «아무것도 지어내지 않는다»', () => {
  /* ⚠ 자료 설명을 기계가 지어내면 «책에 없는 말»이 법인 이름으로 나간다.
       보도자료에는 목차가 없다 — 그때는 제목과 내려받기만 나가야 한다. */
  const 편 = 감(Object.assign({}, 바탕));
  assert.ok(편.서식.indexOf(바탕.제목) >= 0, '제목마저 안 나온다');
  assert.ok(편.서식.indexOf('내려받기') >= 0, '내려받기 단추가 없다');
});

test('★★★ 자료의 우리말도 «우리가 쓴 것»만 나간다 — 발행처 설명은 실리지 않는다', () => {
  /* ⚠⚠ 자료에는 발행처가 쓴 설명(x.설명)이 함께 담겨 온다. 그것은 «남의 글»이다.
       우리말 자리에 그것이 새어 들어가면 남의 보도자료가 우리 이름으로 나간다. */
  const 몰래 = '이것은발행처가쓴설명입니다표시자777';
  const 편 = 감(Object.assign({}, 바탕, { 설명: 몰래 }));
  assert.ok(편.서식.indexOf(몰래) < 0,
    '★★★ 발행처가 쓴 설명이 편지에 실렸다 — 우리 글이 아니다');
});
