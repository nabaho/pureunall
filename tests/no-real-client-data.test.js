'use strict';
/* ══════ 저장소에 «진짜 의뢰인 자료»가 다시 들어오지 못하게 한다 (2026-09-18) ══════

   ■ 무엇이 있었나
     이 저장소는 PUBLIC 이다. 그런데 목업·검사·주석이 대부분 «살아 있는 화면을 떠서»
     만들어져, 실제 의뢰인 자료가 그대로 들어와 있었다.
       · 사업자등록번호 60여 가지 · 회사 이름 28곳 · 대표자 13명
       · 직원 이름과 짝지어진 **주민등록번호 열세 자리**
       · 부당해고·산재·임금체불 **사건 당사자의 실명**과 사건번호(목업 317장)
     2026-09-08 · 09-18 두 번에 걸쳐 치웠다. 그런데 사람 눈으로만 막으면
     **다음 달에 또 들어온다** — 화면을 떠 오는 것이 제일 빠른 길이기 때문이다.

   ★★★ 그래서 «모양»으로 막는다 — 값을 외우지 않는다
     지운 값을 목록으로 적어 두면 그 목록이 곧 유출이다. 그래서 여기에는
     **가짜가 갖춰야 할 모양**만 적는다. 모양에 안 맞으면 그 자리에서 멈춘다.

   ⚠ 걸렸을 때 고치는 법은 실패 글에 함께 적는다.
     「무엇이 걸렸는지」만 말하고 「어떻게 하라」를 안 적으면, 다음 사람은
     검사를 고치는 대신 **지우는 쪽**을 고른다.

   node --test tests/no-real-client-data.test.js */
const test = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { execSync } = require('node:child_process');

const R = path.join(__dirname, '..');

/* ── 훑을 파일 ─────────────────────────────────────────────────────────
   ⚠★ `git ls-files` 는 한글 이름을 «따옴표로 감싸» 내놓는다(core.quotepath).
     그대로 읽으면 한글 이름 파일이 통째로 빠지는데, 아무 소리도 안 난다 —
     2026-09-18 정리 때 실제로 그렇게 두 파일을 놓쳤다. 그래서 끄고 읽는다. */
function 훑을파일() {
  return execSync('git -c core.quotepath=false ls-files', { cwd: R, encoding: 'utf8', maxBuffer: 1 << 28 })
    .trim().split('\n')
    .filter(f => /\.(html|js|mjs|md|json|txt|css)$/.test(f))
    /* 남의 코드·우리 홈페이지 사본 — 우리가 짓는 예시가 아니다 */
    .filter(f => !/^(site|vendor|node_modules|reference)\//.test(f))
    .filter(f => !/^docs\/homepage-backup\//.test(f))
    .filter(f => !/^\.claude\//.test(f))
    /* 이 검사 자신 */
    .filter(f => f !== 'tests/no-real-client-data.test.js');
}
const 파일들 = 훑을파일();

/* 한 번만 읽어 둔다 — 규칙마다 다시 읽으면 1,900장을 네 번 훑는다 */
const 못읽음 = [];
const 글 = new Map();
파일들.forEach(f => {
  try { 글.set(f, fs.readFileSync(path.join(R, f), 'utf8')); } catch (_) { 못읽음.push(f); }
});
/* 규칙 하나를 «모든 파일»에 돌린다 — 걸린 자리를 모아 돌려준다 */
function 훑기(만들기, 찾기) {
  const 걸린것 = [];
  글.forEach((s, f) => {
    const re = new RegExp(만들기.source, 'g');
    let m;
    while ((m = re.exec(s))) { const t = 찾기(m); if (t) 걸린것.push(f + ' → ' + t); }
  });
  return [...new Set(걸린것)];
}

test('★ 훑을 파일을 실제로 읽는다 — 한 장도 조용히 빠지지 않는다', () => {
  assert.ok(파일들.length > 500, '훑은 파일이 ' + 파일들.length + '장뿐입니다 — 목록 만들기가 깨졌습니다');
  assert.deepEqual(못읽음, [],
    '★★★ 못 읽은 파일이 있으면 그 파일은 «검문을 안 받고» 지나갑니다.\n' +
    '  한글 이름 파일이 따옴표째 들어오면 이렇게 됩니다 — core.quotepath 를 보십시오.');
});

/* ══════ ① 사업자등록번호 ═══════════════════════════════════════════
   우리 예시 번호는 **123- 으로 시작한다.** 그 밖의 번호는 실제 사업장을
   가리킬 수 있다 — 국세청에 치면 어느 회사인지 바로 나온다. */
const BIZ = /\b[0-9]{3}-[0-9]{2}-[0-9]{5}\b/g;
/* 우리 것이거나, 숫자만 봐도 가짜인 줄 아는 것 */
const BIZ_예외 = new Set([
  /* 푸른노무법인 «우리» 번호 — 위임장·계산서 서식이 실제로 쓴다 */
  '312-81-03893', '312-81-52792',
  /* 한 숫자만 되풀이하거나 차례대로 센 것 — 사람이 봐도 가짜다 */
  '000-00-00000', '000-00-00001', '000-00-00002', '000-00-00003', '000-82-00000',
  '111-11-11111', '222-22-22222', '333-33-33333', '888-88-88888',
  '999-99-99999', '999-82-99999', '111-22-33333',
  '214-86-01234', '234-56-78901', '345-67-89012', '456-78-90123', '567-89-01234',
  '312-81-12345', '312-81-00003'
]);
const BIZ_고치는법 =
  '\n  고치는 법: 예시 번호는 «123-» 으로 시작하게 짓습니다.\n' +
  '    검산(bizNoOk)을 타는 자리라면 검사자리까지 맞춰야 합니다 —\n' +
  '      가중치 [1,3,7,1,3,7,1,3,5] 로 앞 아홉 자리를 곱해 더하고,\n' +
  '      아홉째 자리×5 의 «십의 자리»를 한 번 더 더한 뒤,\n' +
  '      (10 − 합%10) % 10 이 끝자리입니다.\n' +
  '    보기: 123-81-2001? → 앞 아홉 자리 합으로 끝자리를 구해 채웁니다.\n' +
  '  진짜 번호를 못 쓰는 까닭은 tests/no-real-client-data.test.js 머리에 있습니다.';

test('★★★ 사업자등록번호는 «123-» 으로 시작하는 예시뿐이다', () => {
  const 걸린것 = 훑기(BIZ, m =>
    (m[0].startsWith('123-') || BIZ_예외.has(m[0])) ? null : m[0]);
  assert.deepEqual(걸린것, [],
    '★★★ 실제 사업장을 가리킬 수 있는 사업자등록번호가 있습니다.' + BIZ_고치는법);
});

/* ══════ ② 주민등록번호 ════════════════════════════════════════════
   ⚠⚠ 이것 하나가 다른 모든 것보다 무겁다. 뒷자리는 «뻔한 가짜»여야 한다.
     앞 여섯 자리(생년월일)는 검사가 날짜를 읽는 데 쓰므로 자유롭게 둔다 —
     생년월일만으로는 사람이 특정되지 않는다. */
const RRN = /\b[0-9]{6}-([1-4][0-9]{6})\b/g;
const 뒷자리_예외 = new Set([
  '1234567', '2345678', '3456789',
  '1000000', '2000000', '3000000', '4000000',
  '1111111', '2222222', '3333333', '4444444',
  '2234567', '1111112'
]);
test('★★★ 주민등록번호 뒷자리는 «뻔한 가짜»여야 한다', () => {
  const 걸린것 = 훑기(RRN, m => 뒷자리_예외.has(m[1]) ? null : '뒷자리 ' + m[1]);
  assert.deepEqual(걸린것, [],
    '★★★ 주민등록번호 뒷자리가 진짜처럼 보입니다.\n' +
    '  고치는 법: 뒷자리를 1234567 · 2234567 · 2000000 처럼 «한눈에 가짜»로 바꾸십시오.\n' +
    '    첫 자리(성별·세기)만 맞추면 검사는 그대로 돕니다.\n' +
    '  ⚠ 여기에 새 뒷자리를 «예외로 더하지» 마십시오 — 그 순간 문이 열립니다.');
});

/* ══════ ③ 휴대전화 ════════════════════════════════════════════════
   가운데 네 자리가 뻔한 꼴이어야 한다. 사무실 유선(041-…)은 안 본다 —
   우리 번호와 공공기관 대표번호가 많아 헛걸림이 크다. */
const MOBILE = /\b01[016-9]-([0-9]{3,4})-[0-9]{4}\b/g;
const 가운데_예외 = /^(0000|1111|1200|2222|3333|4444|5555|6666|7777|8888|9999|1234|9876)$/;
test('★★ 휴대전화 가운데 네 자리는 «뻔한 가짜»여야 한다', () => {
  const 걸린것 = 훑기(MOBILE, m => 가운데_예외.test(m[1]) ? null : m[0]);
  assert.deepEqual(걸린것, [],
    '★★ 진짜처럼 보이는 휴대전화가 있습니다.\n' +
    '  고치는 법: 010-1111-2222 · 010-1200-0001 처럼 가운데를 뻔한 숫자로 바꾸십시오.\n' +
    '    한 검사 안에서 여러 사람을 갈라 봐야 하면 010-1200-0001 · 0002 … 로 세십시오.');
});

/* ══════ ④ 목업은 다시 두지 않는다 ═════════════════════════════════
   317장을 지운 까닭이 docs/mockups/README.md 에 있다. 새 목업을 같은 자리에
   쌓기 시작하면 같은 일이 되풀이된다 — 그림은 «지어낸 자료»로만 짓는다. */
test('★★ docs/mockups 에는 안내문과 그림 원본만 둔다', () => {
  const 목업 = 파일들.filter(f => f.startsWith('docs/mockups/'));
  const 허락 = 목업.filter(f => /\/README\.md$|\/art-[^/]*\.html$/.test(f));
  assert.deepEqual(목업.filter(f => !허락.includes(f)), [],
    '★★ docs/mockups 에 새 파일이 생겼습니다.\n' +
    '  까닭은 docs/mockups/README.md 에 있습니다 — 317장이 실제 화면을 떠 온 것이라 지웠습니다.\n' +
    '  목업이 필요하면 지어낸 자료(가나상사·홍길동·123-45-67890)로 짓고,\n' +
    '  결론은 status/ 기록에 글로 남기십시오.');
});
