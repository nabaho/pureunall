/* 판결문을 «푸른 양식으로» 간추린다 (대표 지시 2026-09-20 「판례전문도」)
   ═══════════════════════════════════════════════════════════════════════════
   앞선 지시 「판례등 전문보기는 판례정보를 그대로 넣지말고 푸른양식으로 정리해라」
   → 껍데기는 우리 얼굴이 되었지만 «속»은 법제처 원문 그대로였다.

   ■ 실측 (2026-09-20, 대법원 2018다296229)
     「판결 전문」 한 칸에 33,804자 — 쪽 높이 18,032px, 화면으로 열여덟 장.
     그런데 정작 «어떻게 됐나»(【주 문】 「상고를 기각한다」)는 그 덩이의
     250번째 글자에 묻혀 있었다. 바쁜 분은 결론을 못 찾고, 안 바쁜 분도 안 내린다.

   ■ 고친 길 — 법제처 판결문의 【 】 머리표로 갈라 다시 세운다
     주문(맨 위·판에 얹음) → 판시사항 → 판결요지 → 참조조문 → 원심판결 →
     사건 관계인 → 판결 이유(접어 둠)
     실측: 쪽 높이 18,032px → 2,593px. 펴면 18,173px 로 다 보인다.

   ■ 이 검사가 지키는 것
     ㉠ 주문이 «맨 위»다 — 결론이 먼저다
     ㉡ 가르면서 «한 글자도 안 버린다»
     ㉢ 못 가르면 예전처럼 통째로 — 법제처가 꼴을 바꿔도 내용을 안 잃는다
     ㉣ 접는 칸은 «판결 이유»뿐 — 판결요지·해석례 이유는 알맹이라 안 접는다
     ㉤ 두 화면(따로 연 쪽·그 자리에서 편 것)이 «같은 모양»이다 */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');

const 뿌리 = path.join(__dirname, '..');
const NF = require('../functions/news-full.js');
const NV = require('../functions/news-view.js');
const 보는쪽 = fs.readFileSync(path.join(뿌리, 'functions/news-view.js'), 'utf8');

/* 법제처가 실제로 내주는 꼴 그대로 — 머리표 안의 «빈칸»까지(【주 문】·【이 유】) */
const 전문 = [
  '【원고, 상고인】 ○○○노동조합 (소송대리인 법무법인 여는)',
  '【피고, 피상고인】 △△중공업 주식회사',
  '【원심판결】 부산고법 2018. 11. 14. 선고 2018나53149 판결',
  '【주 문】',
  '상고를 기각한다. 상고비용은 원고가 부담한다.',
  '【이 유】 상고이유를 판단한다.',
  '1. 사안의 개요 및 쟁점',
  '가. 사안의 개요'
].join('\n');

function 판례XML(속) {
  return '<PrecService>'
    + '<사건명><![CDATA[단체교섭청구의소]]></사건명>'
    + '<법원명>대법원</법원명><사건번호>2018다296229</사건번호>'
    + '<선고일자>20260521</선고일자>'
    + '<판시사항><![CDATA[사용자의 범위]]></판시사항>'
    + '<판결요지><![CDATA[종전 법리가 유지되어야 한다.]]></판결요지>'
    + '<참조조문><![CDATA[헌법 제33조 제1항]]></참조조문>'
    + '<판례내용><![CDATA[' + (속 == null ? 전문 : 속) + ']]></판례내용>'
    + '</PrecService>';
}

/* ═══ ㉠ 가르기 자체 ═══════════════════════════════════════════════════ */

test('★★★ 【주 문】의 «빈칸»을 넘어 결론을 꺼낸다', () => {
  const r = NF.전문가르기(전문);
  assert.ok(r.ok, '★★★ 못 갈랐다 — 결론이 3만 자 속에 묻힌 채로 나간다');
  assert.equal(r.주문, '상고를 기각한다. 상고비용은 원고가 부담한다.',
    '★★★ 주문을 잘못 꺼냈다: ' + JSON.stringify(r.주문));
  assert.match(r.원심판결, /부산고법 2018\. 11\. 14\./, '★ 원심판결을 못 꺼냈다');
  assert.match(r.이유, /^상고이유를 판단한다/, '★★ 이유를 못 꺼냈다');
  assert.match(r.이유, /사안의 개요/, '★★ 이유가 중간에 끊겼다');
});

test('★★★ 가르면서 «한 글자도 안 버린다»', () => {
  /* ⚠ 조용히 사라지는 글이 있으면 안 된다. 아는 머리표가 아니면 관계인에 모은다. */
  const r = NF.전문가르기(전문);
  assert.match(r.관계인, /○○○노동조합/, '★★★ 원고가 사라졌다');
  assert.match(r.관계인, /△△중공업/, '★★★ 피고가 사라졌다');
  /* 머리표 앞에 붙은 글도 안 버린다 */
  const r2 = NF.전문가르기('앞에 붙은 안내글\n' + 전문);
  assert.match(r2.관계인, /앞에 붙은 안내글/, '★★ 머리표 앞 글을 버렸다');
});

test('★★★ 「주문」이 없으면 «가르지 않는다» — 통째로 두는 편이 낫다', () => {
  /* ⚠ 법제처가 꼴을 바꾸거나 낯선 판결문이 오면 반쯤 가른 것보다 통째가 낫다. */
  assert.equal(NF.전문가르기('【이 유】 어쩌고').ok, false, '주문 없이 갈랐다');
  assert.equal(NF.전문가르기('머리표가 하나도 없는 글').ok, false, '머리표 없이 갈랐다');
  assert.equal(NF.전문가르기('').ok, false, '빈 글을 갈랐다');
  assert.equal(NF.전문가르기(null).ok, false, '빈 값을 갈랐다');
});

/* ═══ ㉡ 차례와 접기 ═══════════════════════════════════════════════════ */

test('★★★ 주문이 «맨 위»고 판결 이유가 «맨 뒤»다', () => {
  const r = NF.풀기('prec', 판례XML());
  assert.ok(r.ok, '못 풀었다');
  assert.deepEqual(r.칸들.map((k) => k.이름),
    ['주문', '판시사항', '판결요지', '참조조문', '원심판결', '사건 관계인', '판결 이유'],
    '★★★ 보는 차례가 어긋났다 — 결론이 먼저 와야 한다');
});

test('★★★ 접는 것은 «판결 이유»뿐이다 — 알맹이는 안 접는다', () => {
  const r = NF.풀기('prec', 판례XML());
  const 접힌것 = r.칸들.filter((k) => k.접기).map((k) => k.이름);
  assert.deepEqual(접힌것, ['판결 이유'],
    '★★★ 접는 칸이 잘못됐다 (' + 접힌것.join(',') + ') — 판결요지가 접히면 알맹이가 숨는다');
});

test('★★★ 해석례의 «이유»는 안 접는다 — 회답이 짧아 이것이 알맹이다', () => {
  /* 실측 2026-09-20: 회답 126자 · 이유 2,908자. 이유를 접으면 볼 것이 없어진다. */
  const xml = '<Expc><안건명><![CDATA[압류 제외 임금]]></안건명>'
    + '<해석기관명>법제처</해석기관명><안건번호>25-0001</안건번호><해석일자>20260101</해석일자>'
    + '<질의요지><![CDATA[무엇을 묻는다]]></질의요지>'
    + '<회답><![CDATA[이러하다]]></회답>'
    + '<이유><![CDATA[' + '가'.repeat(2908) + ']]></이유></Expc>';
  const r = NF.풀기('expc', xml);
  assert.ok(r.ok, '못 풀었다');
  assert.deepEqual(r.칸들.filter((k) => k.접기).map((k) => k.이름), [],
    '★★★ 해석례의 이유를 접었다 — 회답이 126자뿐인데 알맹이를 숨겼다');
});

test('★★ 못 가른 판결문은 «판결 전문» 한 칸으로, 접어서 낸다', () => {
  const r = NF.풀기('prec', 판례XML('머리표가 없는 옛 꼴의 판결문입니다.'));
  const 전 = r.칸들.find((k) => k.이름 === '판결 전문');
  assert.ok(전, '★★ 못 갈랐는데 내용이 사라졌다 — 물러설 자리가 없다');
  assert.equal(전.접기, true, '★★ 못 가른 덩이를 안 접었다 — 쪽이 열여덟 장이 된다');
  assert.match(전.글, /머리표가 없는 옛 꼴/, '★★ 내용이 바뀌었다');
});

/* ═══ ㉢ 쪽에 그리기 ═══════════════════════════════════════════════════ */

test('★★★ 쪽에서 주문은 «판에 얹고», 판결 이유는 <details> 로 접는다', () => {
  const r = NF.풀기('prec', 판례XML());
  const h = NF.쪽(r, 'https://www.law.go.kr/x?target=prec&ID=1');
  assert.match(h, /<div class="p key">[\s\S]*?상고를 기각한다/,
    '★★★ 주문이 판에 안 얹혔다 — 결론이 다른 글과 똑같이 보인다');
  assert.match(h, /<details class="fold"><summary>판결 이유/,
    '★★★ 판결 이유를 안 접었다');
  /* 판결요지는 «펼친 채»로 있어야 한다 — 접는 칸 밖에 있는지 본다 */
  assert.match(h.replace(/<details[\s\S]*?<\/details>/g, ''), /판결요지/,
    '★★★ 판결요지가 접힌 칸 안으로 들어갔다 — 읽으시라고 있는 칸이다');
  /* 접은 칸은 «얼마나 긴지» 미리 알린다 — 모르고 누르면 놀란다 */
  assert.match(h, /판결 이유[\s\S]{0,120}?\d{1,3}(,\d{3})*자/,
    '★★ 접은 칸의 글자 수를 안 적는다');
  /* ⚠ 자바스크립트 없이 열려야 한다 — 메일에서 새 탭으로 여신 분도 쓰신다 */
  assert.ok(h.indexOf('<script') < 0, '★★★ 쪽에 스크립트가 생겼다 — <details> 면 필요 없다');
});

test('★★ 접어도 «내용은 쪽 안에» 있다 — 눌렀을 때 다시 받아 오지 않는다', () => {
  const r = NF.풀기('prec', 판례XML());
  const h = NF.쪽(r, 'https://www.law.go.kr/x');
  assert.match(h, /사안의 개요/, '★★ 접힌 글이 쪽에서 빠졌다 — 펴도 볼 것이 없다');
});

test('★★★ 처음 보이는 것이 «크게» 줄었다', () => {
  /* 값을 못 박지 않는다 — 접힌 것을 뺀 쪽이 «전체의 절반 미만»이면 된다.
     실측 2026-09-20: 18,032px → 2,593px. */
  const r = NF.풀기('prec', 판례XML(전문 + '\n' + '가'.repeat(20000)));
  const h = NF.쪽(r, 'https://www.law.go.kr/x');
  const 펴짐 = h.replace(/<details[\s\S]*?<\/details>/g, '');
  assert.ok(펴짐.length * 2 < h.length,
    '★★★ 접었는데도 처음 보이는 것이 절반을 넘는다 (' + 펴짐.length + '/' + h.length + ')');
});

/* ═══ ㉤ 두 화면이 같은 모양 ═════════════════════════════════════════ */

test('★★★ 「그 자리에서 편 것」도 «같은 모양»이다', () => {
  /* ⚠⚠ 한쪽만 고치면 메일에서 새 탭으로 여신 분과 웹에서 펴신 분이
       «다른 것»을 보신다. 두 곳이 같은 칸들(NF.풀기)을 같은 모양으로 그려야 한다. */
  assert.match(보는쪽, /details class="fold"/,
    '★★★ 그 자리에서 펴는 쪽은 아직 안 접는다 — 거기서는 열여덟 장 그대로다');
  assert.match(보는쪽, /k\.이름==="주문"\?" key":""/,
    '★★★ 그 자리에서 펴는 쪽은 주문을 판에 안 얹는다');
  assert.match(보는쪽, /k\.접기\?/, '★★★ 접기 표를 안 본다');
  /* 꾸밈도 두 곳에 있어야 보인다 */
  assert.match(보는쪽, /\.full \.p\.key\{/, '★★ 주문 판의 꾸밈이 없다');
  assert.match(보는쪽, /\.full details\.fold\{/, '★★ 접는 칸의 꾸밈이 없다');
});

test('★★ 편지 쪽은 «건드리지 않았다» — 판례는 여전히 결과만 싣는다', () => {
  /* 대표 지시 2026-09-08 「간단하게 결과만 나오게」. 전문 쪽을 손봤다고
     편지에 판결 이유가 딸려 들어가면 편지가 다시 다섯 배가 된다. */
  const T = require('../js/pu-news-tpl.js');
  const C = require('../js/pu-news-core.js');
  const h = T.편지짓기({ 회차: C.회차('2026-09-14'), 우리글: '', 안: { case: [{
    갈래: '판례', 딱지: '[판례]', 제목: '어느 판례', 인용: '대법원 2018다296229',
    링크: 'https://www.law.go.kr/DRF/lawService.do?target=prec&type=HTML&ID=1' }] } },
  { 회사이름: '푸른노무법인' }, { 미리보기: true }).서식;
  assert.ok(h.indexOf('주 문') < 0 && h.indexOf('판결 이유') < 0,
    '★★ 편지에 판결문 속살이 들어왔다 — 편지는 결과만 싣는다');
});
