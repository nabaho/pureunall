'use strict';
/* 「이번 주 한마디」를 «저절로» 짓는다 · 노동뉴스가 통째로 사라지지 않게
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-20:
     「노동뉴스는 사라졌다. 그리고 이번주 한마디도 자동으로 작성되게 해야되는데
      왜 안되나 다시 확인해봐라」

   ⚠⚠ 2026-09-20 실측으로 두 가지가 드러났다:
     ① 우리글(한마디)이 "" 였다 — 저절로 짓는 자리가 «아예 없었다».
        AI 단추는 기사에만 있었고 한마디에는 없었다. 「안 되는」 것이 아니라 «없었다».
     ② 주간노동뉴스 5건이 담겼는데 «실릴 것 0» 이었다. 기사는 우리 말이 있어야
        편지에 나가는데 다섯 건 다 비어 있었다 — 그래서 꼭지가 통째로 빠졌다.
        화면은 「아직 안 씀 — 안 실림」이라 적어 두었지만, 손이 한 번 더 가야 했다.

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ① 한마디를 짓는 자리가 «있다» — 단추로도, 채울 때 저절로도
     ② 한마디는 «이 회차에 담긴 것»만 보고 쓴다 — 바깥 사실을 지어내지 않는다
     ③ 이미 쓰신 글은 «덮지 않는다» — 저절로 도는 것이 사람 글을 지우면 안 된다
     ④ 지은 것이 «AI 가 쓴 것»임을 화면이 밝힌다
     ⑤ 초안을 우리 말로 옮기는 것은 «사람이 누른다» — 말없이 실리지 않는다 */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const { stripComments } = require('./strip-comments');

const ROOT = path.join(__dirname, '..');
const 날글 = fs.readFileSync(path.join(ROOT, 'pu-news.html'), 'utf8').replace(/\r\n/g, '\n');
const news = stripComments(날글);
const B = require('../functions/news-brief.js');

const 함수 = (이름) => {
  const i = news.indexOf('function ' + 이름 + '(');
  assert.ok(i > 0, 이름 + ' 을 못 찾음');
  return news.slice(i, news.indexOf('\n}', i));
};

/* ══════════════════════════════════════════════════════════════════════════
   ① 한마디를 짓는 자리
   ══════════════════════════════════════════════════════════════════════════ */

test('★★★ 「이번 주 한마디」를 짓는 자리가 «있다»', () => {
  /* ⚠ 2026-09-20 까지 이런 자리가 아예 없었다. AI 단추는 기사에만 있었다. */
  assert.ok(/function 한마디초안짓기\(/.test(news),
    '★★★ 한마디를 짓는 자리가 없다 — 「자동으로」가 될 수 없다');
  assert.ok(/한마디초안짓기\(\)/.test(날글),
    '★★★ 손으로 부를 단추가 없다');
});

test('★★★ 채울 때 «저절로» 짓는다 — 대표가 또 한 번 누르지 않게', () => {
  /* ⚠ 단추만 두면 「자동으로」가 아니다. 「이 주치로 채우기」 한 번에 끝나야 한다. */
  const fn = 함수('자동담기');
  assert.ok(/한마디초안짓기\(/.test(fn),
    '★★★ 채우기가 한마디를 안 짓는다 — 단추를 또 눌러야 한다');
});

test('★★★ 이미 쓰신 글은 «덮지 않는다»', () => {
  /* ⚠⚠ 저절로 도는 것이 사람 글을 지우면, 공들여 쓰신 한마디가 소리 없이 사라진다.
       되돌릴 길도 없다 — 이것만은 반드시 막는다. */
  const fn = 함수('한마디초안짓기');
  assert.ok(/우리글/.test(fn) && /(trim\(\)|덮|이미)/.test(fn),
    '★★★ 이미 쓴 글이 있는지 보지 않는다');
});

test('★★★ 한마디는 «이 회차에 담긴 것»만 보고 쓴다 — 바깥 사실을 지어내지 않는다', () => {
  /* ⚠⚠ 법인 이름으로 143곳에 나가는 글이다. 담긴 것 밖의 숫자·날짜·전망을
       한 글자라도 지어내면, 그것이 우리 의견으로 읽힌다. */
  const fn = 함수('한마디초안짓기');
  assert.ok(/지어내|보태지|만들지/.test(fn),
    '★★★ 지어내지 말라는 말이 AI 지시에 없다');
  assert.ok(/d\.안|안\[/.test(fn),
    '★★★ 이 회차에 담긴 것을 안 보고 쓴다');
});

test('★★ 지은 것이 «AI 가 쓴 것»임을 화면이 밝힌다', () => {
  /* ⚠ 사람이 쓴 것과 기계가 쓴 것이 같아 보이면, 읽어 보지 않고 내보내게 된다. */
  assert.ok(/우리글초안/.test(news),
    '★★ 지은 글을 따로 적어 두지 않는다 — 무엇이 초안인지 알 길이 없다');
  assert.ok(/우리글초안/.test(함수('회차저장')),
    '★★ 저장할 때 그 표를 안 쓴다 — 새로 고치면 초안인지 아닌지 잊는다');
});

/* ══════════════════════════════════════════════════════════════════════════
   ② 초안을 우리 말로 — «사람이 누른다»
   ══════════════════════════════════════════════════════════════════════════ */

test('★★★ 초안을 우리 말로 옮기는 것은 «사람이 누른다»', () => {
  /* ⚠⚠ AI 초안이 저절로 우리 말이 되면, 기계가 쓴 글이 법인 이름으로 나간다.
       그 선을 넘지 않으면서 손은 한 번으로 줄인다 — 한 번에 모두 옮기는 단추. */
  assert.ok(/function 초안모두우리말\(/.test(news),
    '★★★ 초안을 한 번에 옮기는 단추가 없다 — 다섯 건이면 다섯 번 눌러야 한다');
  const fn = 함수('초안모두우리말');
  assert.ok(/confirm\(/.test(fn),
    '★★★ 묻지 않고 옮긴다 — 기계 글이 곧바로 편지로 간다');
});

test('★★★ 저절로 도는 자리는 AI 초안을 «우리 말로 바꾸지 않는다»', () => {
  /* ⚠⚠ 이 선이 무너지면 사람이 한 번도 안 읽은 문장이 143곳에 나간다.
       채우기는 «초안까지»다. */
  const fn = 함수('자동담기');
  assert.ok(!/우리말\s*=/.test(fn),
    '★★★ 채우기가 우리말을 바로 쓴다 — 사람이 안 읽은 글이 나간다');
});

/* ══════════════════════════════════════════════════════════════════════════
   ③ 거르개 — 실린 것을 보고 더한다
   ══════════════════════════════════════════════════════════════════════════ */

test('★★ 「포토에세이」·「인사동정」은 뉴스레터에 안 싣는다', () => {
  /* ⚠ 2026-09-20 실측: 다섯 자리 가운데 둘이 이것이었다 —
       「포토에세이│화물노동자의 ‘먹고사는 일’」, 「안전분야 인사동정(고용동부)」.
       사진 묶음과 인사 명단은 자문사가 챙길 소식이 아니고, 자리를 먹으면
       정작 실을 것이 밀린다. 「[인사]」를 뺀 것과 같은 까닭이다. */
  assert.equal(B.노동글인가('포토에세이│화물노동자의 ‘먹고사는 일’'), false);
  assert.equal(B.노동글인가('안전분야 인사동정(고용동부)'), false);
  /* ★ 진짜 소식은 그대로 걸려야 한다 — 거르개를 너무 넓히면 안 된다 */
  assert.equal(B.노동글인가('4년째 못 받은 임금 2천억원 “박영우 엄벌하라”'), true);
  assert.equal(B.노동글인가('인사노무관리 실무 개정 사항 안내'), true);
});
