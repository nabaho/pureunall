"use strict";
/* «마감 지난 공고»는 담지 않는다
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-13: 「마감지남 거럼」

   ⚠⚠ 실측 2026-09-13: 천안시 기업지원 후보 8건을 하나씩 열어 보니 «여덟 다 마감»이었다.
     5월 18일 · 6월 10일 · 6월 26일 · 7월 31일 · 8월 21일 · 8월 31일 · 9월 11일 …
     지자체 게시판은 지난 공고가 «첫 쪽에 그대로» 쌓여 있어서, 모으는 대로 담으면
     마감된 것만 60곳에 나간다. 「이 사람들 확인도 안 하는구나」가 된다.

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ① «신청·접수·모집» 기간만 본다 — 행사가 언제인지(파견기간·참가기간)는 마감이 아니다
     ② 여러 차수가 적혀 있으면 «가장 늦은 것»이 마감이다
     ③ 해가 안 적힌 날(9.29)도 읽는다
     ④★★★ «모르면 안 버린다» — 기간을 못 읽었다고 버리면 멀쩡한 자료가 조용히 사라진다
     ⑤ 오늘이 마감일이면 «아직 살아 있다» — 그날 18시까지인 곳이 많다

   ⚠ 인터넷을 두드리지 않는다 — 2026-09-13 에 실제로 읽어 온 글을 박아 둔다. */

const test = require("node:test");
const assert = require("node:assert");
const D = require("../functions/news-docs.js");
const R = require("../functions/news-region.js");

const 오늘 = Date.parse("2026-09-13T09:00:00+09:00");

/* ══════════════════════════════════════════════════════════════════════════
   ① 기한 읽기
   ══════════════════════════════════════════════════════════════════════════ */

test("★★ 「신청기간 2026.09.10 ~ 2026.09.17」을 읽는다 (기업마당 꼴)", () => {
  const 글 = "소관부처·지자체 중소벤처기업부 신청기간 2026.09.10 ~ 2026.09.17 사업개요 …";
  assert.equal(D.기한읽기(글, 오늘), "2026-09-17", "기업마당 신청기간을 못 읽는다");
  assert.equal(D.마감지났나(글, 오늘), false, "아직 열린 공고를 마감으로 본다");
});

test("★★ 「신청기간 : 2026. 8. 28.(금) 9:00 ~ 2026. 9. 11.(금) 18:00」을 읽는다 (지자체 꼴)", () => {
  const 글 = "- 신청기간 : 2026. 8. 28.(금) 9:00 ~ 2026. 9. 11.(금) 18:00 - 지원규모 : 4개사";
  assert.equal(D.기한읽기(글, 오늘), "2026-09-11");
  assert.equal(D.마감지났나(글, 오늘), true, "★★ 이틀 전 마감된 공고를 담는다");
});

test("★★★ 여러 «차수»가 적히면 가장 «늦은 것»이 마감이다", () => {
  /* ⚠⚠ 1차만 보고 버리면 2차로 아직 받는 공고를 잃는다. */
  const 글 = "신청기간 [1차] 2026. 8. 3.(월) ~ 8. 14.(금) 17:00까지"
    + " [2차] 2026. 8. 18.(화) ~ 8. 31.(월) 17:00까지 ※ 1차 모집 완료 시 추가모집 없음";
  assert.equal(D.기한읽기(글, 오늘), "2026-08-31", "차수를 다 안 본다");
  assert.equal(D.마감지났나(글, 오늘), true);
});

test("★★★ «행사 날짜»를 마감으로 잘못 읽지 않는다", () => {
  /* ⚠⚠ 여기가 알맹이다. 파견은 11월인데 모집은 8월에 끝났다.
       파견기간을 마감으로 읽으면 «끝난 공고»를 두 달이나 더 내보낸다. */
  const 글 = "3. 파견기간 : 2026. 11. 11.(수) ~ 11. 13.(금)"
    + " 4. 모집기간 : 2026. 8. 12.(수) ~ 8. 21.(금) 18:00까지";
  assert.equal(D.기한읽기(글, 오늘), "2026-08-21",
    "★★★ 파견기간(11월)을 마감으로 읽었다 — 끝난 공고가 계속 나간다");
  assert.equal(D.마감지났나(글, 오늘), true);
});

test("해가 «안 적힌» 날도 읽는다 — 「접수: 9.14(월)~9.29(화)」", () => {
  const 글 = "ㅇ 고용허가서 신청서 접수: 9.14(월)~9.29(화) ㅇ 고용허가서 발급: 10.19(월)~10.30(금)";
  assert.equal(D.기한읽기(글, 오늘), "2026-09-29", "해 없는 날을 못 읽는다");
  assert.equal(D.마감지났나(글, 오늘), false,
    "★ 이번 주부터 접수하는 공고를 마감으로 본다");
});

test("제목에 적힌 「[접수 : 5/18 (월) ]」도 읽는다", () => {
  const 글 = "2026년 천안시 중소기업 육성자금 추가접수 공고 [접수 : 5/18 (월) ]";
  assert.equal(D.마감지났나(글, 오늘), true, "제목에 적힌 접수일을 못 읽는다");
});

/* ══════════════════════════════════════════════════════════════════════════
   ② 모르면 안 버린다 · 오늘까지는 살아 있다
   ══════════════════════════════════════════════════════════════════════════ */

test("★★★ 기간을 «못 읽으면» 안 버린다 — 멀쩡한 자료가 조용히 사라진다", () => {
  /* ⚠⚠ 여기가 무너지면 파견법 매뉴얼·자율점검표처럼 «기한이 없는» 좋은 자료가
       통째로 사라진다. 그런데 화면에는 「모았다」로 뜬다 — 알아챌 길이 없다. */
  assert.equal(D.기한읽기("파견법 업무매뉴얼입니다. 첨부 220331 파견법 업무매뉴얼.pdf", 오늘), "",
    "없는 기한을 지어냈다");
  assert.equal(D.마감지났나("파견법 업무매뉴얼입니다.", 오늘), false,
    "★★★ 기한이 없는 자료를 버린다");
  assert.equal(D.마감지났나("", 오늘), false, "빈 글을 버린다");
  assert.equal(D.마감지났나(null, 오늘), false, "빈손을 버린다");
});

test("★ 오늘이 «마감일»이면 아직 살아 있다 — 그날 18시까지인 곳이 많다", () => {
  assert.equal(D.마감지났나("신청기간 2026.09.01 ~ 2026.09.13", 오늘), false,
    "★ 오늘 마감인 공고를 미리 버린다");
  assert.equal(D.마감지났나("신청기간 2026.09.01 ~ 2026.09.12", 오늘), true,
    "어제 마감된 공고를 담는다");
});

/* ══════════════════════════════════════════════════════════════════════════
   ③ 이어졌나 — 자료(기업마당)와 지역뉴스(천안시) 양쪽
   ══════════════════════════════════════════════════════════════════════════ */

test("★★ 자료를 만들 때 «마감 지난 것»은 아예 안 만든다", () => {
  const 지난것 = {
    샘: "bizinfo", 일련번호: "PBLN_1", 제목: "2026년 ○○ 지원사업 공고",
    등록일: "2026-08-01",
    설명: "신청기간 2026.08.01 ~ 2026.08.20 사업개요 …",
    파일들: [{ 주소: "https://www.bizinfo.go.kr/cmm/fms/fileDown.do?atchFileId=A", 이름: "공고문.hwp" }],
  };
  assert.equal(D.자료로만들기(지난것, { 오늘: 오늘 }), null,
    "★★ 마감 지난 지원사업을 자료로 만든다");
  const 살아있는것 = Object.assign({}, 지난것, {
    설명: "신청기간 2026.09.10 ~ 2026.09.17 사업개요 …" });
  assert.ok(D.자료로만들기(살아있는것, { 오늘: 오늘 }), "살아 있는 공고를 버린다");
});

test("자료에 «마감일»을 적어 둔다 — 화면이 「언제까지」를 말할 수 있게", () => {
  const it = D.자료로만들기({
    샘: "bizinfo", 일련번호: "PBLN_2", 제목: "○○ 지원사업 공고", 등록일: "2026-09-10",
    설명: "신청기간 2026.09.10 ~ 2026.09.17",
    파일들: [{ 주소: "https://www.bizinfo.go.kr/cmm/fms/fileDown.do?atchFileId=B", 이름: "가.hwp" }],
  }, { 오늘: 오늘 });
  assert.equal(it.마감일, "2026-09-17", "마감일을 안 적어 둔다");
});

test("★★ 지역뉴스도 «같은 자»로 잰다 — 두 곳이 다른 잣대를 가지면 안 된다", () => {
  assert.equal(typeof R.마감지났나, "function",
    "★★ 지역뉴스 쪽에 마감 재는 자가 없다");
  assert.equal(R.마감지났나("신청기간 : 2026. 8. 28.(금) ~ 2026. 9. 11.(금) 18:00", 오늘), true);
  assert.equal(R.마감지났나("파견법 업무매뉴얼입니다.", 오늘), false, "기한 없는 것을 버린다");
});

test("★ 기한을 «확인해야 하는» 샘이 그렇다고 적어 둔다", () => {
  /* ⚠ 목록에는 기간이 없다 — 상세를 열어야 안다. 모으는 쪽이 그것을 알아야
       상세를 열어 보고 거른다. 안 적어 두면 목록만 보고 그냥 담는다. */
  const 천안시 = R.출처들.find((x) => x.id === "cheonan-company");
  assert.ok(천안시, "천안시 출처가 없다");
  assert.equal(천안시.기한확인, true,
    "★ 기업지원 샘인데 기한을 확인하라고 안 적혀 있다");
});
