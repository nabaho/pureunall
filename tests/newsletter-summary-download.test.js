'use strict';
/* 요약 줄에 «내려받을 것이 있다»를 표시한다
   ═══════════════════════════════════════════════════════════════════════════
   대표 지시 2026-09-14: 「내려받기 다운로드 있을경우 이부분 표시해라
   그렇게 해야 클릭해서 찾는다.」

   ⚠ 요약판은 줄마다 «↗» 하나뿐이라, 어느 줄에 받을 파일이 딸려 있는지 알 수 없다.
     손님은 눌러 봐야 알고, 대개는 안 눌러 본다 — 공고문·서식이 그대로 묻힌다.

   ★ 여기서 못 박는 것은 «값»이 아니라 «규칙»이다:
     ① 파일이 있는 줄에만 표시가 붙는다 — 없는 줄에 붙으면 «거짓말»이다
     ② 표시는 «표시»일 뿐 — 요약 줄의 링크는 여전히 그 건의 자세히 보기 하나다
       (한 줄에 링크 둘을 두면 어느 것을 눌렀는지도, 어디로 가는지도 흐려진다)
     ③ 자세히 보기 쪽에는 진짜 「내려받기」 단추가 그대로 있다 */

const test = require('node:test');
const assert = require('node:assert');

const T = require('../js/pu-news-tpl.js');
const C = require('../js/pu-news-core.js');

const 회 = C.회차(new Date('2026-09-13T00:00:00Z'));
const 파일주소 = 'https://www.bizinfo.go.kr/cmm/fms/fileDown.do?atchFileId=FILE_000001';

/* ⚠ 요약판이라야 이 표시가 나온다. 요약판은 «자세히 보기»로 갈 자리가 있어야 켜지므로
     추적밑주소를 반드시 준다 — 없으면 편지짓기가 조용히 전문판으로 내려간다.
     (처음에 그것을 안 주고 검사를 돌려 「표시가 없다」로 붉었다.) */
function 편지(안) {
  return T.편지짓기(
    { 회차: 회, 상태: '초안', 안: 안, 우리글: '' },
    { 회사이름: '푸른노무법인', 추적밑주소: 'https://asia-northeast3-x.cloudfunctions.net' },
    { 요약: true, 미리보기: true });
}

const 받을것있는자료 = {
  갈래: '자료', 제목: '2026년 해외시장개척단 참가기업 모집',
  우리말: '중소벤처기업부가 «섬유» 기업의 유럽 판로를 지원합니다.',
  발행처: '중소벤처기업부', 기관: '중소벤처기업부',
  링크: 'https://www.bizinfo.go.kr/x', 파일: 파일주소, 확장자: 'hwp', 파일크기: 204800
};
const 받을것없는자료 = {
  갈래: '자료', 제목: '장관이 사업장을 찾았습니다',
  우리말: '장관이 사전 예고 없이 사업장을 찾았습니다.',
  발행처: '고용노동부', 기관: '고용노동부',
  링크: 'https://www.moel.go.kr/y'
};

/* ⚠⚠ 「내려받기」만 찾으면 «이빨이 없다» — 자료 카드의 진짜 단추에도 그 낱말이 있어서,
     요약에 표시를 하나도 안 붙여도 검사가 통과한다(처음에 실제로 그랬다).
   ★ 요약 표시는 «⬇ 가 앞», 진짜 단추는 «↓ 가 뒤»다. 생김새로 갈라 본다. */
const 표시 = /⬇\s*내려받기/;

test('★★★ 내려받을 것이 있는 줄에는 «표시»가 붙는다', () => {
  /* ⚠ 이것이 없으면 공고문·서식이 있는 줄과 없는 줄이 똑같이 보인다.
       손님은 눌러 봐야 알고, 대개 안 눌러 본다 — 그대로 묻힌다. */
  const 글 = 편지({ news: [], policy: [받을것있는자료], case: [], hr: [] }).서식;
  assert.ok(표시.test(글), '★★★ 내려받을 것이 있는데 요약에 표시가 없다');
});

test('★★★ 내려받을 것이 «없는» 줄에는 안 붙는다 — 없는 것을 있다고 하면 거짓말이다', () => {
  /* ⚠⚠ 표시만 보고 눌렀는데 받을 것이 없으면, 다음부터는 표시를 안 믿는다.
       한 번 못 믿게 되면 표시를 붙인 뜻이 통째로 없어진다. */
  const 글 = 편지({ news: [], policy: [받을것없는자료], case: [], hr: [] }).서식;
  assert.ok(!표시.test(글),
    '★★★ 파일이 없는데 표시가 붙었다 — 눌러도 받을 것이 없다');
});

test('★★★ 요약 줄의 «링크는 여전히 하나»다 — 표시가 링크가 되면 안 된다', () => {
  /* ⚠⚠ 한 줄에 링크가 둘이면 어느 것을 눌렀는지도, 어디로 가는지도 흐려진다.
       추적 목록도 한 건을 두 번 세게 된다.
     ★ 표시는 «여기 받을 것이 있다»만 말하고, 가는 곳은 그 건의 자세히 보기 하나다. */
  const 글 = 편지({ news: [], policy: [받을것있는자료], case: [], hr: [] }).서식;
  assert.ok(표시.test(글), '★★★ 요약 표시(⬇ 내려받기)가 없다');
  /* ⚠⚠ 요약 줄이 가는 곳은 그 건의 «자세히 보기» 하나다. 표시까지 파일로 걸면
       한 줄에 링크가 둘이 되어, 어느 것을 눌렀는지도 어디로 가는지도 흐려지고
       추적이 한 건을 두 번 센다. */
  const 몇번 = 글.split(파일주소).length - 1;
  assert.equal(몇번, 0,
    '★★★ 요약에 파일 주소가 ' + 몇번 + '번 박혔다 — 표시가 링크가 되었다');
  assert.ok(!/내려받기\s*↓/.test(글),
    '★★★ 요약에 «진짜 단추»가 들어왔다 — 요약은 한 줄짜리다');
});

test('★★★ 전문판의 «진짜 단추»는 그대로다 — 표시가 그것을 대신하지 않는다', () => {
  /* ★ 요약은 「여기 받을 것이 있다」만 말하고, 받는 것은 «자세히 보기» 쪽이다.
     ⚠ 표시를 붙이면서 진짜 단추를 잃으면, 표시를 보고 눌러 간 손님이 빈손으로 돌아온다. */
  const 글 = T.편지짓기(
    { 회차: 회, 상태: '초안', 안: { news: [], policy: [받을것있는자료], case: [], hr: [] } },
    { 회사이름: '푸른노무법인' }, { 요약: false, 미리보기: true }).서식;
  assert.ok(글.indexOf(파일주소) >= 0,
    '★★★ 진짜 파일 주소가 전문에서 사라졌다 — 받을 길이 없어진다');
  assert.ok(/내려받기\s*↓/.test(글), '★★★ 전문의 내려받기 단추가 사라졌다');
});

test('★ 표시는 «기사»에는 안 붙는다 — 남의 기사에는 우리가 줄 파일이 없다', () => {
  const 글 = 편지({
    news: [{ 갈래: '기사', 제목: '개정 노조법 시행 이후', 우리말: '우리 말입니다.',
      링크: 'https://www.labortoday.co.kr/a', 언론사: '매일노동뉴스' }],
    policy: [], case: [], hr: []
  }).서식;
  assert.ok(!표시.test(글), '★ 기사 줄에 내려받기 표시가 붙었다');
});

test('★★ 표시가 «여러 줄»일 때도 있는 줄에만 붙는다', () => {
  /* ⚠ 한 줄에만 대 보면, 「있으면 무조건 다 붙인다」로 짜 놓아도 통과한다. */
  const 글 = 편지({
    news: [], policy: [받을것있는자료, 받을것없는자료], case: [], hr: []
  }).서식;
  const 몇개 = (글.match(/⬇\s*내려받기/g) || []).length;
  assert.equal(몇개, 1,
    '★★ 표시가 ' + 몇개 + '개다 — 파일 있는 줄은 하나뿐인데 다 붙거나 안 붙었다');
});
