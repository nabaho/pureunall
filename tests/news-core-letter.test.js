test('★★★ 핵심판에 쓴 «모든 스타일 속성»은 발송기 허용 목록 안이다 — 미리보기엔 있고 메일엔 없는 꾸밈이 없다', () => {
  const 편 = 짓기(회차({ 핵심: 두장() }));
  const 시작 = 편.서식.indexOf('이번 주 꼭 알아야 할');
  const 끝 = 편.서식.indexOf('전체 소식 보기');
  assert.ok(시작 > 0 && 끝 > 시작, '핵심판 구간을 못 찾았다');
  const 구간 = 편.서식.slice(시작 - 600, 끝 + 200);
  const 스타일들 = (구간.match(/style="([^"]*)"/g) || []).map((s) => s.slice(7, -1));
  assert.ok(스타일들.length > 20, '스타일을 못 읽었다(찾는 그물이 헐겁다)');
  const 조각 = (s) => s.split(';').map((x) => x.trim()).filter(Boolean);
  스타일들.forEach((s) => {
    const 남음 = 조각(MS.cleanStyle(s));
    const 원래 = 조각(s);
    const 잃음 = 원래.filter((x) => 남음.indexOf(x) < 0);
    assert.deepStrictEqual(잃음, [], '발송기가 조용히 지우는 꾸밈이 있다 — 미리보기엔 보이고 실제 메일엔 없다: ' + 잃음.join(' / '));
  });
});

