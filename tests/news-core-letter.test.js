/* ═══ 인사 · 지역 자리 ═══ */

test('명절 인사와 «받는 곳별 지역 소식 자리»는 핵심판에서도 그대로다', () => {
  const 편 = T.편지짓기(회차({ 핵심: 두장(), 인사: { 제목: '풍성한 한가위 되십시오', 글: '고맙습니다.' } }), 설정, { 요약: false, 지역: '' });
  assert.ok(핵심판인가(편));
  assert.match(편.서식, /풍성한 한가위/, '인사가 사라졌다');
  assert.ok(편.서식.includes('{지역뉴스}'), '지역 소식 자리가 사라졌다 — 받는 곳별 소식이 안 끼워진다');
  assert.ok(편.본문.includes('{지역뉴스평문}'), '평문의 지역 소식 자리가 사라졌다');
});

