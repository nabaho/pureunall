test('★★ 실제 발송(추적)에서는 카드 링크와 «전체 소식 보기»가 추적 번호를 거친다', () => {
  const 편 = T.편지짓기(회차({ 핵심: 두장() }), 설정, { 요약: false, 지역: '' });
  assert.ok(핵심판인가(편));
  const 번호 = (편.서식.match(/newsClick\?i=[^"]*&(?:amp;)?n=(\d+)/g) || []);   /* HTML 속 & 는 &amp; 다 */
  assert.ok(번호.length >= 3, '추적 링크가 모자란다: ' + 번호.length);
  const 주소들 = 편.링크들.map((v) => (v && typeof v === 'object') ? v.주소 : v);
  assert.ok(주소들.indexOf('https://n.example/a2') >= 0, '카드의 원문 링크가 추적 목록에 없다');
  assert.ok(주소들.some((u) => /\/newsView\?i=/.test(u)), '전체 소식 보기(웹 전문) 주소가 추적 목록에 없다');
  assert.ok(!/href="https:\/\/n\.example\/a2"/.test(편.서식), '추적을 안 거치고 원문으로 곧장 간다');
});

test('★★ 카드 주소가 http(s) 가 아니면 안 쓰고 «전체 소식 보기»로 간다 — 카드는 남는다', () => {
  const 편 = 짓기(회차({ 핵심: [카드({ 링크: 'javascript:alert(1)' })] }));
  assert.ok(핵심판인가(편));
  assert.ok(!/javascript:/i.test(편.서식), '나쁜 주소가 편지에 실렸다');
  assert.match(편.서식, /newsView\?i=/, '갈 곳이 전체 소식 보기로 안 바뀌었다');
});

/* ═══ ㉥ 사람 글을 믿지 않는다 ═══ */

test('★★ 카드 글의 태그·중괄호는 글자로 나간다 — 편지를 못 뚫고, 대표님이 쓴 {주의} 가 조용히 안 사라진다', () => {
  const 편 = T.편지짓기(회차({ 핵심: [카드({ 제목: '<script>alert(1)</script> {주의}', 설명: '<b>굵게</b> {하나}', 할일: '"따옴표" & 확인' })] }), 설정, { 요약: false, 지역: '' });
  assert.ok(!/<script>alert/.test(편.서식), '태그가 그대로 실렸다');
  assert.ok(편.서식.includes('&lt;script&gt;'), '태그가 글자로 안 나간다');
  assert.ok(!/\{주의\}|\{하나\}/.test(편.서식.replace(/\{지역뉴스\}|\{추적열쇠\}/g, '')), '중괄호가 발송기 자리로 읽힌다 — 받는 분 편지에서 조용히 사라진다');
  assert.ok(편.서식.includes('&#123;주의&#125;'), '중괄호가 글자로 안 나간다');
  assert.ok(!/\{주의\}/.test(편.본문), '평문에 중괄호가 그대로 있다');
});

