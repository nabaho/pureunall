/* 안내문 — 자료만 올려도 «푸른이 보내는» 안내문이 된다 (대표 지시 2026-09-27)
   「안내문은 pdf 나 ppt 등 자료를 업로드 하면 푸른에서 보내는 것으로 하게 해달라」

   ■ 이 검사가 지키는 «규칙»
     ① 제목 + 자료만 있어도 편지가 만들어진다 (예전에는 요점·본문을 꼭 써야 했다)
     ② 쓴 말이 없으면 «푸른노무법인에서 … 보내 드립니다»가 들어간다 — 서식·평문 둘 다
     ③ 사람이 한 줄이라도 쓰면 그것이 이긴다 (기본말이 사람 글을 덮거나 곁들지 않는다)
     ④ 자료도 글도 없으면 여전히 안 만든다 — 빈 안내문은 안 나간다
     ⑤ 기본말도 중괄호 막기를 지난다 — 제목의 { } 가 발송기에 먹히지 않는다
     ⑥ 화면: 올리기가 «먼저», 안내문은 그다음 — 실패하면 빈 초안이 안 남는다
     ⑦ 화면이 받는 파일 종류가 올리개의 목록 안에 있다 (PDF·파워포인트는 반드시) */

const test = require('node:test');
const assert = require('node:assert');
const fs = require('node:fs');
const path = require('node:path');
const N = require('../js/pu-news-notice.js');
const MS = require('../functions/mail-send.js');
const { 주석걷기, 함수몸 } = require('./helpers/strip-comments.js');

const 화면 = 주석걷기(fs.readFileSync(path.join(__dirname, '..', 'pu-news.html'), 'utf8'));
const 설정 = { 회사이름: '푸른노무법인', 전화: '041-000-0000' };
const 자료 = { 이름: '2026 하반기 가나상사 교육 안내', 크기: 320000,
  주소: 'https://example.test/fn/newsView?file=' + 'a'.repeat(32) + '.pdf&n=x' };

test('★★★ 제목 + 자료만으로 안내문이 만들어진다', () => {
  const 편 = N.안내짓기({ 제목: '하반기 교육 안내', 첨부: [자료] }, 설정, {});
  assert.ok(편, '★★★ 자료만 올린 안내문을 안 만든다 — 파일 한 장 보내려고 글을 지어 넣어야 한다');
  assert.match(편.제목, /푸른노무법인 안내\] 하반기 교육 안내/, '제목 줄이 «푸른노무법인 안내»가 아니다');
  /* 받는 분이 실제로 보는 것 — 발송기를 지난 뒤에도 내려받기 단추가 산다 */
  const 씻 = MS.sanitizeHtml(편.서식);
  assert.ok(씻.indexOf('newsView?file=') >= 0, '★★ 내려받기 단추가 발송기에서 사라진다');
});

test('★★ 쓴 말이 없으면 «푸른노무법인에서 … 보내 드립니다» — 서식·평문 둘 다', () => {
  const 편 = N.안내짓기({ 제목: '하반기 교육 안내', 첨부: [자료] }, 설정, {});
  assert.match(편.서식, /푸른노무법인에서 「하반기 교육 안내」 자료를 보내 드립니다/,
    '★★ 누가·무엇을 보냈는지 말이 없다 — 파일만 덩그러니 오면 스팸으로 의심한다');
  assert.match(편.본문, /푸른노무법인에서 「하반기 교육 안내」 자료를 보내 드립니다/, '평문에 기본말이 없다');
  const 둘 = N.안내짓기({ 제목: '서식 모음', 첨부: [자료, 자료] }, 설정, {});
  assert.match(둘.서식, /자료 2건을 보내 드립니다/, '여러 건일 때 건수를 안 말한다');
  /* 회사 이름은 설정을 따른다 */
  const 딴 = N.안내짓기({ 제목: '안내', 첨부: [자료] }, { 회사이름: '가나노무법인' }, {});
  assert.match(딴.서식, /가나노무법인에서 「안내」/, '회사 이름을 설정에서 안 읽는다');
});

test('★★ 사람이 한 줄이라도 쓰면 그것이 이긴다', () => {
  const 본 = N.안내짓기({ 제목: '안내', 본문: '홍길동 님께 드리는 말씀입니다.', 첨부: [자료] }, 설정, {});
  assert.ok(본.서식.indexOf('보내 드립니다') < 0, '★★ 사람이 쓴 본문 옆에 기본말이 곁들었다');
  const 요 = N.안내짓기({ 제목: '안내', 요점: ['연차 사용 계획을 확인'], 첨부: [자료] }, 설정, {});
  assert.ok(요.서식.indexOf('보내 드립니다') < 0, '★ 요점을 썼는데 기본말이 끼었다');
});

test('★ 자료도 글도 없으면 여전히 안 만든다', () => {
  assert.strictEqual(N.안내짓기({ 제목: '안내' }, 설정, {}), null, '★ 빈 안내문이 만들어진다');
  assert.strictEqual(N.안내짓기({ 제목: '', 첨부: [자료] }, 설정, {}), null, '제목 없는 안내문이 만들어진다');
  /* 누를 수 없는 주소(https 아님)는 자료로 치지 않는다 */
  assert.strictEqual(N.안내짓기({ 제목: '안내', 첨부: [{ 이름: '가', 주소: 'javascript:x' }] }, 설정, {}), null,
    '★ 누를 수 없는 자료 하나로 안내문이 만들어진다');
});

test('★★ 기본말도 중괄호 막기를 지난다 — 제목의 { } 가 발송기에 먹히지 않는다', () => {
  const 편 = N.안내짓기({ 제목: '가나{상사} 안내', 첨부: [자료] }, 설정, {});
  const 기본말자리 = 편.서식.indexOf('보내 드립니다');
  const 앞 = 편.서식.slice(Math.max(0, 기본말자리 - 80), 기본말자리);
  assert.ok(앞.indexOf('{상사}') < 0, '★★ 서식 기본말에 날것 { } 가 남았다 — 발송기가 지운다');
  const i = 편.본문.indexOf('보내 드립니다');
  assert.ok(편.본문.slice(Math.max(0, i - 60), i).indexOf('{상사}') < 0, '★★ 평문 기본말에 날것 { } 가 남았다');
});

test('★★ 화면: 올리기가 «먼저», 안내문은 그다음 — 실패하면 빈 초안이 안 남는다', () => {
  const 몸 = 함수몸(화면, '자료로안내문');
  assert.ok(몸, '자료로안내문 이 없다');
  const i올 = 몸.indexOf('파일올리기('), i만 = 몸.indexOf('새안내문(');
  assert.ok(i올 > 0 && i만 > i올, '★★ 안내문을 먼저 만든다 — 올리기가 실패하면 빈 초안이 남는다');
  assert.match(몸.slice(i올, i만), /if\(!a\) return/, '★ 못 올렸는데도 안내문을 만든다');
  /* 두 번 눌러 두 장이 생기지 않게 */
  assert.match(몸, /App\.올리는중\) return/, '올리는 동안 또 누르면 두 장이 생긴다');
  assert.match(몸, /finally\{[^}]*App\.올리는중 = false/, '실패하면 단추가 «올리는 중»에 멈춘다');
});

test('★ 화면이 받는 파일 종류가 올리개의 목록 안에 있다 — PDF·파워포인트는 반드시', () => {
  const 목 = /const 안내파일끝들 = \[([^\]]*)\]/.exec(화면);
  assert.ok(목, '안내파일끝들 을 못 찾았다');
  const 끝들 = 목[1].match(/'([a-z0-9]+)'/g).map((s) => s.slice(1, -1));
  const 단추 = 화면.slice(화면.indexOf('자료로안내문(this.files[0])') - 400, 화면.indexOf('자료로안내문(this.files[0])'));
  const 받음 = /accept="([^"]+)"/.exec(단추);
  assert.ok(받음, '자료로 안내문 만들기 단추에 accept 가 없다');
  받음[1].split(',').map((s) => s.trim().replace(/^\./, '')).forEach(function (e) {
    const k = e === 'jpeg' ? 'jpg' : e;
    assert.ok(끝들.indexOf(k) >= 0, '★ 고를 수는 있는데 못 올리는 종류가 있다: ' + e);
  });
  ['pdf', 'ppt', 'pptx'].forEach(function (e) {
    assert.ok(받음[1].indexOf('.' + e) >= 0, '★ 대표 지시의 ' + e + ' 를 고를 수 없다');
  });
});

test('★★ 빈 안내문 화면 전체가 자료 놓는 자리이고 기본 메일 모양을 먼저 보여 준다', () => {
  assert.match(화면, /id="ntDrop"[^>]*ondrop="안내자료놓기\(event\)"/,
    '오른쪽 빈 화면에 파일을 끌어 놓을 수 없다');
  assert.match(화면, /function 안내자료놓기\([^)]+\)[\s\S]*dataTransfer[\s\S]*자료로안내문\(files\[0\]\)/,
    '놓은 파일이 기존의 안전한 올리기 길로 이어지지 않는다');
  assert.match(화면, /보내기 전 기본 디자인[\s\S]*id="ntDefaultPreview"/,
    '자료를 올리기 전에는 메일 디자인을 판단할 수 없다');
  assert.match(화면, /function 안내기본미리보기그리기\([^)]*\)[\s\S]*Notice\.안내짓기/,
    '기본 미리보기가 실제 안내문 서식을 쓰지 않는다');
});
