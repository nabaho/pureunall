/* 「전문 보기」 쪽도 «창(팝업)과 같은 옷»을 입는다 (대표 지시 2026-09-20)
   ═══════════════════════════════════════════════════════════════════════════
   「현재 팝업디자인이 정말 마음에 든다 이렇게 뉴스레터 화면 바꿔 줄수없나」

   ■ 창이 좋았던 까닭
     ① 갈색 머리띠가 «누가 보낸 것인지»를 먼저 말한다
     ② 흰 종이가 떠 있어 편지가 «한 장»으로 보인다
     ③ 꼬리띠가 «누구에게 물으면 되는지»를 끝에서 다시 말한다
     그 셋을 쪽에도 그대로 입힌다. 편지 «속»은 한 글자도 안 건드린다.

   ■ 이 검사가 지키는 것
     ㉠ 머리띠·꼬리띠가 있고, 회차 이름을 적는다
     ㉡ 편지 «속»은 손대지 않는다 — 담아 둔 전문이 그대로 들어간다
     ㉢ ⚠⚠ 종이에 overflow:hidden 을 걸지 않는다 — 걸면 차림표 틀고정이 죽는다
     ㉣ 폭은 «한 곳»에만 적는다
     ㉤ 창(팝업)은 그대로다 — 쪽에 옷을 입혔다고 창을 잃으면 안 된다 */

const test = require('node:test');
const assert = require('node:assert');

const NV = require('../functions/news-view.js');

const 전문 = '<table width="980" style="width:980px;background-color:#ffffff">'
  + '<tr data-stick="1"><td>차림표</td></tr>'
  + '<tr><td>편지 속입니다</td></tr></table>';
const 쪽 = NV.쪽('푸른노무법인 2026년 09월 3주차 주간뉴스레터 입니다.', 전문);

/* ⚠⚠ 창(#pop)에도 «똑같은 머리띠·꼬리띠»가 있다. 쪽 전체에서 찾으면 카드의 것을
     통째로 빼도 창의 것이 걸려 검사가 초록이 된다 — 2026-09-20 이빨 확인에서
     「꼬리띠 빼기」가 그렇게 벙어리였다. 카드 «안»만 잘라 놓고 본다. */
function 카드속(h) {
  const a = (h || 쪽).indexOf('<div id="card">');
  const b = (h || 쪽).indexOf('<div id="pop">');
  assert.ok(a >= 0 && b > a, '카드를 못 찾았다');
  return (h || 쪽).slice(a, b);
}
const 카드 = 카드속();

/* ═══ ㉠ 머리띠·꼬리띠 ═════════════════════════════════════════════════ */

test('★★★ 편지가 «떠 있는 흰 종이» 위에 얹힌다 — 머리띠와 꼬리띠가 있다', () => {
  assert.match(카드, /^<div id="card">[\s\S]{0,400}?class="hd"/,
    '★★★ 종이(#card)와 머리띠가 없다 — 창에서 좋았던 것이 안 왔다');
  assert.match(카드, /class="hd"[\s\S]{0,200}?PUREUN/, '★★ 머리띠에 PUREUN 이 없다');
  assert.match(카드, /class="ft"[\s\S]{0,200}?푸른노무법인/, '★★★ 꼬리띠가 없다');
  assert.match(카드, /class="ft"[\s\S]{0,300}?041-556-0035/,
    '★★ 꼬리띠에 «어디로 물으면 되는지»가 없다');
});

test('★★ 머리띠가 «어느 회차»인지 적는다', () => {
  assert.match(카드, /class="hd"[\s\S]{0,300}?2026년 09월 3주차/,
    '★★ 머리띠가 회차를 안 적는다 — 무엇을 보고 있는지 알 수 없다');
});

test('제목이 없어도 머리띠는 빈칸으로 두지 않는다', () => {
  /* ⚠ 값을 못 박지 않는다 — 꼬리제목() 이 무엇으로 물러서든 «비어 있지만 않으면» 된다. */
  const 머리 = /<div class="hd">[\s\S]*?<b>([\s\S]*?)<\/b>/.exec(카드속(NV.쪽('', 전문)));
  assert.ok(머리, '머리띠를 못 찾았다');
  assert.ok(머리[1].trim().length >= 2,
    '제목이 없을 때 머리띠가 텅 빈다: ' + JSON.stringify(머리[1]));
});

/* ═══ ㉡ 편지 속은 손대지 않는다 ═══════════════════════════════════════ */

test('★★★ 편지 «속»은 한 글자도 안 바뀐다', () => {
  /* ⚠ 담아 둔 전문은 «그때 나간 그대로»다. 껍데기를 바꾼다고 속을 다시 그리면
       지난 회차가 오늘 모양으로 바뀐다 — 그러면 「그때 무엇을 보냈나」를 잃는다. */
  assert.ok(쪽.indexOf(전문) >= 0, '★★★ 담아 둔 전문이 그대로 안 들어갔다');
});

/* ═══ ㉢ 틀고정을 죽이지 않는다 ════════════════════════════════════════ */

test('★★★ 종이에 overflow:hidden 을 «걸지 않는다» — 걸면 차림표가 안 따라온다', () => {
  /* ⚠⚠ 창(#pop .in)에는 overflow:hidden 이 있다. 그 줄을 같이 베껴 오면 안에 있는
       차림표의 position:sticky 가 통째로 죽는다 — 화면으로는 «그냥 안 따라올» 뿐이라
       한참 못 찾는다. 창에서 옷을 가져올 때 제일 쉽게 딸려 오는 줄이다. */
  const 종이 = (/#card\{[^}]*\}/.exec(쪽) || [''])[0];
  assert.ok(종이, '#card 꾸밈을 못 찾았다');
  assert.ok(!/overflow\s*:\s*hidden/.test(종이),
    '★★★ 종이에 overflow:hidden 이 걸렸다 — 차림표 틀고정이 죽는다');
  /* 틀고정 자체도 그대로 있어야 한다 */
  assert.match(쪽, /#wrap \[data-stick\]\{position:sticky/,
    '★★★ 차림표 틀고정이 사라졌다');
});

/* ═══ ㉣ 폭은 한 곳에만 ════════════════════════════════════════════════ */

test('★★ 폭은 «종이»가 갖고, 편지는 그것을 따라간다', () => {
  assert.match(쪽, /#card\{[^}]*width:980px/, '★★ 종이 폭이 편지 폭과 다르다');
  assert.match(쪽, /#wrap\{width:100%/,
    '★★ 편지에 폭을 또 적었다 — 두 곳에 적으면 한쪽만 바뀐다');
});

/* ═══ ㉤ 창은 그대로 ═══════════════════════════════════════════════════ */

test('★★★ 창(팝업)은 그대로 있다 — 쪽에 옷을 입혔다고 창을 잃지 않는다', () => {
  assert.match(쪽, /<div id="pop">/, '★★★ 창이 사라졌다');
  assert.match(쪽, /id="popb"/, '★★★ 창의 몸이 사라졌다');
  assert.match(쪽, /id="popx"/, '★★ 창 닫기 단추가 사라졌다');
  /* 창의 바탕 큰 글자는 창에만 있다 — 쪽에는 안 가져왔다(카드에 가려 안 보인다) */
  assert.match(쪽, /#pop \.bg \.w\{/, '★★ 창의 바탕 글자 꾸밈이 사라졌다');
  assert.ok(쪽.indexOf('id="pgbg"') < 0,
    '★ 쪽 바탕에 큰 글자를 도로 넣었다 — 카드(980px)가 그 글자(550px)를 늘 가린다');
});
