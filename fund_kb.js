  /* ── 검색·점수화·프롬프트·답변 합성 엔진 (PuFundAsk) ── */
  function norm(s) {
    return String(s || '').toLowerCase().replace(/\s+/g, '');
  }

  function ngrams(s, n) {
    var clean = norm(s).replace(/[^가-힣a-z0-9%]/g, '');
    var out = {};
    if (clean.length < n) {
      if (clean) out[clean] = true;
      return out;
    }
    for (var i = 0; i <= clean.length - n; i++) {
      out[clean.slice(i, i + n)] = true;
    }
    return out;
  }

  function scoreItem(item, qRaw) {
    var q = String(qRaw || '').trim();
    if (!q) return 0;
    var qLow = q.toLowerCase();
    var qNorm = norm(q);
    var score = 0;

    // 1. 문서번호·법조문 직접 일치 가중치
    var docNo = String(item.docNo || '').toLowerCase();
    var idLow = String(item.id || '').toLowerCase();
    if (docNo && qLow.indexOf(docNo) >= 0) score += 80;
    if (idLow && qLow.indexOf(idLow) >= 0) score += 80;

    // 문서번호 조각(예: 3866, 3961, 169호, 14호의2, 15호, 56호) 매칭
    var numTokens = q.match(/[0-9]{2,4}(?:호(?:의[0-9])?)?|[가-힣]+-[0-9]{3,4}/g) || [];
    for (var ni = 0; ni < numTokens.length; ni++) {
      var tk = numTokens[ni];
      if (docNo.indexOf(tk) >= 0 || String(item.law || '').indexOf(tk) >= 0 || String(item.title || '').indexOf(tk) >= 0) {
        score += 35;
      }
    }

    // 2. 태그 정확·부분 일치
    var tags = item.tags || [];
    for (var ti = 0; ti < tags.length; ti++) {
      var tg = norm(tags[ti]);
      if (!tg) continue;
      if (qNorm.indexOf(tg) >= 0) score += 22;
      else if (tg.length >= 3 && tg.indexOf(qNorm) >= 0 && qNorm.length >= 2) score += 14;
    }

    // 3. 어절(단어) 단위 매칭
    var words = qLow.split(/[\s,·/?!()[\]"']+/).filter(function (w) { return w.length >= 2; });
    var titleLow = String(item.title || '').toLowerCase();
    var qFieldLow = String(item.q || '').toLowerCase();
    var aFieldLow = String(item.a || '').toLowerCase();
    var lawLow = String(item.law || '').toLowerCase();
    var ptsLow = (item.points || []).join(' ').toLowerCase();

    for (var wi = 0; wi < words.length; wi++) {
      var w = words[wi];
      // 조사 제거 후보 (앞 2~4글자 어근)
      var roots = [w];
      var stripped = w.replace(/(은|는|이|가|을|를|의|에|에서|으로|로|과|와|도|만|까지|부터|인가요|할까요|하나요|인지|여부|대한|관련)$/, '');
      if (stripped.length >= 2 && stripped !== w) roots.push(stripped);

      for (var ri = 0; ri < roots.length; ri++) {
        var r = roots[ri];
        var weight = (ri === 0) ? 1.0 : 0.85;
        if (titleLow.indexOf(r) >= 0) score += Math.round(14 * weight);
        if (qFieldLow.indexOf(r) >= 0) score += Math.round(10 * weight);
        if (lawLow.indexOf(r) >= 0) score += Math.round(8 * weight);
        if (ptsLow.indexOf(r) >= 0) score += Math.round(7 * weight);
        if (aFieldLow.indexOf(r) >= 0) score += Math.round(5 * weight);
      }
    }

    // 4. 2-gram 유사도 보조 점수
    var qGrams = Object.keys(ngrams(q, 2));
    if (qGrams.length > 0) {
      var hay = norm(item.title + ' ' + item.q + ' ' + (item.tags || []).join(' ') + ' ' + item.docNo);
      var hit = 0;
      for (var gi = 0; gi < qGrams.length; gi++) {
        if (hay.indexOf(qGrams[gi]) >= 0) hit++;
      }
      score += Math.round((hit / qGrams.length) * 18);
    }

    return score;
  }

  function topicRoots(qRaw) {
    var qLow = String(qRaw || '').toLowerCase();
    var stop = {
      '기금': 1, '기금법인': 1, '근로복지기금': 1, '사내근로복지기금': 1, '공동근로복지기금': 1,
      '사내기금': 1, '공동기금': 1, '근로자': 1, '회사': 1, '기업': 1, '사업장': 1, '경우': 1,
      '가능': 1, '가능한지': 1, '여부': 1, '기준': 1, '무엇': 1, '어떻게': 1, '대한': 1, '관련': 1,
      '사업': 1, '지원사업': 1, '운영': 1, '법령': 1
    };
    var words = qLow.split(/[\s,·/?!()[\]"']+/).filter(function (w) { return w.length >= 2; });
    var out = [];
    for (var i = 0; i < words.length; i++) {
      var w = words[i].replace(/(은|는|이|가|을|를|의|에|에서|으로|로|과|와|도|만|까지|부터|인가요|할까요|하나요|되나요|있나요|인지|여부|대한|관련)$/, '');
      if (w.length >= 2 && !stop[w] && out.indexOf(w) < 0) out.push(w);
    }
    return out;
  }

  function extractRelevantChunk(item, question) {
    var aText = String((item && item.a) || '').trim();
    var pts = Array.isArray(item && item.points) ? item.points : [];
    var roots = topicRoots(question);
    if (!roots.length) {
      return { body: aText, points: pts.slice(0, 1) };
    }

    // 1. 번호 구분(① ② ③ ...)이 있는 경우 질문 핵심어와 일치하는 단락만 추출 (RAG 청크 필터링)
    var body = aText;
    var parts = aText.split(/(?=[①②③④⑤])/);
    if (parts.length >= 2) {
      var intro = '';
      var clauses = [];
      for (var pi = 0; pi < parts.length; pi++) {
        var seg = parts[pi].trim();
        if (!seg) continue;
        if (!/^[①②③④⑤]/.test(seg)) {
          intro = seg;
        } else {
          var sLow = seg.toLowerCase();
          var sc = 0;
          for (var ri = 0; ri < roots.length; ri++) {
            if (sLow.indexOf(roots[ri]) >= 0) sc += (roots[ri].length >= 3 ? 3 : 2);
          }
          clauses.push({ text: seg, score: sc });
        }
      }
      var maxSc = 0;
      for (var ci = 0; ci < clauses.length; ci++) {
        if (clauses[ci].score > maxSc) maxSc = clauses[ci].score;
      }
      if (maxSc > 0) {
        var pickedClauses = clauses
          .filter(function (c) { return c.score >= Math.max(2, Math.ceil(maxSc * 0.5)); })
          .map(function (c) { return c.text; });
        if (pickedClauses.length === 1) {
          body = pickedClauses[0].replace(/^[①②③④⑤]\s*/, '');
        } else if (pickedClauses.length > 0 && pickedClauses.length < clauses.length) {
          body = (intro ? intro + ' ' : '') + pickedClauses.join('\n');
        }
      }
    }

    // 2. 실무 체크포인트도 질문 핵심어와 가장 밀접한 항목만 추출 (불필요한 부가 항목 제외)
    var maxPtSc = 0;
    var scoredPts = pts.map(function (p) {
      var pLow = String(p || '').toLowerCase();
      var sc = 0;
      for (var rj = 0; rj < roots.length; rj++) {
        if (pLow.indexOf(roots[rj]) >= 0) sc += (roots[rj].length >= 3 ? 3 : 2);
      }
      if (sc > maxPtSc) maxPtSc = sc;
      return { text: p, score: sc };
    });
    var matchedPts = maxPtSc > 0
      ? scoredPts.filter(function (x) { return x.score >= Math.max(2, Math.ceil(maxPtSc * 0.6)); }).map(function (x) { return x.text; })
      : pts.slice(0, 1);
    var finalPts = matchedPts.slice(0, 2);

    return { body: body, points: finalPts };
  }

  function pick(kb, question, opts) {
    var list = Array.isArray(kb) ? kb : FUND_KB;
    var max = (opts && opts.max) || 3;
    var cat = (opts && opts.cat && opts.cat !== 'all') ? opts.cat : '';
    var q = String(question || '').trim();
    if (!q) {
      var base = cat ? list.filter(function (x) { return x.cat === cat; }) : list;
      return base.slice(0, max);
    }
    var scored = [];
    for (var i = 0; i < list.length; i++) {
      var it = list[i];
      var s = scoreItem(it, q);
      if (cat && it.cat === cat) s += 6;
      if (s > 0) scored.push({ item: it, score: s });
    }
    scored.sort(function (a, b) { return b.score - a.score; });
    if (!scored.length) return [];
    var topScore = scored[0].score;
    var minCut = Math.max(12, Math.floor(topScore * 0.45));
    var filtered = scored.filter(function (x) { return x.score >= minCut; });
    return filtered.slice(0, max).map(function (x) { return x.item; });
  }

  function filter(kb, cat, query) {
    var list = Array.isArray(kb) ? kb : FUND_KB;
    var c = (cat && cat !== 'all') ? cat : '';
    var q = String(query || '').trim();
    var pool = c ? list.filter(function (x) { return x.cat === c; }) : list.slice();
    if (!q) return pool;
    var scored = [];
    for (var i = 0; i < pool.length; i++) {
      var s = scoreItem(pool[i], q);
      if (s > 0) scored.push({ item: pool[i], score: s });
    }
    scored.sort(function (a, b) { return b.score - a.score; });
    return scored.map(function (x) { return x.item; });
  }

