/* ══════════════════════════════════════════════════════════════════════════
   메일 첨부가 «우리가 쓸 서류»인가 — PuDocPick (2026-10-05)
   ══════════════════════════════════════════════════════════════════════════
   대표 지시 「2걸음」 — 메일함에서 사업자등록증·명함·등록확인서·계약서로 보이는 것만
   저절로 모아 한꺼번에 사진첩으로 보내는 길의 «고르개».

   ★ 왜 규칙을 한 곳에 두나
     고르는 잣대가 화면에 흩어지면 「띠에 7건이라고 적혀 있는데 걸러 보면 5건」이 된다.
     목록 거르개·띠의 숫자·한꺼번에 보내기가 모두 이 함수 하나를 본다.

   ★ 무엇을 보고 고르나 (요금 0원 — 판독하지 않는다)
     ① 첨부 «이름»(거울의 an) ② 메일 «제목» ③ 파일 종류(확장자)
     이름이 아직 없는 옛 줄은 제목으로만 본다 — 메일함을 열수록 이름이 채워진다.

   ⚠ 왜 «안 고르는 말»이 먼저인가
     급여명세·청구서·세금계산서가 훨씬 많다(실측: 첨부 5,516통 중 제목에 급여·명세
     1,086통, 사업자등록증은 30통). 판독해도 쓸 데가 없고 AI 하루 몫만 축낸다.
     그래서 **먼저 빼고** 그 다음에 고른다.

   ⚠ 이것은 «후보»다 — 사람이 보고 누른다. 기계가 기업정보함을 바로 고치지 않는다.
   ══════════════════════════════════════════════════════════════════════════ */
(function (글로벌) {
  'use strict';

  /* 갈래 — 앞에 있는 것이 먼저 걸린다(사업자등록증이 계약서보다 앞).
     ⚠ 쓸모가 둘로 갈린다. 실제 메일을 세어 보고 나눴다(첨부 5,552통 기준):
       · '기업정보함' — 사진첩이 판독해 업체·사람 칸을 채운다. 사업자등록증 67 · 명함 1
       · '계약서길'   — 계약서 231통. **이미 더 좋은 길이 있다**(첨부 줄의 「→ 기업별
         계약서」가 회사·종류·날짜를 확인하고 🔒 서명본으로 담는다). 사진첩으로 보내면
         판독 몫만 쓰고 그 자리에 안 들어간다. 그래서 «후보로 보여는 주되»
         한꺼번에 보내기에서는 뺀다. */
  var 갈래들 = [
    { 이름: '사업자등록증', 쓸모: '기업정보함', 말: /사업자\s*등록증|사업자등록증/ },
    { 이름: '등록확인서',   쓸모: '기업정보함', 말: /등록\s*확인서|사업자\s*확인서|사실\s*증명/ },
    { 이름: '명함',         쓸모: '기업정보함', 말: /명\s*함|名銜/ },
    { 이름: '계약서',       쓸모: '계약서길',   말: /계약서|자문\s*계약|고문\s*계약|위촉|약정서/ },
  ];
  function 쓸모of(갈래) {
    for (var i = 0; i < 갈래들.length; i++) if (갈래들[i].이름 === 갈래) return 갈래들[i].쓸모;
    return '';
  }

  /* ⚠ 이 말이 들어 있으면 «서류 후보가 아니다» — 갈래보다 먼저 본다.
       「급여계약서」처럼 둘 다 든 것은 안 고른다(급여 쪽이 압도적으로 많다). */
  var 뺄말 = /급여|임금|명세|월급|상여|연말정산|청구|세금계산서|계산서|영수증|이체|입금|견적|공고|입찰|뉴스레터|소식지|안내문|설문|초대|광고|결제|요금|고지서|신용카드|보험료|납부/;

  /* 사진첩이 받아 판독할 수 있는 것만 — 그림과 PDF.
     ⚠ 엑셀·한글은 사진첩이 글자를 읽어 주지 못한다(한글 원본은 따로 보관하는 길이 있다). */
  var 되는확장자 = /\.(jpe?g|png|gif|bmp|webp|heic|heif|tiff?|pdf)$/i;

  function 말고르기(글) {
    return String(글 == null ? '' : 글);
  }

  /* 첨부 이름 하나가 서류로 보이는가 — 보이면 갈래, 아니면 '' */
  function 이름갈래(이름) {
    var s = 말고르기(이름);
    if (!s) return '';
    if (!되는확장자.test(s)) return '';
    if (뺄말.test(s)) return '';
    for (var i = 0; i < 갈래들.length; i++) if (갈래들[i].말.test(s)) return 갈래들[i].이름;
    return '';
  }

  /* 제목이 서류로 보이는가 — 이름이 아직 없을 때 쓰는 «둘째 잣대» */
  function 제목갈래(제목) {
    var s = 말고르기(제목);
    if (!s) return '';
    if (뺄말.test(s)) return '';
    for (var i = 0; i < 갈래들.length; i++) if (갈래들[i].말.test(s)) return 갈래들[i].이름;
    return '';
  }

  /* ── 메일 한 줄을 본다 ──
     줄(v)은 거울이 담아 둔 그대로다: a(첨부 수) · s(제목) · an(첨부 이름들).
     돌려주는 것:
       { 서류: true/false, 갈래: '사업자등록증', 어디서: '이름'|'제목', 이름: '사업자등록증.pdf' }
     ⚠ 첨부가 없으면 아무리 제목이 그럴듯해도 후보가 아니다 — 보낼 것이 없다. */
  function 보기(줄) {
    var v = 줄 || {};
    var 첨부수 = Number(v.a || 0);
    if (!첨부수) return { 서류: false, 갈래: '', 쓸모: '', 어디서: '', 이름: '' };

    var 이름들 = [];
    if (Array.isArray(v.an)) 이름들 = v.an;
    else if (v.an && typeof v.an === 'object') 이름들 = Object.keys(v.an).map(function (k) { return v.an[k]; });

    for (var i = 0; i < 이름들.length; i++) {
      var g = 이름갈래(이름들[i]);
      if (g) return { 서류: true, 갈래: g, 쓸모: 쓸모of(g), 어디서: '이름', 이름: 말고르기(이름들[i]) };
    }
    /* 이름이 «아직 없는» 옛 줄만 제목으로 본다 — 이름이 있는데 안 걸린 것은
       그 이름들이 서류가 아니라는 뜻이다(제목에 「계약」이 있어도 붙은 것은 청구서다). */
    if (!이름들.length) {
      var t = 제목갈래(v.s);
      if (t) return { 서류: true, 갈래: t, 쓸모: 쓸모of(t), 어디서: '제목', 이름: '' };
    }
    return { 서류: false, 갈래: '', 쓸모: '', 어디서: '', 이름: '' };
  }

  function 서류인가(줄) { return !!보기(줄).서류; }

  /* 사진첩으로 «한꺼번에» 보낼 값어치가 있는 것 — 판독이 기업정보함으로 이어지는 갈래만.
     계약서는 후보로 보여는 주되 여기서는 뺀다(「→ 기업별 계약서」가 더 맞는 길이다). */
  function 보낼만한가(줄) { return 보기(줄).쓸모 === '기업정보함'; }

  /* 한 번에 보내는 수 — 사진첩 자동 판독이 한 번에 20장이라 그 안에 들어간다.
     ⚠ 더 늘리려면 사진첩의 AUTO_READ_MAX 부터 본다. 넘기면 남은 것은 다음에 열 때
       읽히는데, 사람은 「판독이 안 됐다」고 본다. */
  var 한번에 = 10;

  글로벌.PuDocPick = {
    보기: 보기, 서류인가: 서류인가, 보낼만한가: 보낼만한가,
    이름갈래: 이름갈래, 제목갈래: 제목갈래,
    갈래들: 갈래들, 뺄말: 뺄말, 되는확장자: 되는확장자, 한번에: 한번에,
  };
  if (typeof module !== 'undefined' && module.exports) module.exports = 글로벌.PuDocPick;
})(typeof window !== 'undefined' ? window : globalThis);
