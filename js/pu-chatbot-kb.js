  function parseReply(raw, picked, validAppKeys) {
    var validIds = {};
    (picked || []).forEach(function (x) { if (x && x.id) validIds[x.id] = true; });
    var validFlows = {};
    PORTAL_FLOWS.forEach(function (f) { validFlows[f.id] = true; });

    var appAllow = null;
    if (Array.isArray(validAppKeys)) {
      appAllow = {};
      validAppKeys.forEach(function (k) { appAllow[k] = true; });
    }

    var txt = String(raw || '').trim();
    if (!txt) return localAnswer(picked, '');

    var cleanTxt = txt.replace(/^```(?:json)?\s*|\s*```$/gi, '').trim();
    var a = cleanTxt.indexOf('{'), b = cleanTxt.lastIndexOf('}');
    if (a >= 0 && b > a) {
      try {
        var obj = JSON.parse(cleanTxt.slice(a, b + 1));
        if (obj && typeof obj.answer === 'string' && obj.answer.trim()) {
          var cites = Array.isArray(obj.cites)
            ? obj.cites.filter(function (id) { return !!validIds[id]; }).slice(0, 2)
            : [];
          if (!cites.length && picked && picked.length) cites = [picked[0].id];

          var apps = Array.isArray(obj.apps)
            ? obj.apps.filter(function (k) { return typeof k === 'string' && (!appAllow || !!appAllow[k]); }).slice(0, 4)
            : [];
          if (!apps.length && picked && picked.length) {
            apps = collectApps(picked).filter(function (k) { return !appAllow || !!appAllow[k]; });
          }

          var flowId = (typeof obj.flowId === 'string' && validFlows[obj.flowId])
            ? obj.flowId
            : inferFlowId(picked, '');

          var followUps = Array.isArray(obj.followUps)
            ? obj.followUps
                .filter(function (s) { return typeof s === 'string' && s.trim().length >= 4; })
                .map(function (s) { return s.trim().slice(0, 70); })
                .slice(0, 3)
            : [];
          if (!followUps.length) followUps = defaultFollowUps(picked);

          return {
            answer: obj.answer.trim(),
            cites: cites,
            apps: apps,
            flowId: flowId,
            followUps: followUps,
            none: false,
            mode: 'ai'
          };
        }
        if (obj && typeof obj === 'object') return localAnswer(picked, '');
      } catch (_) {}
    }

    return {
      answer: cleanTxt,
      cites: (picked || []).slice(0, 2).map(function (x) { return x.id; }),
      apps: collectApps(picked).filter(function (k) { return !appAllow || !!appAllow[k]; }),
      flowId: inferFlowId(picked, ''),
      followUps: defaultFollowUps(picked),
      none: false,
      mode: 'ai'
    };
  }

