  function maskPersonal(text) {
    var out = String(text == null ? '' : text)
      .replace(/[\u0000-\u0008\u000b\u000c\u000e-\u001f\u007f]/g, '')
      .replace(/<{3,}|>{3,}/g, '')
      .replace(/\r\n?/g, '\n')
      .trim()
      .slice(0, 2000);
    var kinds = [];
    /* js/pu-rrn-mask.js 가 함께 실려 있으면 그 지우개도 먼저 태운다 */
    if (root && root.PuRrnMask && typeof root.PuRrnMask.maskRrnInText === 'function') {
      var rrnRes = root.PuRrnMask.maskRrnInText(out);
      if (rrnRes && rrnRes.count > 0) {
        out = rrnRes.text;
        kinds.push('주민번호');
      }
    }
    PII_MASKS.forEach(function (m) {
      var hit = false;
      out = out.replace(m.re, function (_, g1) {
        hit = true;
        return m.to.indexOf('$1') >= 0 ? m.to.replace('$1', g1 || '') : m.to;
      });
      if (hit && kinds.indexOf(m.kind) < 0) kinds.push(m.kind);
    });
    return { text: out, kinds: kinds };
  }

