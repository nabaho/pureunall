  function gramsOf(s) {
    var out = {};
    tokensOf(s).forEach(function (w) {
      for (var i = 0; i + 1 < w.length; i++) {
        var g = w.substr(i, 2);
        if (!STOP_GRAMS[g]) out[g] = 1;
      }
    });
    return Object.keys(out);
  }

  function scoreEntry(it, rawQ) {
    var q = String(rawQ || '').trim();
    if (!q) return 0;
    var eq = expandQuery(q).toLowerCase();
    var score = 0;

    /* 기금 항목이고 PuFundAsk.scoreItem 이 있으면 전문 기금 점수도 반영 */
    if (it.cat === 'fund' && it._rawFundItem && root && root.PuFundAsk && typeof root.PuFundAsk.scoreItem === 'function') {
      var fs = root.PuFundAsk.scoreItem(it._rawFundItem, q);
      if (fs > 0) score += Math.min(48, Math.round(fs * 0.9));
    }

    var idLow = String(it.id || '').toLowerCase();
    var docLow = String(it.docNo || '').toLowerCase();
    var titleLow = String(it.title || '').toLowerCase();
    var qLow = String(it.q || '').toLowerCase();
    var lawLow = String(it.law || '').toLowerCase();
    var aLow = String(it.a || '').toLowerCase();
    var ptsLow = (it.points || []).join(' ').toLowerCase();
    var tags = (it.tags || []).map(function (t) { return String(t || '').toLowerCase(); });

    if (idLow && eq.indexOf(idLow) >= 0) score += 60;
    if (docLow && docLow.length >= 4 && eq.indexOf(docLow) >= 0) score += 40;

    tags.forEach(function (tg) {
      if (!tg) return;
      var tgNoSpace = tg.replace(/\s+/g, '');
      var eqNoSpace = eq.replace(/\s+/g, '');
      if (tgNoSpace.length >= 2 && eqNoSpace.indexOf(tgNoSpace) >= 0) {
        score += 18 + Math.min(10, tgNoSpace.length * 2);
      }
    });

    tokensOf(eq).forEach(function (tk) {
      if (tk.length < 2 || STOP_GRAMS[tk]) return;
      if (tags.some(function (tg) { return tg.indexOf(tk) >= 0; })) score += 10;
      if (titleLow.indexOf(tk) >= 0) score += 9;
      if (qLow.indexOf(tk) >= 0) score += 6;
      if (lawLow.indexOf(tk) >= 0) score += 5;
      if (aLow.indexOf(tk) >= 0) score += 3;
      if (ptsLow.indexOf(tk) >= 0) score += 2;
    });

    gramsOf(eq).forEach(function (g) {
      if (titleLow.indexOf(g) >= 0) score += 3;
      else if (qLow.indexOf(g) >= 0) score += 2;
      else if (aLow.indexOf(g) >= 0) score += 1;
    });

    /* 기금 고유 키워드가 있을 때 기금 항목 가중, 시스템 위치 질문일 때 시스템 항목 가중 */
    if (/기금|출연|예규\s*제?169|복지공단|기본재산|고유목적사업준비금/.test(q) && it.cat === 'fund') score += 12;
    if (/어디서|어느\s*앱|무슨\s*앱|타일|화면|포털|사용법|열기|메뉴/.test(q) && it.cat === 'system') score += 14;
    if (/장려금|지원금|바우처|고용유지|청년일자리|계속고용|워라밸/.test(q) && it.cat === 'govaid') score += 10;
    if (/근로기준법|연차|주휴|통상임금|평균임금|퇴직금|부당해고|괴롭힘|근로계약서|취업규칙/.test(q) && it.cat === 'labor') score += 10;

    return score;
  }

  function extractChunk(it, question) {
    if (it && it.cat === 'fund' && it._rawFundItem && root && root.PuFundAsk && typeof root.PuFundAsk.extractRelevantChunk === 'function') {
      return root.PuFundAsk.extractRelevantChunk(it._rawFundItem, question);
    }
    return {
      body: String((it && it.a) || '').trim(),
      points: ((it && it.points) || []).slice(0, 3)
    };
  }

  /* ── 상위 관련 항목 추출 (RAG Retrieval) ── */
  function pick(question, opts) {
    opts = opts || {};
    var max = opts.max || 3;
    var cat = (opts.cat && opts.cat !== 'all') ? opts.cat : '';
    var list = allItems(opts.fundKb);
    var pool = cat ? list.filter(function (x) { return x.cat === cat; }) : list;
    var q = String(question || '').trim();
    if (!q) return pool.slice(0, max);

    var scored = [];
    for (var i = 0; i < pool.length; i++) {
      var s = scoreEntry(pool[i], q);
      if (s > 0) scored.push({ item: pool[i], score: s });
    }
    scored.sort(function (a, b) { return b.score - a.score; });
    if (!scored.length) return [];
    var top = scored[0].score;
    var cut = Math.max(10, Math.floor(top * 0.42));
    return scored.filter(function (x) { return x.score >= cut; }).slice(0, max).map(function (x) { return x.item; });
  }

  /* ── 사전 검색 필터 ── */
  function filter(cat, query, opts) {
    opts = opts || {};
    var c = (cat && cat !== 'all') ? cat : '';
    var list = allItems(opts.fundKb);
    var pool = c ? list.filter(function (x) { return x.cat === c; }) : list;
    var q = String(query || '').trim();
    if (!q) return pool;
    var scored = [];
    for (var i = 0; i < pool.length; i++) {
      var s = scoreEntry(pool[i], q);
      if (s > 0) scored.push({ item: pool[i], score: s });
    }
    scored.sort(function (a, b) { return b.score - a.score; });
    return scored.map(function (x) { return x.item; });
  }

  function collectApps(items) {
    var out = [];
    (items || []).forEach(function (it) {
      (it && it.apps || []).forEach(function (k) {
        if (k && out.indexOf(k) < 0) out.push(k);
      });
    });
    return out.slice(0, 3);
  }

  /* ── 로컬 즉시 답변 (AI 대기 전 또는 오프라인·한도 초과 시에도 정확한 근거 답변 제공) ── */
  function localAnswer(picked, question) {
    if (!picked || !picked.length) {
      return {
        answer: '내장 사전에서 직접 일치하는 항목을 찾지 못했습니다. AI 연결 시 질문을 바탕으로 답변을 생성하며, 더 정확한 검색을 위해 핵심 키워드(예: 업체등록, 사진첩 판독, 연차촉진, 통상임금, 청년일자리도약장려금, 기금 감사 겸직 등)로 물어봐 주세요.',
        cites: [],
        apps: [],
        none: true,
        mode: 'local'
      };
    }
    var top = picked[0];
    var ch = extractChunk(top, question);
    var lines = [ch.body];
    if (ch.points && ch.points.length) {
      lines.push('');
      for (var i = 0; i < ch.points.length; i++) {
        lines.push('• ' + ch.points[i]);
      }
    }
    lines.push('');
    lines.push('📌 근거/안내: ' + top.law + (top.docNo ? ' (' + top.docNo + ')' : ''));
    return {
      answer: lines.join('\n'),
      cites: [top.id],
      apps: collectApps([top]),
      none: false,
      mode: 'local'
    };
  }

