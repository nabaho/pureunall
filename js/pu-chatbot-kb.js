    if (/어디서|어느\s*앱|무슨\s*앱|타일|화면|포털|사용법|열기|메뉴|연결도|연동|의뢰인\s*업무|자료함|영업관리|내부관리/.test(q) && it.cat === 'system') score += 16;
    if (/장려금|지원금|바우처|고용유지|청년일자리|계속고용|워라밸/.test(q) && !/어디서|연결도/.test(q) && it.cat === 'govaid') score += 10;
